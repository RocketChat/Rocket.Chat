// Regenerates src/code/highlightLanguages.ts from the installed highlight.js; run it after upgrading highlight.js.
const fs = require('fs');
const path = require('path');

const hljs = require('highlight.js');

const toArray = (value) => {
	if (Array.isArray(value)) {
		return value;
	}
	return value ? [value] : [];
};

const collectSubLanguages = (mode, seen, found) => {
	if (!mode || typeof mode !== 'object' || seen.has(mode)) {
		return;
	}
	seen.add(mode);
	toArray(mode.subLanguage).forEach((language) => found.add(language));
	Object.values(mode).forEach((value) => toArray(value).forEach((child) => collectSubLanguages(child, seen, found)));
};

const names = hljs.listLanguages().sort();
const aliases = {};
const dependencies = {};

for (const name of names) {
	const language = hljs.getLanguage(name);
	const found = new Set();
	collectSubLanguages(language, new Set(), found);
	found.delete(name);
	if (found.size) {
		dependencies[name] = [...found].sort();
	}
	for (const alias of language.aliases || []) {
		if (!names.includes(alias) && !aliases[alias]) {
			aliases[alias] = name;
		}
	}
}

const lines = [
	'// Generated by scripts/generate-highlight-languages.cjs; do not edit by hand.',
	"import type { LanguageFn } from 'highlight.js';",
	'',
	'type LanguageModule = { default: LanguageFn };',
	'',
	'export const languageLoaders: Record<string, () => Promise<LanguageModule>> = {',
	...names.map((name) => `\t'${name}': () => import('highlight.js/lib/languages/${name}'),`),
	'};',
	'',
	'export const languageAliases: Record<string, string> = {',
	...Object.keys(aliases)
		.sort()
		.map((alias) => `\t'${alias}': '${aliases[alias]}',`),
	'};',
	'',
	'export const languageDependencies: Record<string, string[]> = {',
	...Object.keys(dependencies)
		.sort()
		.map((name) => `\t'${name}': [${dependencies[name].map((dependency) => `'${dependency}'`).join(', ')}],`),
	'};',
	'',
];

fs.writeFileSync(path.join(__dirname, '../src/code/highlightLanguages.ts'), lines.join('\n'));
