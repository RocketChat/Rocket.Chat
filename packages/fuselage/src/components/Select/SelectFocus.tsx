import { styled, Text } from '@tamagui/web';
import type { ReactNode, Ref } from 'react';

import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { pickWebPressHandlers } from '../../helpers/pickAttributes';
import { prependClassName } from '../../helpers/prependClassName';
import type { ButtonActionAttributes, ButtonRef } from '../../types/ElementAttributes';

export type SelectFocusProps = Omit<ButtonActionAttributes, 'ref'> & {
	/** An anchor is a button here and an input in the filtered selects, so its ref is typed for both. */
	ref?: Ref<Element>;
	/** Comes after the chips of a multiple select, whatever its place in the document. */
	last?: boolean;
	children?: ReactNode;
};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const selectFocusFrame = {
	flexBasis: 'auto',
	wordWrap: 'inherit',
	render: 'button',
	display: 'inline-block',
	flexDirection: 'row',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	width: 'var(--rcx-select-focus-width, auto)',
	opacity: 'var(--rcx-select-focus-opacity, 1)',
	cursor: 'pointer',
	outlineStyle: 'none',
	overflow: 'hidden',
	textOverflow: 'ellipsis',
	userSelect: 'none',
	textAlign: 'start',
	verticalAlign: 'middle',
	whiteSpace: 'nowrap',
	textDecorationLine: 'none',
	backgroundColor: 'inherit',
	appearance: 'none',
	color: 'var(--rcx-color-font-hint, #6c737a)',
	fontSize: '0.875rem',
	fontWeight: 500,
	lineHeight: '1.25rem',
	letterSpacing: '0rem',
} as const;

const selectFocusDisabled = {
	cursor: 'not-allowed',
} as const;

const selectFocusLast = {
	order: 1,
} as const;

// end of generated

// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const SelectFocusFrame = styled(Text, {
	...selectFocusFrame,
	variants: {
		// not `disabled`: a frame's own `disabled` compiles to aria-disabled
		look: { enabled: {}, disabled: { ...selectFocusDisabled } },
		last: { true: { ...selectFocusLast }, false: {} },
	},
});

/** The button a select takes the focus on, which shows nothing while the select shows its value in its place. */
function SelectFocus(props: SelectFocusProps) {
	const { disabled, last } = props;
	// A multiple select hands its anchor the class too, for an anchor of the app's own
	const lastClass = last && !props.className?.split(' ').includes('rcx-select__anchor--last') ? ' rcx-select__anchor--last' : '';

	return (
		<SelectFocusFrame
			look={disabled ? 'disabled' : 'enabled'}
			last={Boolean(last)}
			className={prependClassName(props.className, `rcx-box rcx-box--full rcx-select__focus rcx-select__focus--button${lastClass}`)}
			render={
				<button
					{...ariaAndDataAttributes(props)}
					{...pickWebPressHandlers(props)}
					type='button'
					ref={props.ref as ButtonRef}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
					name={props.name}
					value={props.value}
					disabled={disabled}
				/>
			}
		>
			{props.children}
		</SelectFocusFrame>
	);
}

export default SelectFocus;
