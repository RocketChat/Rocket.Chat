import { styled, View } from '@tamagui/web';
import type { ReactNode } from 'react';

import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { pickPositionStyle, pickWebAnimationHandlers, pickWebPressHandlers } from '../../helpers/pickAttributes';
import { prependClassName } from '../../helpers/prependClassName';
import type { DivAnimationHandlers, DivAttributes, DivPressHandlers, PositionedAttributes } from '../../types/ElementAttributes';

export type SelectPopupProps = DivAttributes &
	DivPressHandlers &
	DivAnimationHandlers &
	PositionedAttributes & {
		/** The popup is on its way out, so it takes no pointer. */
		closed?: boolean;
		children?: ReactNode;
	};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const selectPopupFrame = {
	display: 'block',
	flexDirection: 'row',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	render: 'div',
} as const;

const selectPopupClosed = {
	pointerEvents: 'none',
} as const;

// end of generated

// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const SelectPopupFrame = styled(View, {
	...selectPopupFrame,
	variants: {
		closed: { true: { ...selectPopupClosed }, false: {} },
	},
});

/** What `PositionAnimated` places under a `Select`: it keeps the pointer from taking the focus off the trigger. */
function SelectPopup(props: SelectPopupProps) {
	return (
		<SelectPopupFrame
			closed={Boolean(props.closed)}
			className={prependClassName(props.className, 'rcx-box rcx-box--full')}
			render={
				<div
					{...ariaAndDataAttributes(props)}
					{...pickPositionStyle(props)}
					{...pickWebAnimationHandlers(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref}
					id={props.id}
					title={props.title}
				/>
			}
		>
			{props.children}
		</SelectPopupFrame>
	);
}

export default SelectPopup;
