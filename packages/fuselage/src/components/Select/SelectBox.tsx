import { styled, View } from '@tamagui/web';
import type { AriaAttributes, ReactNode, Ref } from 'react';

import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { pickWebPressHandlers } from '../../helpers/pickAttributes';
import { prependClassName } from '../../helpers/prependClassName';
import type { ButtonRef, DivRef, ElementActionAttributes } from '../../types/ElementAttributes';

export type SelectBoxProps = Omit<ElementActionAttributes, 'ref'> &
	AriaAttributes & {
		/** The box is measured by the popup that opens under it, whichever tag it renders. */
		ref?: Ref<Element>;
		/** The tag of the box: a `button` for the trigger of a `Select`, a `div` for the rest. */
		is?: 'div' | 'button';
		/** What the box holds: the trigger's own text, a wrapper, a field of chips, or only a group. */
		layout?: 'plain' | 'trigger' | 'wrapped' | 'multi';
		/** A trigger one line short. */
		small?: boolean;
		/** The box of an `AutoComplete`, which has its own classes. */
		autocomplete?: boolean;
		/** Eases the border and background between states; on unless it is `false`. */
		animated?: boolean;
		invalid?: boolean;
		disabled?: boolean;
		autoFocus?: boolean;
		children?: ReactNode;
	};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const selectBoxFrame = {
	display: 'inline-flex',
	flexDirection: 'row',
	alignItems: 'center',
	flexShrink: 1,
	minWidth: '9rem',
	minHeight: '2.5rem',
	render: 'div',
	position: 'relative',
	flexWrap: 'nowrap',
	flexGrow: 1,
	flexBasis: 'auto',
	paddingBlock: '8px',
	paddingInline: '15px',
	verticalAlign: 'baseline',
	wordBreak: 'break-all',
	outlineStyle: 'none',
	borderWidth: '1px',
	borderStyle: 'solid',
	borderRadius: 'var(--rcx-input-border-radius, var(--rcx-border-radius-medium, 0.25rem))',
} as const;

const selectBoxLayouts = {
	'plain': {},
	'trigger': {
		display: 'flex',
		justifyContent: 'space-between',
		fontSize: '0.875rem',
		fontWeight: 400,
		lineHeight: '1.25rem',
		letterSpacing: '0rem',
	},
	'trigger-small': {
		display: 'flex',
		justifyContent: 'space-between',
		fontSize: '0.875rem',
		fontWeight: 400,
		lineHeight: '1.25rem',
		letterSpacing: '0rem',
		minWidth: '7rem',
		minHeight: '1.75rem',
		paddingBlock: '4px',
		paddingInline: '8px',
	},
	'wrapped': {
		paddingInline: '11px',
	},
	'multi': {
		paddingBlock: '4px',
	},
} as const;

// end of generated

// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const SelectBoxFrame = styled(View, {
	...selectBoxFrame,
	variants: {
		layout: selectBoxLayouts,
	},
});

/** The bordered box of a select and of the autocomplete, which share it. */
function SelectBox(props: SelectBoxProps) {
	const { is, layout = 'plain', small, autocomplete, animated = true, invalid, disabled } = props;
	const root = autocomplete ? 'rcx-autocomplete' : 'rcx-select';
	const classes = prependClassName(
		props.className,
		[
			animated ? 'rcx-box rcx-box--full rcx-box--animated' : 'rcx-box rcx-box--full',
			root,
			layout === 'trigger' && !autocomplete && `${root}--trigger`,
			small && `${root}--small`,
			invalid && `${root}--invalid`,
			disabled && `${root}--disabled`,
		]
			.filter(Boolean)
			.join(' '),
	);
	const frameLayout = layout === 'trigger' && small ? 'trigger-small' : layout;

	// One literal element per tag, as zero-runtime has to know the tag; what the consumer passes goes on that element
	if (is === 'button') {
		return (
			<SelectBoxFrame
				layout={frameLayout}
				className={classes}
				render={
					<button
						{...ariaAndDataAttributes(props)}
						{...pickWebPressHandlers(props)}
						type='button'
						ref={props.ref as ButtonRef}
						id={props.id}
						title={props.title}
						role={props.role}
						tabIndex={props.tabIndex}
						disabled={disabled}
						// oxlint-disable-next-line jsx-a11y/no-autofocus -- the consumer's to set
						autoFocus={props.autoFocus}
					/>
				}
			>
				{props.children}
			</SelectBoxFrame>
		);
	}

	return (
		<SelectBoxFrame
			layout={frameLayout}
			className={classes}
			render={
				<div
					{...ariaAndDataAttributes(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref as DivRef}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{props.children}
		</SelectBoxFrame>
	);
}

export default SelectBox;
