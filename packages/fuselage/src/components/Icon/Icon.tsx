// Declared where they render: zero-runtime only erases a `styled()` whose every use is in its own module
const IconFrame = styled(Text, {
	...iconFrame,
	variants: {
		tone: iconTones,
	},
});

// The glyph is decorative unless the caller states otherwise: an explicit `aria-hidden`, even `undefined`, replaces the default
function Icon(props: IconProps) {
	const { name, size, color, className } = props;

	return (
		<IconFrame
			tone={color}
			className={prependClassName(className, `rcx-box rcx-box--full rcx-icon--name-${name} rcx-icon`)}
			render={
				<i
					{...ariaAndDataAttributes(props)}
					{...pickWebPressHandlers(props)}
					{...customProperties({ '--rcx-icon-size': toSize(size) })}
					ref={props.ref}
					id={props.id}
					title={props.title}
					role={props.role}
					aria-hidden={Object.hasOwn(props, 'aria-hidden') ? props['aria-hidden'] : 'true'}
				/>
			}
		>
			{nameToCharacterMapping[name]}
		</IconFrame>
	);
}

// Lists re-render hundreds of icons whose props did not change
export default memo(Icon);
