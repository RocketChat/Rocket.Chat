import { styled, View } from '@tamagui/web';
import type { ReactNode } from 'react';

import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { cxx } from '../../helpers/composeClassNames';
import { pickWebPressHandlers } from '../../helpers/pickAttributes';
import { prependClassName } from '../../helpers/prependClassName';
import type { DivActionAttributes } from '../../types/ElementAttributes';

export type ModalBackdropProps = DivActionAttributes & {
	children?: ReactNode;
	/** Drops the overlay colour, for a backdrop that only catches events or stacks over another one. */
	transparent?: boolean;
	/** Covers its positioned container instead of the viewport. */
	contained?: boolean;
};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const backdropFrame = {
	display: 'flex',
	flexDirection: 'column',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	render: 'div',
	position: 'fixed',
	zIndex: 100,
	top: 0,
	right: 0,
	bottom: 0,
	left: 0,
	backgroundColor: 'var(--rcx-color-surface-overlay, #2f343d80)',
} as const;

const backdropContained = {
	position: 'absolute',
} as const;

const backdropTransparent = {
	backgroundColor: 'transparent',
} as const;

// end of generated

// Declared where they render: zero-runtime only erases a `styled()` whose every use is in its own module
const BackdropFrame = styled(View, {
	...backdropFrame,
	variants: {
		contained: { true: backdropContained },
		transparent: { true: backdropTransparent },
	},
});

const ModalBackdrop = (props: ModalBackdropProps) => {
	const { transparent, contained, children, className } = props;

	return (
		<BackdropFrame
			contained={contained}
			transparent={transparent}
			className={prependClassName(className, `rcx-box rcx-box--full ${cxx('rcx-modal__backdrop')({ contained: !!contained })}`)}
			render={
				<div
					{...ariaAndDataAttributes(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{children}
		</BackdropFrame>
	);
};

export default ModalBackdrop;
