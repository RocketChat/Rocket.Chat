import { styled, View } from '@tamagui/web';

import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { cx } from '../../helpers/composeClassNames';
import { prependClassName } from '../../helpers/prependClassName';
import type { DivAttributes } from '../../types/ElementAttributes';
import { Icon, type IconProps } from '../Icon';

export type ModalIconProps = DivAttributes & {
	name: IconProps['name'];
	size?: IconProps['size'];
	/** Tints the icon with the status it stands for. */
	variant?: 'danger' | 'warning' | 'info' | 'success';
	/** Aligns the icon with the end of the header instead of its centre, for a header taller than one line. */
	align?: 'center' | 'end';
};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const iconFrame = {
	display: 'flex',
	flexDirection: 'row',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	render: 'div',
	paddingBlock: '4px',
} as const;

const iconAlignments = {
	center: {
		alignItems: 'center',
	},
	end: {
		alignItems: 'end',
	},
} as const;

const iconTones = {
	plain: {},
	danger: {
		color: 'var(--rcx-color-font-danger, #d40c26)',
	},
	warning: {
		color: 'var(--rcx-color-status-font-on-warning, #895f00)',
	},
	info: {
		color: 'var(--rcx-color-font-info, #095ad2)',
	},
	success: {
		color: 'var(--rcx-color-status-font-on-success, #148660)',
	},
} as const;

// end of generated

// Declared where they render: zero-runtime only erases a `styled()` whose every use is in its own module
const IconFrame = styled(View, {
	...iconFrame,
	variants: {
		align: iconAlignments,
		tone: iconTones,
	},
});

const ModalIcon = (props: ModalIconProps) => {
	const { size = 'x20', name, variant, align = 'center' } = props;

	return (
		<IconFrame
			align={align}
			tone={variant ?? 'plain'}
			className={prependClassName(
				props.className,
				cx('rcx-box rcx-box--full rcx-modal__icon', { 'rcx-modal__icon--variant': variant ?? false, 'rcx-modal__icon--align': align }),
			)}
			render={<div {...ariaAndDataAttributes(props)} ref={props.ref} id={props.id} title={props.title} />}
		>
			<Icon name={name} size={size} />
		</IconFrame>
	);
};

export default ModalIcon;
