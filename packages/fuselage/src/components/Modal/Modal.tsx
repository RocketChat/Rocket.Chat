import { styled, Text, View } from '@tamagui/web';
import type { ReactNode } from 'react';

import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { customProperties } from '../../helpers/customProperties';
import { pickWebAnimationHandlers, pickWebPressHandlers } from '../../helpers/pickAttributes';
import { prependClassName } from '../../helpers/prependClassName';
import { size } from '../../styleTokens';
import type { DialogAttributes, ElementSubmitHandler } from '../../types/ElementAttributes';

/** A Fuselage size (`x480`) or a length in pixels. */
export type ModalSize = `x${number}` | number;

export type ModalProps = DialogAttributes & {
	children?: ReactNode;
	/** A fixed width, for content that needs it instead of the default fluid one. */
	width?: ModalSize;
	/** A fixed height, for content that has no intrinsic height (e.g. an iframe). */
	height?: ModalSize;
	/** A maximum height, past which the content scrolls, for content taller than the default limit allows. */
	maxHeight?: ModalSize;
	/** Whether the dialog is open, which a modal is unless told otherwise. */
	open?: boolean;
	/** Hides the modal while keeping it, and its state, mounted. */
	hidden?: boolean;
	/** Turns the modal's surface into a form that calls this handler on submit, so a `type='submit'` button inside it confirms the modal. */
	onSubmit?: ElementSubmitHandler;
	/** The `id` of the form the modal renders when `onSubmit` is given, for controls outside of it that point at it with `form`. */
	formId?: string;
};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const modalFrame = {
	display: 'flex',
	flexDirection: 'row',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	render: 'dialog',
	position: 'static',
	width: 'var(--rcx-modal-width, 100%)',
	height: 'var(--rcx-modal-height, fit-content)',
	maxHeight: 'var(--rcx-modal-max-height, 100%)',
	maxWidth: {
		sm: '40rem',
	},
	margin: 'var(--rcx-modal-margin, auto)',
	padding: {
		default: 0,
		sm: '16px',
	},
	borderWidth: 0,
	borderStyle: 'solid',
	borderColor: 'currentColor',
	color: 'CanvasText',
	backgroundColor: 'transparent',
} as const;

const modalHidden = {
	display: 'none',
} as const;

const modalInnerFrame = {
	flexBasis: 'auto',
	whiteSpace: 'inherit',
	wordWrap: 'inherit',
	display: 'flex',
	flexDirection: 'column',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 0,
	minHeight: 'auto',
	render: 'div',
	flexGrow: 1,
	width: '100%',
	padding: 0,
	color: 'var(--rcx-color-font-default, #2f343d)',
	borderRadius: 'var(--rcx-modal-border-radius, var(--rcx-border-radius-large, 0.5rem))',
	backgroundColor: 'var(--rcx-color-surface-light, #ffffff)',
	fontSize: '0.875rem',
	fontWeight: 400,
	lineHeight: '1.25rem',
	letterSpacing: '0rem',
	boxShadow:
		'0px 0px 2px 0px var(--rcx-color-shadow-elevation-2x, #2f343d14), 0px 0px 12px 0px var(--rcx-color-shadow-elevation-2y, #2f343d1f)',
	borderWidth: '1px',
	borderStyle: 'solid',
	borderColor: 'var(--rcx-color-shadow-elevation-border, #ebecef)',
} as const;

// end of generated

// Declared where they render: zero-runtime only erases a `styled()` whose every use is in its own module
const ModalFrame = styled(View, {
	...modalFrame,
	variants: {
		hidden: { true: modalHidden },
	},
});

const ModalInnerFrame = styled(Text, { ...modalInnerFrame });

const Modal = (props: ModalProps) => {
	const { children, onSubmit, formId, width, height, maxHeight, hidden, className } = props;

	return (
		<ModalFrame
			hidden={hidden}
			className={prependClassName(className, 'rcx-box rcx-box--full rcx-modal')}
			render={
				<dialog
					open={props.open ?? true}
					aria-modal='true'
					{...ariaAndDataAttributes(props)}
					{...pickWebPressHandlers(props)}
					{...pickWebAnimationHandlers(props)}
					{...customProperties({
						'--rcx-modal-width': size(width),
						'--rcx-modal-height': size(height),
						'--rcx-modal-max-height': size(maxHeight),
					})}
					hidden={hidden}
					ref={props.ref}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{onSubmit ? (
				<ModalInnerFrame className='rcx-box rcx-box--full rcx-modal__inner' render={<form id={formId} onSubmit={onSubmit} />}>
					{children}
				</ModalInnerFrame>
			) : (
				<ModalInnerFrame className='rcx-box rcx-box--full rcx-modal__inner' render={<div />}>
					{children}
				</ModalInnerFrame>
			)}
		</ModalFrame>
	);
};

export default Modal;
