import { styled, View } from '@tamagui/web';
import type { AriaAttributes, CSSProperties, DialogHTMLAttributes, ElementType, ReactNode, Ref } from 'react';
import { createElement } from 'react';

import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { size } from '../../styleTokens';
import type { PartAttributes } from '../../types/ElementAttributes';
import type { BoxProps } from '../Box';

type WrapperProps = Pick<BoxProps, 'elevation' | 'className' | 'children'>;

export type ModalProps = {
	/** A fixed width, for content that needs it instead of the default fluid one. */
	width?: BoxProps['width'];
	/** A fixed height, for content that has no intrinsic height (e.g. an iframe). */
	height?: BoxProps['height'];
	/** A maximum height, past which the content scrolls, for content taller than the default limit allows. */
	maxHeight?: BoxProps['maxHeight'];
	/** Hides the modal while keeping it, and its state, mounted. */
	hidden?: boolean;
	children?: ReactNode;
	wrapperFunction?: (props: WrapperProps) => ReactNode;
	wrapper?: ElementType<WrapperProps>;
} & PartAttributes<HTMLElement> &
	Pick<DialogHTMLAttributes<HTMLDialogElement>, 'open'> &
	Pick<AriaAttributes, 'aria-modal' | 'aria-label' | 'aria-labelledby' | 'aria-describedby' | 'aria-busy'>;

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

// Declared where they render: zero-runtime only erases a `styled()` whose every use is in its own module
const ModalFrame = styled(View, {
	render: 'dialog',
	display: 'flex',
	flexDirection: 'row',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	position: 'static',
	width: 'var(--rcx-modal-width, 100%)',
	height: 'var(--rcx-modal-height, auto)',
	maxHeight: 'var(--rcx-modal-max-height, 100%)',
	margin: 'var(--rcx-modal-margin, auto)',
	backgroundColor: 'transparent',
});

const ModalInnerFrame = styled(View, {
	render: 'div',
	display: 'flex',
	flexDirection: 'column',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 0,
	minHeight: 'auto',
	flexGrow: 1,
	width: '100%',
	padding: 0,
	color: 'var(--rcx-color-font-default, #2f343d)',
	borderRadius: 'var(--rcx-modal-border-radius, var(--rcx-border-radius-large, 0.5rem))',
	borderWidth: '1px',
	borderStyle: 'solid',
	borderColor: 'var(--rcx-color-shadow-elevation-border, #ebecef)',
	backgroundColor: 'var(--rcx-color-surface-light, #ffffff)',
	boxShadow: '0 0 2px 0 var(--rcx-color-shadow-elevation-2x, #2f343d14), 0 0 12px 0 var(--rcx-color-shadow-elevation-2y, #2f343d1f)',
	fontSize: '0.875rem',
	fontWeight: 400,
	lineHeight: '1.25rem',
	letterSpacing: '0rem',
});

// end of generated

const ModalInner = ({ className, children }: WrapperProps) => (
	<ModalInnerFrame className={['rcx-box rcx-box--full', className].filter(Boolean).join(' ')}>{children}</ModalInnerFrame>
);

const Modal = (props: ModalProps) => {
	const { children, wrapper = ModalInner, wrapperFunction, className, width, height, maxHeight, hidden } = props;
	const wrapperProps = {
		children,
		className: 'rcx-modal__inner',
		elevation: '2',
	} as const;
	// The open sizes travel as custom properties, which the frame reads; zero-runtime rejects a `style` written on the element
	const sizes = {
		style: {
			'--rcx-modal-width': size(width),
			'--rcx-modal-height': size(height),
			'--rcx-modal-max-height': size(maxHeight),
		} as CSSProperties,
	};

	return (
		<ModalFrame
			render={
				<dialog
					{...ariaAndDataAttributes(props)}
					{...sizes}
					// The ref is typed for any element the caller holds
					ref={props.ref as Ref<HTMLDialogElement>}
					id={props.id}
					title={props.title}
					open={props.open ?? true}
					hidden={hidden}
					aria-modal={props['aria-modal'] ?? 'true'}
				/>
			}
			className={['rcx-box rcx-box--full', 'rcx-modal', className].filter(Boolean).join(' ')}
		>
			{wrapperFunction ? wrapperFunction(wrapperProps) : createElement(wrapper, wrapperProps)}
		</ModalFrame>
	);
};

export default Modal;
