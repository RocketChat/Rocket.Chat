import { styled, View } from '@tamagui/web';
import type { DialogHTMLAttributes, ElementType, ReactNode } from 'react';
import { createElement } from 'react';

import type { ElementProps } from '../../types/ElementProps';
import { Box, type BoxProps } from '../Box';

export type ModalProps = ElementProps<Element, DialogHTMLAttributes<HTMLDialogElement>> & {
	/** A fixed width, for content that needs it instead of the default fluid one. */
	width?: BoxProps['width'];
	/** A fixed height, for content that has no intrinsic height (e.g. an iframe). */
	height?: BoxProps['height'];
	/** A maximum height, past which the content scrolls, for content taller than the default limit allows. */
	maxHeight?: BoxProps['maxHeight'];
	/** Hides the modal while keeping it, and its state, mounted. */
	hidden?: boolean;
	wrapperFunction?: (props: Pick<BoxProps, 'elevation' | 'className' | 'children'>) => ReactNode;
	wrapper?: ElementType<Pick<BoxProps, 'elevation' | 'className' | 'children'>>;
};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

// Declared where they render: zero-runtime only erases a `styled()` whose every use is in its own module
const ModalFrame = styled(View, {
	render: 'dialog',
	display: 'flex',
	flexDirection: 'row',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	position: 'static',
	width: '100%',
	maxHeight: '100%',
	margin: 'var(--rcx-modal-margin, auto)',
	backgroundColor: 'transparent',
});

// end of generated

const Modal = ({ children, wrapper = Box, wrapperFunction, className, ...props }: ModalProps) => {
	const wrapperProps = {
		children,
		className: 'rcx-modal__inner',
		elevation: '2',
	} as const;

	return (
		<ModalFrame
			// The caller's attributes go on the element `render` names: zero-runtime rejects spreads on a frame
			render={<Box is='dialog' open aria-modal='true' {...props} />}
			className={['rcx-modal', className].filter(Boolean).join(' ')}
		>
			{wrapperFunction ? wrapperFunction(wrapperProps) : createElement(wrapper, wrapperProps)}
		</ModalFrame>
	);
};

export default Modal;
