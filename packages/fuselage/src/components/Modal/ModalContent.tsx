import { styled, Text, View } from '@tamagui/web';
import type { ReactNode } from 'react';

import { useScrollEdges } from './useScrollEdges';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { pickWebPressHandlers } from '../../helpers/pickAttributes';
import { prependClassName } from '../../helpers/prependClassName';
import type { DivAttributes, DivPressHandlers } from '../../types/ElementAttributes';

export type ModalContentProps = DivAttributes &
	DivPressHandlers & {
		children?: ReactNode;
		onScrollContent?: ((touching: { top: boolean }) => void) | undefined;
		/** Stretches the content to the modal's height and closes the modal itself, for content that brings its own footer. */
		fill?: boolean;
	};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const contentFrame = {
	display: 'block',
	flexDirection: 'row',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	render: 'div',
	position: 'relative',
	overflowY: 'auto',
} as const;

const contentWrapperFrame = {
	flexBasis: 'auto',
	whiteSpace: 'inherit',
	wordWrap: 'inherit',
	display: 'block',
	flexDirection: 'row',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	render: 'div',
	marginInline: '24px',
} as const;

const contentWrapperFill = {
	true: {
		height: '100%',
		paddingBlockEnd: '16px',
	},
	false: {},
} as const;

// end of generated

// Declared where they render: zero-runtime only erases a `styled()` whose every use is in its own module
const ContentFrame = styled(View, { ...contentFrame });

const ContentWrapperFrame = styled(Text, {
	...contentWrapperFrame,
	variants: {
		fill: contentWrapperFill,
	},
});

const ModalContent = (props: ModalContentProps) => {
	const { children, onScrollContent, fill } = props;
	const onScroll = useScrollEdges(onScrollContent);

	return (
		<ContentFrame className='rcx-box rcx-box--full rcx-modal__content' render={<div onScroll={onScroll} />}>
			<ContentWrapperFrame
				fill={!!fill}
				className={prependClassName(
					props.className,
					`rcx-box rcx-box--full rcx-modal__content-wrapper${fill ? ' rcx-modal__content-wrapper--fill' : ''}`,
				)}
				render={
					<div {...ariaAndDataAttributes(props)} {...pickWebPressHandlers(props)} ref={props.ref} id={props.id} title={props.title} />
				}
			>
				{children}
			</ContentWrapperFrame>
		</ContentFrame>
	);
};

export default ModalContent;
