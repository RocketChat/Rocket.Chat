const IconButtonFrame = styled(View, {
	...iconButtonFrame,
	group: 'button',
	variants: {
		box: iconButtonBoxes,
		// A badge and a segment each position the frame, so one variant holds both
		layer: iconButtonLayers,
		segment: iconButtonSegments,
		paint: iconButtonPaints,
	},
});

const IconButtonContent = styled(Text, {
	...iconButtonContent,
	variants: { glyph: iconButtonGlyphs },
});

const IconButtonBadge = styled(Text, {
	...iconButtonBadge,
	variants: { corner: iconButtonCorners },
});

const iconSizes = {
	mini: 'x12',
	tiny: 'x16',
	small: 'x20',
	medium: 'x24',
	large: 'x28',
} as const;

const layerOf = (badged: boolean, segmented: boolean) => {
	if (badged) return segmented ? 'segmented-badged' : 'badged';
	return segmented ? 'segmented' : undefined;
};

const hasPressedPaint = (paint: string): paint is 'icon' | 'info' | 'success' | 'warning' | 'danger' => !paint.startsWith('secondary');

function IconButton(props: IconButtonProps) {
	const { icon, badge, badgePosition = 'top-end', variant, size = 'large', pressed, color, disabled, children, className } = props;
	const segment = useContext(SegmentContext);
	// `secondary-info` is the name of the paint and of the class of the primary variant
	const name = variant === 'primary' ? 'secondary-info' : variant;
	const kind = name ?? 'icon';

	const paintOf = () => {
		// The trigger of a split button is a ghost over the group's background, whichever variant and state it has
		if (segment?.ghost) return disabled ? (`ghost-${segment.tone}-disabled` as const) : (`ghost-${segment.tone}` as const);
		if (disabled) return `${kind}-disabled` as const;
		return pressed && hasPressedPaint(kind) ? (`${kind}-pressed` as const) : kind;
	};

	const classes = prependClassName(
		className,
		[
			'rcx-box rcx-box--full rcx-button rcx-button--icon rcx-button--square',
			name && `rcx-button--icon-${name}`,
			pressed && `rcx-button--icon-${name ?? ''}-pressed`,
			`rcx-button--${size}-square`,
			pressed && 'rcx-button--icon-pressed',
			badge && 'rcx-button--with-badge',
		]
			.filter(Boolean)
			.join(' '),
	);

	const content = (
		// The button is not a Box, so without this the margins of a Margins above it would land on the Boxes inside it
		<BoxTransforms.Provider value={null}>
			{/* The glyph takes the color whichever way the caller gave the icon; a disabled button keeps its disabled one */}
			<IconButtonContent glyph={disabled ? undefined : color}>
				{isValidElement<any>(icon) ? icon : <Icon name={icon} size={iconSizes[size]} />}
				{children}
			</IconButtonContent>
			{Boolean(badge) && (
				<IconButtonBadge
					corner={badgePosition}
					className={`rcx-button__badge rcx-button__badge--${badgePosition}`}
					render={<span aria-hidden='true' />}
				>
					{badge}
				</IconButtonBadge>
			)}
		</BoxTransforms.Provider>
	);

	if (props.is === 'a') {
		return (
			<IconButtonFrame
				box={size}
				layer={layerOf(Boolean(badge), Boolean(segment))}
				segment={segment?.position}
				paint={paintOf()}
				className={classes}
				{...pickFramePressHandlers(props)}
				render={
					<a
						{...ariaAndDataAttributes(props)}
						{...pickWebInteractionHandlers(props)}
						{...pickWebPressHandlers(props)}
						href={props.href}
						target={props.target ?? (props.external ? '_blank' : undefined)}
						rel={props.rel ?? (props.external ? 'noopener noreferrer' : undefined)}
						download={props.download}
						ref={props.ref as WebLinkRef}
						id={props.id}
						title={props.title}
						role={props.role}
						tabIndex={props.tabIndex}
					/>
				}
			>
				{content}
			</IconButtonFrame>
		);
	}

	return (
		<IconButtonFrame
			box={size}
			layer={layerOf(Boolean(badge), Boolean(segment))}
			segment={segment?.position}
			paint={paintOf()}
			className={classes}
			{...pickFramePressHandlers(props)}
			render={
				<button
					{...ariaAndDataAttributes(props)}
					{...pickWebInteractionHandlers(props)}
					{...pickWebPressHandlers(props)}
					type={props.type ?? 'button'}
					form={props.form}
					name={props.name}
					value={props.value}
					// oxlint-disable-next-line jsx-a11y/no-autofocus -- the consumer's to set
					autoFocus={props.autoFocus}
					disabled={disabled}
					ref={props.ref as WebButtonRef}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{content}
		</IconButtonFrame>
	);
}

export default IconButton;
