const iconSizes = {
	mini: 'x12',
	tiny: 'x16',
	small: 'x20',
	medium: 'x24',
	large: 'x28',
} as const;

function IconButton({
	icon,
	badge,
	badgePosition = 'top-end',
	variant: variantProp,
	size = 'large',
	pressed,
	is = 'button',
	external,
	color,
	disabled,
	children,
	className,
	ref,
	...props
}: IconButtonProps) {
	// `secondary-info` is the class that paints the primary palette.
	const variant = variantProp === 'primary' ? 'secondary-info' : (variantProp ?? '');

	// The caller's attributes go on the element `render` names: zero-runtime rejects spreads on a frame
	const attributes = {
		...(is === 'a' ? { rel: external ? 'noopener noreferrer' : undefined, target: external ? '_blank' : undefined } : { type: 'button' }),
		...props,
	};

	// Disabled colors win over pressed ones
	const state = [disabled && '-disabled', pressed && '-pressed'].find(Boolean) || '';
	const paint = `${variant || 'icon'}${state}`;
	// Listed in the order `Box` gave the `rcx-` props it used to take: each one went in front of the last
	const classes = [
		badge && 'rcx-button--with-badge',
		pressed && 'rcx-button--icon-pressed',
		`rcx-button--${size}-square`,
		pressed && `rcx-button--icon-${variant}-pressed`,
		variant && `rcx-button--icon-${variant}`,
		'rcx-button--square',
		'rcx-button--icon',
		'rcx-button',
		className,
	]
		.filter(Boolean)
		.join(' ');

	return (
		<IconButtonFrame
			render={<Box {...attributes} is={is} color={color} disabled={disabled} ref={ref} />}
			sizing={size}
			badged={Boolean(badge)}
			paint={paint}
			className={classes}
		>
			{isValidElement<any>(icon) ? icon : <Icon name={icon} size={iconSizes[size]} />}
			{Boolean(badge) && (
				<span className={`rcx-button__badge rcx-button__badge--${badgePosition}`} aria-hidden='true'>
					{badge}
				</span>
			)}
			{children}
		</IconButtonFrame>
	);
}

export default IconButton;
