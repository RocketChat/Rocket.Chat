const ButtonContent = styled(Text, buttonContent);

const fontScaleOf = (size: ButtonProps['size']) => {
	if (size === 'large') return 'large';
	if (size === 'small' || size === 'medium') return 'small';
	return undefined;
};

// Mini and tiny take the default box unless square, and compact only matters to a rectangular one
const boxOf = (size: ButtonProps['size'], compact: boolean, square: boolean) => {
	if (square) return size && size !== 'large' ? (`${size}-square` as const) : 'square';
	if (size === 'small' || size === 'medium' || size === 'large') return compact ? (`${size}-compact` as const) : size;
	return compact ? 'compact' : undefined;
};

/**
 * Indicates an actionable user action.
 */
function Button(props: ButtonProps) {
	const { variant, size, square, compact, loading, disabled, icon, children, className } = props;
	const unavailable = disabled || loading;
	const segment = useContext(SegmentContext);

	const classes = prependClassName(
		className,
		[
			'rcx-box rcx-box--full rcx-button',
			variant && `rcx-button--${variant}`,
			size && size !== 'mini' && size !== 'tiny' && `rcx-button--${size}`,
			square && 'rcx-button--square',
			compact && 'rcx-button--compact',
			square && size && `rcx-button--${size}-square`,
			loading && 'rcx-button--loading',
		]
			.filter(Boolean)
			.join(' '),
	);

	const fontScale = fontScaleOf(size);
	const box = boxOf(size, Boolean(compact), Boolean(square));

	const content = (
		// The button is not a Box, so without this the margins of a Margins above it would land on the Boxes inside it
		<BoxTransforms.Provider value={null}>
			<ButtonContent className='rcx-button--content'>
				{icon && !loading && <Icon className='rcx-button__icon' size='x16' name={icon} />}
				{loading && <Icon className='rcx-button__icon' size='x16' name='loading' />}
				{children}
			</ButtonContent>
		</BoxTransforms.Provider>
	);

	// A link has no disabled state, so it keeps the colors of its kind
	if (props.is === 'a') {
		return (
			<ButtonFrame
				fontScale={fontScale}
				box={box}
				square={square}
				segment={segment?.position}
				segmented={Boolean(segment)}
				paint={variant ?? 'secondary'}
				className={classes}
				render={
					<a
						{...ariaAndDataAttributes(props)}
						{...pickWebInteractionHandlers(props)}
						{...pickWebPressHandlers(props)}
						onDragOver={props.onDragOver}
						onDrop={props.onDrop}
						href={props.href}
						target={props.target ?? (props.external ? '_blank' : undefined)}
						rel={props.rel ?? (props.external ? 'noopener noreferrer' : undefined)}
						download={props.download}
						ref={props.ref as WebLinkRef}
						id={props.id}
						title={props.title}
						role={props.role}
						tabIndex={props.tabIndex}
					/>
				}
			>
				{content}
			</ButtonFrame>
		);
	}

	return (
		<ButtonFrame
			fontScale={fontScale}
			box={box}
			square={square}
			segment={segment?.position}
			segmented={Boolean(segment)}
			paint={unavailable ? `${variant ?? 'secondary'}-disabled` : (variant ?? 'secondary')}
			className={classes}
			render={
				<button
					{...ariaAndDataAttributes(props)}
					{...pickWebInteractionHandlers(props)}
					{...pickWebPressHandlers(props)}
					onDragOver={props.onDragOver}
					onDrop={props.onDrop}
					type={props.type ?? 'button'}
					form={props.form}
					name={props.name}
					value={props.value}
					// oxlint-disable-next-line jsx-a11y/no-autofocus -- the consumer's to set
					autoFocus={props.autoFocus}
					disabled={unavailable}
					ref={props.ref as WebButtonRef}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{content}
		</ButtonFrame>
	);
}

export default Button;
