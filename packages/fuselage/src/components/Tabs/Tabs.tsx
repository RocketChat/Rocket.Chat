import { styled, View } from '@tamagui/web';
import type { ReactNode } from 'react';

import { TabsContext, tabsValue } from './TabsContext';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { pickWebPressHandlers } from '../../helpers/pickAttributes';
import { prependClassName } from '../../helpers/prependClassName';
import type { DivAttributes, DivPressHandlers } from '../../types/ElementAttributes';

export type TabsProps = DivAttributes &
	DivPressHandlers & {
		children?: ReactNode;
		divider?: boolean;
		/** Grows the items to fill the whole width. */
		stretch?: boolean;
	};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const tabsFrame = {
	render: 'div',
	display: 'flex',
	flexDirection: 'row',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	position: 'relative',
} as const;

const tabsDividers = {
	with: {
		borderBottomWidth: '1px',
		borderBottomStyle: 'solid',
		borderBottomColor: 'var(--rcx-color-stroke-light, #cbced1)',
	},
	without: {},
} as const;

const tabsLayouts = {
	row: {},
	stretch: {
		flexDirection: 'column',
	},
} as const;

const tabsScrollBoxFrame = {
	render: 'div',
	display: 'block',
	flexDirection: 'row',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	position: 'relative',
	overflow: 'auto',
	marginBlock: '-4px',
} as const;

const tabsWrapperFrame = {
	render: 'div',
	display: 'flex',
	flexDirection: 'row',
	flexWrap: 'nowrap',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	position: 'static',
	marginBlock: 0,
	marginInline: '12px',
	paddingBlock: '4px',
	paddingInline: 0,
} as const;

// end of generated

// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const TabsFrame = styled(View, {
	...tabsFrame,
	variants: {
		divider: tabsDividers,
		layout: tabsLayouts,
	},
});

const TabsScrollBox = styled(View, tabsScrollBoxFrame);

const TabsWrapper = styled(View, tabsWrapperFrame);

/**
 * Tabs is a component to navigate around the UI using buttons arranged together with the selected tab highlighted.
 */
function Tabs({ children, divider = true, stretch = false, ...props }: TabsProps) {
	return (
		<TabsContext.Provider value={tabsValue(divider, stretch)}>
			<TabsFrame
				divider={divider ? 'with' : 'without'}
				layout={stretch ? 'stretch' : 'row'}
				className={prependClassName(
					props.className,
					`rcx-box rcx-box--full rcx-tabs${stretch ? ' rcx-tabs--stretch' : ''}${divider ? ' rcx-tabs--with-divider' : ''}`,
				)}
				render={
					<div {...ariaAndDataAttributes(props)} {...pickWebPressHandlers(props)} ref={props.ref} id={props.id} title={props.title} />
				}
			>
				<TabsScrollBox className='rcx-box rcx-box--full rcx-tabs__scroll-box'>
					<TabsWrapper className='rcx-box rcx-box--full rcx-tabs__wrapper' render={<div role='tablist' />}>
						{children}
					</TabsWrapper>
				</TabsScrollBox>
			</TabsFrame>
		</TabsContext.Provider>
	);
}

export default Tabs;
