function TabsItem(props: TabsItemProps) {
	const { selected, disabled, className, children } = props;
	const { divider, stretch } = useContext(TabsContext);
	// A tab bar with a divider keeps the underline of a hovered tab at 1px
	const grows = !divider ? '-grows' : '';
	const look = (selected && (disabled ? 'selectedDisabled' : 'selected')) || `${disabled ? 'disabled' : 'idle'}${grows}`;

	return (
		<TabsItemFrame
			look={look}
			divider={divider ? 'with' : 'without'}
			stretch={stretch ? 'stretch' : 'fixed'}
			className={prependClassName(
				className,
				`rcx-box rcx-box--full rcx-tabs__item${selected ? ' rcx-tabs__item--selected' : ''}${disabled ? ' rcx-tabs__item--disabled' : ''}${
					selected && disabled ? ' rcx-tabs__item--selected--disabled' : ''
				}`,
			)}
			render={
				<button
					{...ariaAndDataAttributes(props)}
					{...pickWebPressHandlers(props)}
					aria-selected={props['aria-selected'] ?? (selected ? 'true' : 'false')}
					role={props.role ?? 'tab'}
					disabled={disabled}
					ref={props.ref}
					id={props.id}
					title={props.title}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{children}
		</TabsItemFrame>
	);
}

