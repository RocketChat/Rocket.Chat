const Banner = (props: BannerProps) => {
	const {
		actionable,
		children,
		className,
		closeable,
		icon,
		inline = false,
		link,
		linkText = 'More info',
		linkTarget = '_blank',
		onAction,
		onClose,
		title,
		variant: requestedVariant = 'neutral',
	} = props;
	const ref = useRef<DivElement>(null);
	const mergedRef = useMergedRefs(ref, props.ref);
	const { inlineSize } = useBorderBoxSize(ref, {
		debounceDelay: 70,
	});

	const isIconVisible = useMemo(() => inlineSize > 375, [inlineSize]);

	const variant = variants.includes(requestedVariant) ? requestedVariant : variants[0];
	const density = inline ? 'inline' : 'regular';

	const handleBannerClick = useCallback(() => {
		if (onAction) {
			onAction();
		}
	}, [onAction]);

	const handleCloseButtonClick = useCallback(
		(event: MouseEvent) => {
			event.stopPropagation();

			if (onClose) {
				onClose();
			}
		},
		[onClose],
	);

	const buttonProps = useButtonPattern(handleBannerClick);
	const pattern = onAction ? buttonProps : undefined;

	const classes = [`rcx-banner rcx-banner--${variant}`, inline && 'rcx-banner--inline', actionable && 'rcx-banner--actionable']
		.filter(Boolean)
		.join(' ');

	return (
		<BannerFrame
			tone={variant}
			density={density}
			action={actionable ? 'actionable' : 'none'}
			className={prependClassName(className, classes)}
			render={
				<div
					{...ariaAndDataAttributes(props)}
					ref={mergedRef}
					id={props.id}
					role={props.role ?? pattern?.role ?? 'banner'}
					tabIndex={props.tabIndex ?? pattern?.tabIndex ?? -1}
					onClick={props.onClick ?? pattern?.onClick}
					onKeyDown={props.onKeyDown ?? pattern?.onKeyDown}
				/>
			}
		>
			{icon && isIconVisible && (
				<BannerIcon
					tone={variant}
					className={`rcx-banner__icon rcx-banner__icon--${variant}${inline ? ` rcx-banner__icon--${variant}--inline` : ''}`}
				>
					{icon}
				</BannerIcon>
			)}
			<BannerContent density={density} className={`rcx-banner__content${inline ? ' rcx-banner__content--inline' : ''}`}>
				{title && (
					<BannerTitle density={density} className={`rcx-banner__title${inline ? ' rcx-banner__title--inline' : ''}`}>
						{title}
					</BannerTitle>
				)}
				{children}
				{link && (
					<BannerLink className={`rcx-banner__link rcx-banner__link--${variant}`} render={<a href={link} target={linkTarget} />}>
						{linkText}
					</BannerLink>
				)}
			</BannerContent>
			{closeable && (
				<BannerCloseButton density={density} className={`rcx-banner__close-button${inline ? ' rcx-banner__close-button--inline' : ''}`}>
					<IconButton size='small' onClick={handleCloseButtonClick} icon='cross' />
				</BannerCloseButton>
			)}
		</BannerFrame>
	);
};

export default Banner;
