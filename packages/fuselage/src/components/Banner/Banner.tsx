const variants: BannerVariant[] = ['neutral', 'info', 'success', 'warning', 'danger'];

// The icon shows only where the banner is wide enough for it
const ICON_MIN_INLINE_SIZE = 375;

const Banner = (props: BannerProps) => {
	const { actionable, children, className, closeable, icon, inline = false, link, linkText = 'More info', linkTarget = '_blank' } = props;
	const { onAction, onClose, title, variant: requestedVariant = 'neutral' } = props;
	const ref = useRef<WebDivElement>(null);
	const mergedRef = useMergedRefs(ref, props.ref);
	const { inlineSize } = useBorderBoxSize(ref, {
		debounceDelay: 70,
	});

	const isIconVisible = useMemo(() => inlineSize > ICON_MIN_INLINE_SIZE, [inlineSize]);

	const variant = variants.includes(requestedVariant) ? requestedVariant : variants[0];
	const density = inline ? 'inline' : 'regular';

	const handleBannerClick = useCallback(() => {
		onAction?.();
	}, [onAction]);

	const handleCloseButtonClick = useCallback(
		(event: { stopPropagation(): void }) => {
			event.stopPropagation();
			onClose?.();
		},
		[onClose],
	);

	const buttonProps = useButtonPattern(handleBannerClick);
	const pattern = onAction ? buttonProps : undefined;

	return (
		<BannerFrame
			tone={variant}
			density={density}
			action={actionable ? 'actionable' : 'none'}
			className={prependClassName(className, cxx('rcx-banner')(variant, { inline, actionable: Boolean(actionable) }))}
			render={
				<div
					{...ariaAndDataAttributes(props)}
					ref={mergedRef}
					id={props.id}
					role={props.role ?? pattern?.role ?? 'banner'}
					tabIndex={pattern?.tabIndex ?? -1}
					onClick={pattern?.onClick}
					onKeyDown={pattern?.onKeyDown}
				/>
			}
		>
			{icon && isIconVisible && (
				<BannerIcon
					tone={variant}
					className={cx('rcx-banner__icon', `rcx-banner__icon--${variant}`, inline && `rcx-banner__icon--${variant}--inline`)}
				>
					{icon}
				</BannerIcon>
			)}
			<BannerContent density={density} className={cx('rcx-banner__content', inline && 'rcx-banner__content--inline')}>
				{title && (
					<BannerTitle density={density} className={cx('rcx-banner__title', inline && 'rcx-banner__title--inline')}>
						{title}
					</BannerTitle>
				)}
				{children}
				{link && (
					<BannerLink className={`rcx-banner__link rcx-banner__link--${variant}`} render={<a href={link} target={linkTarget} />}>
						{linkText}
					</BannerLink>
				)}
			</BannerContent>
			{closeable && (
				<BannerCloseButton density={density} className={cx('rcx-banner__close-button', inline && 'rcx-banner__close-button--inline')}>
					<IconButton size='small' onClick={handleCloseButtonClick} icon='cross' />
				</BannerCloseButton>
			)}
		</BannerFrame>
	);
};

