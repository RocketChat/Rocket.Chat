const joinClasses = (...names: (string | false | undefined)[]) => names.filter(Boolean).join(' ');

const Banner = ({
	actionable,
	children,
	className,
	closeable,
	icon,
	inline = false,
	link,
	linkText = 'More info',
	linkTarget = '_blank',
	onAction,
	onClose,
	title,
	variant = 'neutral',
	...props
}: BannerProps) => {
	const ref = useRef<HTMLDivElement>(null);
	const { inlineSize } = useBorderBoxSize(ref, {
		debounceDelay: 70,
	});

	const isIconVisible = useMemo(() => inlineSize > 375, [inlineSize]);

	variant = variants.includes(variant) ? variant : variants[0];

	const handleBannerClick = useCallback(() => {
		if (onAction) {
			onAction();
		}
	}, [onAction]);

	const handleCloseButtonClick = useCallback(
		(event: MouseEvent) => {
			event.stopPropagation();

			if (onClose) {
				onClose();
			}
		},
		[onClose],
	);

	const buttonProps = useButtonPattern(handleBannerClick);

	// The caller's attributes go on the element `render` names: zero-runtime rejects spreads on a frame
	const attributes = { ...(onAction ? { ...buttonProps } : { role: 'banner', tabIndex: -1 }), ...props };

	return (
		<BannerFrame
			render={<div {...attributes} ref={ref} />}
			tone={variant}
			inline={inline}
			actionable={Boolean(actionable)}
			className={joinClasses(
				'rcx-banner',
				`rcx-banner--${variant}`,
				inline && 'rcx-banner--inline',
				actionable && 'rcx-banner--actionable',
				className,
			)}
		>
			{icon && isIconVisible && (
				<BannerIconFrame
					tone={variant}
					className={joinClasses('rcx-banner__icon', `rcx-banner__icon--${variant}`, inline && `rcx-banner__icon--${variant}--inline`)}
				>
					{icon}
				</BannerIconFrame>
			)}
			<BannerContentFrame inline={inline} className={joinClasses('rcx-banner__content', inline && 'rcx-banner__content--inline')}>
				{title && (
					<BannerTitleFrame inline={inline} className={joinClasses('rcx-banner__title', inline && 'rcx-banner__title--inline')}>
						{title}
					</BannerTitleFrame>
				)}
				{children}
				{link && (
					<BannerLinkFrame
						render={<a href={link} target={linkTarget} />}
						className={joinClasses('rcx-banner__link', `rcx-banner__link--${variant}`)}
					>
						{linkText}
					</BannerLinkFrame>
				)}
			</BannerContentFrame>
			{closeable && (
				<BannerCloseButtonFrame
					inline={inline}
					className={joinClasses('rcx-banner__close-button', inline && 'rcx-banner__close-button--inline')}
				>
					<IconButton size='small' onClick={handleCloseButtonClick} icon='cross' />
				</BannerCloseButtonFrame>
			)}
		</BannerFrame>
	);
};

export default Banner;
