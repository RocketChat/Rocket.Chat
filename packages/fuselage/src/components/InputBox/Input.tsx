const shapeOf = ({ undecorated, wrapped, small, last }: Pick<AnyInputProps, 'undecorated' | 'wrapped' | 'small' | 'last'>) => {
	if (last) return 'plain-last';
	const kind = wrapped ? 'wrapped' : (undecorated && 'plain') || 'decorated';
	return small ? (`${kind}-small` as const) : kind;
};

type AnyInputProps = InputProps<TextControlElement>;

/** The `input` or `textarea` of an input box: the frame that draws it and the one place its attributes are forwarded. */
function Input<TElement extends TextControlElement = InputElement>(props: InputProps<TElement>): ReactElement;
function Input(props: AnyInputProps) {
	const { is, type, undecorated, small, placeholderVisible, hidden, invisible, className } = props;
	const isTextArea = is === 'textarea';
	const kind = isTextArea ? 'textarea' : type;

	const classes = prependClassName(
		className,
		[
			'rcx-box rcx-box--full rcx-box--animated',
			kind && `rcx-input-box--type-${kind}`,
			placeholderVisible && 'rcx-input-box--placeholder-visible',
			undecorated && 'rcx-input-box--undecorated',
			small && 'rcx-input-box--small',
			'rcx-input-box',
		]
			.filter(Boolean)
			.join(' '),
	);

	const shape = shapeOf(props);

	// One literal element per tag, as zero-runtime has to know the tag; what the consumer passes goes on that element
	if (isTextArea) {
		return (
			<InputFrame
				shape={shape}
				textarea
				hidden={Boolean(hidden)}
				invisible={Boolean(invisible)}
				className={classes}
				render={
					<textarea
						{...ariaAndDataAttributes(props)}
						{...pickWebTextInputHandlers(props)}
						ref={props.ref as TextAreaRef}
						id={props.id}
						title={props.title}
						role={props.role}
						hidden={hidden}
						name={props.name}
						value={props.value}
						defaultValue={props.defaultValue}
						placeholder={props.placeholder}
						autoCapitalize={props.autoCapitalize}
						autoComplete={props.autoComplete}
						autoCorrect={props.autoCorrect}
						// oxlint-disable-next-line jsx-a11y/no-autofocus -- the consumer's to set
						autoFocus={props.autoFocus}
						disabled={props.disabled}
						readOnly={props.readOnly}
						required={props.required}
						minLength={props.minLength}
						maxLength={props.maxLength}
						inputMode={props.inputMode}
						spellCheck={props.spellCheck}
						form={props.form}
						tabIndex={props.tabIndex}
						inert={props.inert}
						rows={props.rows}
						cols={1}
					/>
				}
			/>
		);
	}

	return (
		<InputFrame
			shape={shape}
			textarea={false}
			hidden={Boolean(hidden)}
			invisible={Boolean(invisible)}
			className={classes}
			render={
				<input
					{...ariaAndDataAttributes(props)}
					{...pickWebTextInputHandlers(props)}
					ref={props.ref as InputRef}
					id={props.id}
					title={props.title}
					role={props.role}
					hidden={hidden}
					type={type}
					size={props.htmlSize}
					name={props.name}
					value={props.value}
					defaultValue={props.defaultValue}
					placeholder={props.placeholder}
					autoCapitalize={props.autoCapitalize}
					autoComplete={props.autoComplete}
					autoCorrect={props.autoCorrect}
					// oxlint-disable-next-line jsx-a11y/no-autofocus -- the consumer's to set
					autoFocus={props.autoFocus}
					disabled={props.disabled}
					readOnly={props.readOnly}
					required={props.required}
					min={props.min}
					max={props.max}
					step={props.step}
					minLength={props.minLength}
					maxLength={props.maxLength}
					pattern={props.pattern}
					inputMode={props.inputMode}
					spellCheck={props.spellCheck}
					multiple={props.multiple}
					accept={props.accept}
					list={props.list}
					form={props.form}
					tabIndex={props.tabIndex}
					inert={props.inert}
				/>
			}
		/>
	);
}

export default Input;
