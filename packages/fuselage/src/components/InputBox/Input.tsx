export type InputType = 'color' | 'date' | 'datetime-local' | 'email' | 'file' | 'number' | 'password' | 'search' | 'text' | 'time' | 'url';

export type InputProps<TElement extends TextControlElement = InputElement> = CommonAttributes &
	WebAttributes<TElement> &
	WebTextInputHandlers<TElement> &
	TextControlAttributes &
	AriaAttributes & {
		role?: AriaRole;
		/** Renders a `textarea`. */
		is?: 'input' | 'textarea';
		/** The kind of `input`; a `textarea` has none. */
		type?: InputType;
		/** The `size` attribute, which with the `width` the box gives it sets the room it takes. */
		htmlSize?: number;
		hidden?: boolean;
		invisible?: boolean;
		/** Drops the border, background and padding of the box, for an input that sits inside another control. */
		undecorated?: boolean;
		/** Comes after the chips of a multiple select, or of an autocomplete, whatever its place in the document. */
		last?: boolean;
		/** Sits inside an input box wrapper, which draws the box and sizes the input by the room it leaves. */
		wrapped?: boolean;
		small?: boolean;
		/** Shows the placeholder colour for a value too. */
		placeholderVisible?: boolean;
	};

