// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const InputBoxWrapperFrame = styled(View, {
	...inputBoxWrapperFrame,
	variants: {
		layout: inputBoxWrapperLayouts,
		hidden: { true: { ...inputBoxWrapperHidden }, false: {} },
		invisible: { true: { ...inputBoxWrapperInvisible }, false: {} },
	},
});

/** The box that draws the border of an input with addons: a label, so a label inside it is a `span`. */
const InputBoxWrapper = (props: InputBoxWrapperProps) => {
	const { endAddonFlush, textarea, small, hidden, invisible } = props;
	const kind = textarea ? 'textarea' : 'input';
	const layout = small ? 'small' : (`${kind}${endAddonFlush ? '-flush' : ''}` as const);

	return (
		<LabelContext.Provider value={true}>
			<InputBoxWrapperFrame
				layout={layout}
				hidden={Boolean(hidden)}
				invisible={Boolean(invisible)}
				className={prependClassName(
					props.className,
					`rcx-box rcx-box--full rcx-label rcx-box--animated rcx-input-box__wrapper${endAddonFlush ? ' rcx-input-box__wrapper--end-addon-flush' : ''}`,
				)}
				// oxlint-disable-next-line jsx-a11y/label-has-associated-control -- it wraps the input its children render
				render={<label {...ariaAndDataAttributes(props)} ref={props.ref as LabelRef} id={props.id} title={props.title} hidden={hidden} />}
			>
				{props.children}
			</InputBoxWrapperFrame>
		</LabelContext.Provider>
	);
};

export default InputBoxWrapper;
