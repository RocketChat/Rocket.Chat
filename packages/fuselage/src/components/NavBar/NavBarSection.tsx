import { styled, View } from '@tamagui/web';
import type { ReactNode } from 'react';
import { Fragment } from 'react';
import { isElement } from 'react-is';
import flattenChildren from 'react-keyed-flatten-children';

import NavBarDivider from './NavBarDivider';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { pickWebPressHandlers } from '../../helpers/pickAttributes';
import { prependClassName } from '../../helpers/prependClassName';
import type { SpanAttributes, SpanPressHandlers } from '../../types/ElementAttributes';

export type NavbarSectionProps = SpanAttributes &
	SpanPressHandlers & {
		children?: ReactNode;
	};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const sectionFrame = {
	display: 'flex',
	flexDirection: 'row',
	alignItems: 'center',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	render: 'span',
} as const;

// end of generated

// Declared where they render: zero-runtime only erases a `styled()` whose every use is in its own module
const SectionFrame = styled(View, { ...sectionFrame });

const NavBarSection = (props: NavbarSectionProps) => {
	const groups = flattenChildren(props.children).filter(isElement);

	return (
		<SectionFrame
			className={prependClassName(props.className, 'rcx-navbar-section')}
			render={<span {...ariaAndDataAttributes(props)} {...pickWebPressHandlers(props)} ref={props.ref} id={props.id} title={props.title} />}
		>
			{groups.map((child, index) => (
				<Fragment key={index}>
					{child}
					{index < groups.length - 1 && <NavBarDivider />}
				</Fragment>
			))}
		</SectionFrame>
	);
};

export default NavBarSection;
