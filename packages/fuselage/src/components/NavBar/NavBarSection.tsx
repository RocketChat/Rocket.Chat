import { styled, View } from '@tamagui/web';
import { Fragment } from 'react';
import { isElement } from 'react-is';
import flattenChildren from 'react-keyed-flatten-children';

import type { NavBarSectionContract } from './NavBar.contract';
import NavBarDivider from './NavBarDivider';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { pickWebContainerHandlers } from '../../helpers/pickWebContainerHandlers';
import { prependClassName } from '../../helpers/prependClassName';
import type { WebSpanProps } from '../../types/WebBoundProps';

export type NavbarSectionProps = WebSpanProps<NavBarSectionContract>;

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const sectionFrame = {
	display: 'flex',
	flexDirection: 'row',
	alignItems: 'center',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	render: 'span',
} as const;

// end of generated

const SectionFrame = styled(View, {
	...sectionFrame,
});

const NavBarSection = (props: NavbarSectionProps) => {
	const groups = flattenChildren(props.children).filter(isElement);

	return (
		<SectionFrame
			className={prependClassName(props.className, 'rcx-navbar-section')}
			render={
				<span
					{...ariaAndDataAttributes(props)}
					{...pickWebContainerHandlers(props)}
					ref={props.ref}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{groups.map((child, index) => (
				<Fragment key={index}>
					{child}
					{index < groups.length - 1 && <NavBarDivider />}
				</Fragment>
			))}
		</SectionFrame>
	);
};

export default NavBarSection;
