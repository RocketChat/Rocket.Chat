import { styled, Text } from '@tamagui/web';
import type { ReactNode } from 'react';

import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { cx } from '../../helpers/composeClassNames';
import type { ActionAccessibilityAttributes, PartAttributes, WebPressHandlers } from '../../types/ElementAttributes';

export type MessageHighlightProps = PartAttributes<HTMLSpanElement> &
	ActionAccessibilityAttributes &
	Pick<WebPressHandlers<HTMLSpanElement>, 'onClick' | 'onKeyDown' | 'onMouseEnter'> & {
		'clickable'?: boolean;
		'variant'?: 'critical' | 'relevant' | 'other' | 'link';
		'children': ReactNode;
		// The mentioned user, which the app's user card reads back
		'data-uid'?: string;
	};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

// Declared where they render: zero-runtime only erases a `styled()` whose every use is in its own module
const MessageHighlightFrame = styled(Text, {
	render: 'span',
	whiteSpace: 'nowrap',
	fontWeight: 500,
	borderRadius: {
		'focus-visible': 'var(--rcx-border-radius-medium, 0.25rem)',
	},
	outlineWidth: {
		'focus-visible': '1px',
	},
	outlineStyle: {
		'default': 'none',
		'focus-visible': 'solid',
	},
	outlineColor: {
		'focus-visible': 'var(--rcx-color-stroke-highlight, #156ff5)',
	},
	boxShadow: {
		'focus-visible': '0 0 0 calc(1px + 2px) var(--rcx-color-stroke-extra-light-highlight, #d1ebfe)',
	},
	variants: {
		tone: {
			critical: {
				color: 'var(--rcx-message-highlight-colors-critical-color, var(--rcx-color-status-font-on-danger, #9b1325))',
			},
			relevant: {
				color: 'var(--rcx-message-highlight-colors-relevant-color, var(--rcx-color-status-font-on-service-1, #974809))',
			},
			other: {
				color: 'var(--rcx-message-highlight-colors-other-color, var(--rcx-color-status-font-on-warning, #895f00))',
			},
			link: {
				color: 'var(--rcx-message-highlight-colors-link-color, var(--rcx-color-status-font-on-info, #095ad2))',
			},
		},
		clickable: {
			true: {
				cursor: 'pointer',
				textDecorationLine: {
					hover: 'underline',
				},
			},
			false: {},
		},
	},
});

// end of generated

function MessageHighlight(props: MessageHighlightProps) {
	const { variant = 'other', className, clickable, children } = props;
	const modifiers = [variant, clickable && 'clickable']
		.filter(Boolean)
		.map((modifier) => `rcx-message__highlight--${modifier}`)
		.join(' ');

	return (
		<MessageHighlightFrame
			tone={variant}
			clickable={Boolean(clickable)}
			className={cx(`rcx-message__highlight ${modifiers}`, className)}
			render={
				<span
					{...ariaAndDataAttributes(props)}
					ref={props.ref}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
					onClick={props.onClick}
					onKeyDown={props.onKeyDown}
					onMouseEnter={props.onMouseEnter}
				/>
			}
		>
			{children}
		</MessageHighlightFrame>
	);
}

export default MessageHighlight;
