import { styled, Text } from '@tamagui/web';
import type { ReactNode } from 'react';

import { ariaAndDataAttributes } from '../../../helpers/ariaAndDataAttributes';
import { cx } from '../../../helpers/composeClassNames';
import { pickWebPressHandlers } from '../../../helpers/pickAttributes';
import type { DivActionAttributes } from '../../../types/ElementAttributes';

export type MessageGenericPreviewDescriptionProps = {
	children?: ReactNode;
	/** Wraps the description onto two lines and cuts what is left, where it would otherwise stay on one. */
	clamp?: boolean;
} & DivActionAttributes;

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const messageGenericPreviewDescriptionFrame = {
	flexBasis: 'auto',
	whiteSpace: 'inherit',
	wordWrap: 'inherit',
	display: 'block',
	flexDirection: 'row',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	render: 'div',
	marginBlockEnd: '4px',
	color: 'var(--rcx-message-generic-preview-description-color, var(--rcx-color-font-default, #2f343d))',
	fontSize: '0.75rem',
	fontWeight: 400,
	lineHeight: '1rem',
	letterSpacing: '0rem',
} as const;

const messageGenericPreviewDescriptionLines = {
	single: {
		overflow: 'hidden',
		textOverflow: 'ellipsis',
		whiteSpace: 'nowrap',
	},
	clamp: {
		whiteSpace: 'normal',
	},
} as const;

// end of generated

const DescriptionFrame = styled(Text, {
	...messageGenericPreviewDescriptionFrame,
	variants: { lines: messageGenericPreviewDescriptionLines },
});

const MessageGenericPreviewDescription = (props: MessageGenericPreviewDescriptionProps) => {
	const { children, clamp = false, className } = props;

	// `numberOfLines` has to be a literal and `render` an inline element for the zero-runtime compiler, so the clamp is its own branch
	if (clamp) {
		return (
			<DescriptionFrame
				lines='clamp'
				numberOfLines={2}
				className={cx('rcx-message-generic-preview__description rcx-message-generic-preview__description--clamp', className)}
				render={
					<div
						{...ariaAndDataAttributes(props)}
						{...pickWebPressHandlers(props)}
						ref={props.ref}
						id={props.id}
						title={props.title}
						role={props.role}
						tabIndex={props.tabIndex}
					/>
				}
			>
				{children}
			</DescriptionFrame>
		);
	}

	return (
		<DescriptionFrame
			lines='single'
			className={cx('rcx-message-generic-preview__description', className)}
			render={
				<div
					{...ariaAndDataAttributes(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{children}
		</DescriptionFrame>
	);
};

export default MessageGenericPreviewDescription;
