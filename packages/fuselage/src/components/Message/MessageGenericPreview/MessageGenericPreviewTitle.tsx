import { styled, Text } from '@tamagui/web';
import type { AnchorHTMLAttributes, ReactNode, Ref } from 'react';

import { ariaAndDataAttributes } from '../../../helpers/ariaAndDataAttributes';
import { cx } from '../../../helpers/composeClassNames';
import type { PartAttributes, WebPressHandlers } from '../../../types/ElementAttributes';

export type MessageGenericPreviewTitleProps = PartAttributes<HTMLSpanElement | HTMLAnchorElement> &
	Pick<WebPressHandlers<HTMLElement>, 'onClick'> &
	Pick<AnchorHTMLAttributes<HTMLAnchorElement>, 'download'> & {
		children?: ReactNode;
		/** Renders the title as a link to this URL, opened in a new tab. */
		externalUrl?: string;
	};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

// Declared where they render: zero-runtime only erases a `styled()` whose every use is in its own module
const MessageGenericPreviewTitleFrame = styled(Text, {
	render: 'span',
	display: 'block',
	wordWrap: 'normal',
	overflow: 'hidden',
	textOverflow: 'ellipsis',
	whiteSpace: 'nowrap',
	fontSize: '0.875rem',
	fontWeight: 400,
	lineHeight: '1.25rem',
	letterSpacing: '0rem',
	marginBlockEnd: '4px',
	color: 'var(--rcx-message-generic-preview-title-color, var(--rcx-color-font-default, #2f343d))',
});

// end of generated

const MessageGenericPreviewTitle = (props: MessageGenericPreviewTitleProps) => {
	const { externalUrl, children, className } = props;

	if (externalUrl) {
		return (
			<MessageGenericPreviewTitleFrame
				className={cx('rcx-message-generic-preview__title rcx-message-generic-preview__title-link', className)}
				render={
					<a
						{...ariaAndDataAttributes(props)}
						href={externalUrl}
						target='_blank'
						// The ref is typed for both tags, each branch renders one
						ref={props.ref as Ref<HTMLAnchorElement>}
						id={props.id}
						title={props.title}
						download={props.download}
						onClick={props.onClick}
					/>
				}
			>
				{children}
			</MessageGenericPreviewTitleFrame>
		);
	}

	return (
		<MessageGenericPreviewTitleFrame
			className={cx('rcx-message-generic-preview__title', className)}
			render={
				// oxlint-disable-next-line jsx-a11y/click-events-have-key-events, jsx-a11y/no-static-element-interactions -- the consumer's handler, as on develop
				<span {...ariaAndDataAttributes(props)} ref={props.ref} id={props.id} title={props.title} onClick={props.onClick} />
			}
		>
			{children}
		</MessageGenericPreviewTitleFrame>
	);
};

export default MessageGenericPreviewTitle;
