import { styled, Text } from '@tamagui/web';
import type { ReactNode } from 'react';

import { useMessageContext } from './MessageContext';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { cx } from '../../helpers/composeClassNames';
import { pickWebPressHandlers } from '../../helpers/pickAttributes';
import type { DivActionAttributes } from '../../types/ElementAttributes';

export type MessageBodyProps = DivActionAttributes & {
	children?: ReactNode;
	dir?: 'ltr' | 'rtl' | 'auto';
	/**
	 * Cuts the body at two lines, as in list previews.
	 */
	clamp?: 2;
};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const messageBodyFrame = {
	whiteSpace: 'inherit',
	wordWrap: 'inherit',
	render: 'div',
	display: 'block',
	overflow: 'hidden',
	paddingBlock: '2px',
	wordBreak: 'break-word',
	color: 'var(--rcx-color-font-default, #2f343d)',
	fontSize: '0.875rem',
	fontWeight: 400,
	lineHeight: '1.25rem',
	letterSpacing: '0rem',
} as const;

const messageBodyPending = {
	true: {
		opacity: 0.4,
	},
} as const;

// end of generated

// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const MessageBodyFrame = styled(Text, {
	...messageBodyFrame,
	variants: { pending: messageBodyPending },
});

const MessageBody = (props: MessageBodyProps) => {
	const pending = !!useMessageContext()?.pending;
	const classes = cx(props.clamp ? 'rcx-message-body rcx-message-body--clamp' : 'rcx-message-body', props.className);

	return props.clamp ? (
		<MessageBodyFrame
			pending={pending}
			numberOfLines={2}
			className={classes}
			render={
				<div
					{...ariaAndDataAttributes(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
					dir={props.dir}
				/>
			}
		>
			{props.children}
		</MessageBodyFrame>
	) : (
		<MessageBodyFrame
			pending={pending}
			className={classes}
			render={
				<div
					{...ariaAndDataAttributes(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
					dir={props.dir}
				/>
			}
		>
			{props.children}
		</MessageBodyFrame>
	);
};

export default MessageBody;
