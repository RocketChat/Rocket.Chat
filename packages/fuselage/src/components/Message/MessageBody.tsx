import { styled, Text } from '@tamagui/web';
import { memo, useContext } from 'react';

import type { MessageBodyContract } from './Message.contract';
import { MessagePendingContext } from './MessageContext';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { cx } from '../../helpers/composeClassNames';
import { pickFramePressHandlers } from '../../helpers/pickFramePressHandlers';
import { pickWebInteractionHandlers } from '../../helpers/pickWebInteractionHandlers';
import { pickWebPressHandlers } from '../../helpers/pickWebPressHandlers';
import type { WebDivProps } from '../../types/WebAttributes';

export type MessageBodyProps = WebDivProps<MessageBodyContract> & {
	dir?: 'ltr' | 'rtl' | 'auto';
};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const messageBodyFrame = {
	whiteSpace: 'inherit',
	wordWrap: 'inherit',
	display: 'block',
	overflow: 'hidden',
	paddingBlock: 2,
	wordBreak: 'break-word',
	color: '$rcx-font-default',
	fontSize: '0.875rem',
	lineHeight: '1.25rem',
	fontWeight: '400',
	letterSpacing: 0,
} as const;
const messageBodyPending = {
	opacity: 0.4,
} as const;

// end of generated

const BodyFrame = styled(Text, {
	render: 'div',
	...messageBodyFrame,
	variants: {
		pending: {
			true: { ...messageBodyPending },
			false: {},
		},
	},
});

const MessageBody = (props: MessageBodyProps) => {
	const pending = useContext(MessagePendingContext);

	// One branch per line count: the zero-runtime compiler takes `numberOfLines` only as a literal
	if (props.clamp) {
		return (
			<BodyFrame
				pending={pending}
				numberOfLines={2}
				className={cx('rcx-message-body rcx-message-body--clamp', props.className)}
				{...pickFramePressHandlers(props)}
				render={
					<div
						{...ariaAndDataAttributes(props)}
						{...pickWebInteractionHandlers(props)}
						{...pickWebPressHandlers(props)}
						ref={props.ref}
						id={props.id}
						title={props.title}
						role={props.role}
						tabIndex={props.tabIndex}
						dir={props.dir}
					/>
				}
			>
				{props.children}
			</BodyFrame>
		);
	}

	return (
		<BodyFrame
			pending={pending}
			className={cx('rcx-message-body', props.className)}
			{...pickFramePressHandlers(props)}
			render={
				<div
					{...ariaAndDataAttributes(props)}
					{...pickWebInteractionHandlers(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
					dir={props.dir}
				/>
			}
		>
			{props.children}
		</BodyFrame>
	);
};

export default memo(MessageBody);
