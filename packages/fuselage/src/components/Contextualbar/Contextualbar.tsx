import { styled, View } from '@tamagui/web';
import type { ReactNode } from 'react';

import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { pickWebPressHandlers } from '../../helpers/pickAttributes';
import { prependClassName } from '../../helpers/prependClassName';
import type { DivRef, ElementActionAttributes } from '../../types/ElementAttributes';

export type ContextualbarProps = ElementActionAttributes & {
	children?: ReactNode;
	/** Makes the bar as wide as its container, as when it is positioned over the room. */
	stretch?: boolean;
	/** How the bar is placed: in the flow beside the room, or over it. */
	position?: 'static' | 'relative' | 'absolute' | 'fixed';
};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const barFrame = {
	display: 'flex',
	flexDirection: 'column',
	alignItems: 'normal',
	flexShrink: 0,
	minWidth: 'auto',
	minHeight: 'auto',
	render: 'div',
	zIndex: 10,
	insetBlockStart: 0,
	insetInlineEnd: 0,
	height: '100%',
	color: 'var(--rcx-color-font-default, #2f343d)',
	backgroundColor: 'var(--rcx-color-surface-room, #ffffff)',
	borderInlineStartColor: 'var(--rcx-color-stroke-extra-light, #ebecef)',
	borderInlineStartWidth: '1px',
} as const;

const barPlacements = {
	static: {
		position: 'static',
	},
	relative: {
		position: 'relative',
	},
	absolute: {
		position: 'absolute',
	},
	fixed: {
		position: 'fixed',
	},
} as const;

const barStretch = {
	width: '100%',
} as const;

// end of generated

// Declared where they render: zero-runtime only erases a `styled()` whose every use is in its own module
const BarFrame = styled(View, {
	...barFrame,
	variants: {
		placement: barPlacements,
		stretch: { true: barStretch },
	},
});

/**
 * The `Contextualbar` has the purpose to persist and input information about the scope of the related page.
 */
function Contextualbar(props: ContextualbarProps) {
	const { stretch, position, children, className } = props;

	return (
		<BarFrame
			placement={position ?? 'static'}
			stretch={stretch}
			className={prependClassName(
				className,
				`rcx-box rcx-box--full${position ? ` rcx-vertical-bar--position-${position}` : ''}${stretch ? ' rcx-vertical-bar--stretch' : ''} rcx-vertical-bar`,
			)}
			render={
				<div
					{...ariaAndDataAttributes(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref as DivRef}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{children}
		</BarFrame>
	);
}

export default Contextualbar;
