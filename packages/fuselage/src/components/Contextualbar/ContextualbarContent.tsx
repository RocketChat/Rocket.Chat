import { styled, Text } from '@tamagui/web';
import type { ReactNode } from 'react';

import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { prependClassName } from '../../helpers/prependClassName';
import type { DivRef, SectionAttributes } from '../../types/ElementAttributes';

export type ContextualbarContentProps = SectionAttributes & {
	children?: ReactNode;
	/** Drops the inline padding, for content such as a list whose items bring their own. */
	flush?: boolean;
	/** Adds a 12px block padding, so the first and last items keep clear of the header and footer. */
	spaced?: boolean;
};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const contentFrame = {
	flexBasis: 'auto',
	whiteSpace: 'inherit',
	wordWrap: 'inherit',
	display: 'flex',
	flexDirection: 'column',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	render: 'div',
	overflowY: 'hidden',
	height: '100%',
	paddingInline: '24px',
} as const;

const contentPaddings = {
	'regular': {},
	'flush': {
		paddingInline: 0,
	},
	'spaced': {
		paddingBlock: '12px',
	},
	'flush-spaced': {
		paddingInline: 0,
		paddingBlock: '12px',
	},
} as const;

// end of generated

// Declared where they render: zero-runtime only erases a `styled()` whose every use is in its own module
const ContentFrame = styled(Text, {
	...contentFrame,
	variants: {
		gutter: contentPaddings,
	},
});

const gutterOf = (flush?: boolean, spaced?: boolean) => {
	if (flush) return spaced ? 'flush-spaced' : 'flush';
	return spaced ? 'spaced' : 'regular';
};

function ContextualbarContent(props: ContextualbarContentProps) {
	const { flush, spaced, children, className } = props;

	return (
		<ContentFrame
			gutter={gutterOf(flush, spaced)}
			className={prependClassName(
				className,
				`rcx-box rcx-box--full rcx-vertical-bar__content${flush ? ' rcx-vertical-bar__content--flush' : ''}${spaced ? ' rcx-vertical-bar__content--spaced' : ''}`,
			)}
			render={<div {...ariaAndDataAttributes(props)} ref={props.ref as DivRef} id={props.id} title={props.title} />}
		>
			{children}
		</ContentFrame>
	);
}

export default ContextualbarContent;
