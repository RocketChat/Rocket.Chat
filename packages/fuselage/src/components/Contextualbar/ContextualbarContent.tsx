import { styled, View } from '@tamagui/web';
import type { DOMAttributes, ReactNode, Ref } from 'react';

import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import type { PartAttributes } from '../../types/ElementAttributes';

export type ContextualbarContentProps = {
	/** Drops the inline padding, for content such as a list whose items bring their own. */
	flush?: boolean;
	/** Adds a 12px block padding, so the first and last items keep clear of the header and footer. */
	spaced?: boolean;
	children?: ReactNode;
} & PartAttributes<HTMLElement> &
	// The thread's file drop target starts on it
	Pick<DOMAttributes<HTMLElement>, 'onDragEnter'>;

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

// Declared where they render: zero-runtime only erases a `styled()` whose every use is in its own module
const ContextualbarContentFrame = styled(View, {
	display: 'flex',
	flexDirection: 'column',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	overflowY: 'hidden',
	height: '100%',
	variants: {
		padding: {
			'default': {
				paddingInline: '24px',
			},
			'flush': {
				paddingInline: 0,
			},
			'spaced': {
				paddingInline: '24px',
				paddingBlock: '12px',
			},
			'flush-spaced': {
				paddingInline: 0,
				paddingBlock: '12px',
			},
		},
	},
});

// end of generated

function ContextualbarContent(props: ContextualbarContentProps) {
	const { flush = false, spaced = false, className, children } = props;

	return (
		<ContextualbarContentFrame
			render={
				<div
					{...ariaAndDataAttributes(props)}
					// The ref is typed for any element the caller holds
					ref={props.ref as Ref<HTMLDivElement>}
					id={props.id}
					title={props.title}
					onDragEnter={props.onDragEnter}
				/>
			}
			padding={[flush && 'flush', spaced && 'spaced'].filter(Boolean).join('-') || 'default'}
			className={['rcx-box rcx-box--full', 'rcx-vertical-bar__content', className].filter(Boolean).join(' ')}
		>
			{children}
		</ContextualbarContentFrame>
	);
}

export default ContextualbarContent;
