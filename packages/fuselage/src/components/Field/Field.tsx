import { styled, View } from '@tamagui/web';
import { createContext } from 'react';
import type { ReactNode } from 'react';

import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { pickWebPressHandlers } from '../../helpers/pickAttributes';
import { prependClassName } from '../../helpers/prependClassName';
import type { ActionAccessibilityAttributes, DivAttributes, DivPressHandlers } from '../../types/ElementAttributes';

export const FieldContext = createContext(false);

export type FieldProps = DivAttributes & DivPressHandlers & Pick<ActionAccessibilityAttributes, 'role'> & { children?: ReactNode };

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const fieldFrame = {
	render: 'div',
	display: 'flex',
	flexDirection: 'column',
	flexWrap: 'nowrap',
	alignItems: 'stretch',
	flexShrink: 0,
	minWidth: 'auto',
	minHeight: 'auto',
	width: '100%',
} as const;

// end of generated

// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const FieldFrame = styled(View, fieldFrame);

/**
 * A `Field` is a wrapper representing an entry in a form.
 */
function Field(props: FieldProps) {
	return (
		<FieldContext.Provider value={true}>
			<FieldFrame
				className={prependClassName(props.className, 'rcx-box rcx-box--full rcx-field')}
				render={
					<div
						{...ariaAndDataAttributes(props)}
						{...pickWebPressHandlers(props)}
						ref={props.ref}
						id={props.id}
						title={props.title}
						role={props.role}
					/>
				}
			>
				{props.children}
			</FieldFrame>
		</FieldContext.Provider>
	);
}

export default Field;
