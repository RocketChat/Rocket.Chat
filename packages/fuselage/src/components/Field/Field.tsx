import { styled, View } from '@tamagui/web';
import { createContext } from 'react';

import type { FieldContract } from './Field.contract';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { pickFramePressHandlers } from '../../helpers/pickFramePressHandlers';
import { pickWebInteractionHandlers } from '../../helpers/pickWebInteractionHandlers';
import { pickWebPressHandlers } from '../../helpers/pickWebPressHandlers';
import { prependClassName } from '../../helpers/prependClassName';
import type { WebDivProps } from '../../types/WebElementAttributes';

export const FieldContext = createContext(false);

export type FieldProps = WebDivProps<FieldContract>;

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const fieldFrame = {
	render: 'div',
	display: 'flex',
	flexDirection: 'column',
	flexWrap: 'nowrap',
	alignItems: 'stretch',
	flexShrink: 0,
	minWidth: 'auto',
	minHeight: 'auto',
	width: '100%',
} as const;

// end of generated

const FieldFrame = styled(View, { ...fieldFrame });

/**
 * A `Field` is a wrapper representing an entry in a form.
 */
function Field(props: FieldProps) {
	return (
		<FieldContext.Provider value={true}>
			<FieldFrame
				className={prependClassName(props.className, 'rcx-box rcx-box--full rcx-field')}
				{...pickFramePressHandlers(props)}
				render={
					<div
						{...ariaAndDataAttributes(props)}
						{...pickWebInteractionHandlers(props)}
						{...pickWebPressHandlers(props)}
						ref={props.ref}
						id={props.id}
						title={props.title}
						role={props.role}
					/>
				}
			>
				{props.children}
			</FieldFrame>
		</FieldContext.Provider>
	);
}

export default Field;
