import { styled, View } from '@tamagui/web';
import type { ReactNode } from 'react';

import { FieldContext } from './Field';
import WithErrorWrapper from '../../helpers/WithErrorWrapper';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { pickWebPressHandlers } from '../../helpers/pickAttributes';
import { prependClassName } from '../../helpers/prependClassName';
import type { ActionAccessibilityAttributes, SpanAttributes, SpanPressHandlers } from '../../types/ElementAttributes';

export type FieldRowProps = SpanAttributes &
	SpanPressHandlers &
	Pick<ActionAccessibilityAttributes, 'role'> & {
		/** Packs the row's content at the end of the line. */
		justify?: 'end';
		children?: ReactNode;
	};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const fieldRowFrame = {
	render: 'span',
	display: 'flex',
	flexDirection: 'row',
	flexWrap: 'nowrap',
	justifyContent: 'space-between',
	alignItems: 'center',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	marginBlockStart: '4px',
	marginBlockEnd: '2px',
	color: 'var(--rcx-color-font-secondary-info, #6c737a)',
} as const;

const fieldRowEnd = {
	justifyContent: 'flex-end',
} as const;

// end of generated

// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const FieldRowFrame = styled(View, {
	...fieldRowFrame,
	variants: {
		justify: { end: { ...fieldRowEnd }, start: {} },
	},
});

const FieldRow = (props: FieldRowProps) => {
	const component = (
		<FieldRowFrame
			justify={props.justify === 'end' ? 'end' : 'start'}
			className={prependClassName(
				props.className,
				`rcx-box rcx-box--full rcx-field__row${props.justify === 'end' ? ' rcx-field__row--justify-end' : ''}`,
			)}
			render={
				<span
					{...ariaAndDataAttributes(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref}
					id={props.id}
					title={props.title}
					role={props.role}
				/>
			}
		>
			{props.children}
		</FieldRowFrame>
	);

	if (process.env.NODE_ENV === 'development') {
		return (
			<WithErrorWrapper context={FieldContext} parentComponent='Field' componentName={FieldRow.name}>
				{component}
			</WithErrorWrapper>
		);
	}

	return component;
};

export default FieldRow;
