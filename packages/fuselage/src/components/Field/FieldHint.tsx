import { styled, Text } from '@tamagui/web';
import type { ReactNode } from 'react';

import { FieldContext } from './Field';
import WithErrorWrapper from '../../helpers/WithErrorWrapper';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { pickWebPressHandlers } from '../../helpers/pickAttributes';
import { prependClassName } from '../../helpers/prependClassName';
import type { ActionAccessibilityAttributes, SpanAttributes, SpanPressHandlers } from '../../types/ElementAttributes';

export type FieldHintProps = SpanAttributes &
	SpanPressHandlers &
	Pick<ActionAccessibilityAttributes, 'role'> & {
		children?: ReactNode;
		/** Sanitized markup for the hint, in place of `children`. */
		dangerouslySetInnerHTML?: { __html: string };
	};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const fieldHintFrame = {
	flexBasis: 'auto',
	whiteSpace: 'inherit',
	wordWrap: 'inherit',
	render: 'span',
	display: 'inline',
	flexDirection: 'row',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	marginBlock: '2px',
	color: 'var(--rcx-color-font-secondary-info, #6c737a)',
	fontSize: '0.75rem',
	fontWeight: 400,
	lineHeight: '1rem',
	letterSpacing: '0rem',
} as const;

// end of generated

// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const FieldHintFrame = styled(Text, fieldHintFrame);

const FieldHint = (props: FieldHintProps) => {
	const component = (
		<FieldHintFrame
			className={prependClassName(props.className, 'rcx-box rcx-box--full rcx-box--with-inline-elements rcx-field__hint')}
			render={
				<span
					{...ariaAndDataAttributes(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref}
					id={props.id}
					title={props.title}
					role={props.role}
					dangerouslySetInnerHTML={props.dangerouslySetInnerHTML}
				/>
			}
		>
			{props.children}
		</FieldHintFrame>
	);

	if (process.env.NODE_ENV === 'development') {
		return (
			<WithErrorWrapper context={FieldContext} parentComponent='Field' componentName={FieldHint.name}>
				{component}
			</WithErrorWrapper>
		);
	}

	return component;
};

export default FieldHint;
