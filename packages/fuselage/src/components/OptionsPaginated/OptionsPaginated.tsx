export type OptionsPaginatedProps = Pick<
	ElementActionAttributes,
	'id' | 'className' | 'title' | 'role' | 'aria-label' | 'aria-labelledby'
> &
	DivAnimationHandlers &
	PositionedAttributes & {
		ref?: Ref<Element>;
		/** A number is a width in pixels; a string is any CSS size. */
		width?: OptionsSize;
		multiple?: boolean;
		options: { value: string | number; label: string; selected?: boolean }[];
		cursor: number;
		withTitle?: boolean;
		renderItem?: ComponentType<{
			role?: string;
			label?: ReactNode;
			title?: string;
			selected?: boolean;
			index?: number;
			focus?: boolean;
			value?: string | number;
			onMouseDown?: (e: MouseEvent<HtmlElementOf>) => void;
		}>;
		renderEmpty?: ElementType<object>;
		onSelect: (option: [unknown, string]) => void;
		endReached?: (start?: number, end?: number) => void;
	};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const optionsPaginatedFrame = {
	display: 'block',
	flexDirection: 'row',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	render: 'div',
	width: 'var(--rcx-options-width, auto)',
} as const;

// end of generated

// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const OptionsPaginatedFrame = styled(View, { ...optionsPaginatedFrame });

export const Empty = memo(() => <Option label='Empty' />);

export { CheckOption };

/**
 * An input for selection of options.
 */
export function OptionsPaginated(props: OptionsPaginatedProps) {
	const {
		withTitle,
		renderEmpty: EmptyComponent = Empty,
		options,
		cursor,
		renderItem: OptionComponent = Option,
		onSelect,
		endReached,
		width,
	} = props;
	const OptionsComponentWithData = ({ index, data }: { index: number; data: OptionsPaginatedProps['options'][0] }) => {
		const { value, label, selected } = data;
		return (
			<OptionComponent
				{...(withTitle && { title: label })}
				index={index}
				role='option'
				label={label}
				onMouseDown={(e) => {
					prevent(e);
					onSelect([value, label]);
					return false;
				}}
				key={value}
				value={value}
				selected={!!selected}
				focus={cursor === index || undefined} // FIXME: undefined???
			/>
		);
	};

	return (
		<OptionsPaginatedFrame
			className={cx('rcx-box rcx-box--full rcx-options', props.className)}
			render={
				<div
					{...ariaAndDataAttributes(props)}
					{...pickWebAnimationHandlers(props)}
					{...positionedCustomProperties(props, { '--rcx-options-width': width === undefined ? undefined : toCSSSize(width) })}
					ref={props.ref as DivRef}
					id={props.id}
					title={props.title}
					role={props.role}
				/>
			}
		>
			<PopoverSurface>
				{!options.length ? (
					<EmptyComponent />
				) : (
					<Virtuoso
						endReached={endReached}
						style={{ height: '144px' }}
						totalCount={options.length}
						data={options}
						// TODO Add a scroller element
						// components={{ Scroller: ScrollableContentWrapper }}
						itemContent={(index, data) => <OptionsComponentWithData index={index} data={data} />}
					/>
				)}
			</PopoverSurface>
		</OptionsPaginatedFrame>
	);
}

export const useVisible = (initialVisibility = AnimatedVisibility.HIDDEN) => {
	const [visible, setVisible] = useDebouncedState(initialVisibility, 10);
	const hide = useStableCallback(() => setVisible(AnimatedVisibility.HIDDEN));
	const show = useStableCallback(() => setVisible(AnimatedVisibility.VISIBLE));

	return [visible, hide, show];
};
