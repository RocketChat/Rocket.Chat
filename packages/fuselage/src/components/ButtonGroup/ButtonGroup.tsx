import { styled, View } from '@tamagui/web';
import type { AriaAttributes, AriaRole, DOMAttributes, ReactNode } from 'react';

import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import type { PartAttributes } from '../../types/ElementAttributes';

export type ButtonGroupProps = {
	align?: 'start' | 'center' | 'end';
	/** `equal` also gives every button the same width. */
	stretch?: boolean | 'equal';
	wrap?: boolean;
	vertical?: boolean;
	small?: boolean;
	large?: boolean;
	children?: ReactNode;
} & PartAttributes<HTMLDivElement> &
	// react-aria's toolbar hands its group the role, orientation, label and the captured handlers of its arrow keys
	{ role?: AriaRole } & Pick<AriaAttributes, 'aria-label' | 'aria-labelledby' | 'aria-orientation'> &
	Pick<DOMAttributes<HTMLDivElement>, 'onClick' | 'onKeyDownCapture' | 'onFocusCapture' | 'onBlurCapture'>;

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const smallGap = {
	gap: '4px',
} as const;
const mediumGap = {
	gap: '8px',
} as const;
const largeGap = {
	gap: '16px',
} as const;

// end of generated

// Declared where they render: zero-runtime only erases a `styled()` whose every use is in its own module
const ButtonGroupFrame = styled(View, {
	render: 'div',
	display: 'flex',
	flexDirection: 'row',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	flexWrap: 'nowrap',
	justifyContent: 'flex-start',
	alignItems: 'center',
	...mediumGap,
	variants: {
		spacing: {
			small: { ...smallGap },
			large: { ...largeGap },
			medium: {},
		},
		// Direction, wrap and stretch set overlapping flex properties, so each combination is one variant
		flow: {
			'row-nowrap-start': {},
			'row-nowrap-stretch': { alignItems: 'stretch', flexGrow: 1 },
			'row-wrap-start': { flexWrap: 'wrap' },
			'row-wrap-stretch': { flexWrap: 'wrap', alignItems: 'stretch', flexGrow: 1 },
			'column-nowrap-start': { flexDirection: 'column' },
			'column-nowrap-stretch': { flexDirection: 'column', alignItems: 'stretch', flexGrow: 1 },
			'column-wrap-start': { flexDirection: 'column', flexWrap: 'wrap' },
			'column-wrap-stretch': { flexDirection: 'column', flexWrap: 'wrap', alignItems: 'stretch', flexGrow: 1 },
		},
		justify: {
			start: { justifyContent: 'flex-start' },
			center: { justifyContent: 'center' },
			end: { justifyContent: 'flex-end' },
		},
	},
});

/**
 * A container for grouping buttons that semantically share a common action context.
 */
function ButtonGroup(props: ButtonGroupProps) {
	const { align = 'start', children, stretch, vertical, wrap, small, large, className } = props;
	const classes = [
		'rcx-button-group',
		stretch && 'rcx-button-group--stretch',
		stretch === 'equal' && 'rcx-button-group--stretch-equal',
		vertical && 'rcx-button-group--vertical',
		align && `rcx-button-group--align-${align}`,
		small && 'rcx-button-group--small',
		large && 'rcx-button-group--large',
		wrap && 'rcx-button-group--wrap',
		className,
	]
		.filter(Boolean)
		.join(' ');

	const spacing = [small && 'small', large && 'large'].find(Boolean) || 'medium';
	const flow = `${vertical ? 'column' : 'row'}-${wrap ? 'wrap' : 'nowrap'}-${stretch ? 'stretch' : 'start'}`;

	return (
		<ButtonGroupFrame
			spacing={spacing}
			flow={flow}
			justify={align}
			className={classes}
			render={
				// oxlint-disable-next-line jsx-a11y/click-events-have-key-events -- a toolbar hands its keys through onKeyDownCapture
				<div
					{...ariaAndDataAttributes(props)}
					role={props.role ?? 'group'}
					ref={props.ref}
					id={props.id}
					title={props.title}
					onClick={props.onClick}
					onKeyDownCapture={props.onKeyDownCapture}
					onFocusCapture={props.onFocusCapture}
					onBlurCapture={props.onBlurCapture}
				/>
			}
		>
			{children}
		</ButtonGroupFrame>
	);
}

export default ButtonGroup;
