import { styled, View } from '@tamagui/web';
import type { ReactElement, RefAttributes } from 'react';
import { useMemo } from 'react';

import { cx } from '../../helpers/composeClassNames';
import { frameProps } from '../../helpers/frameProps';
import type { CommonAttributes, TestAttributes } from '../../types/ElementAttributes';
import type { BoxProps } from '../Box';
import { Icon } from '../Icon';

export type ChevronProps = CommonAttributes<HTMLSpanElement> &
	TestAttributes &
	RefAttributes<HTMLSpanElement> & {
		size?: BoxProps['width'];
		up?: boolean;
		right?: boolean;
		left?: boolean;
		down?: boolean;
		top?: boolean;
		bottom?: boolean;
	};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

// Declared where they render: zero-runtime only erases a `styled()` whose every use is in its own module
const ChevronFrame = styled(View, {
	render: 'span',
	display: 'inline-flex',
	flexDirection: 'row',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	alignSelf: 'center',
	variants: {
		direction: {
			up: {
				transform: 'rotate(-180deg)',
			},
			down: {
				transform: 'rotate(0deg)',
			},
			right: {
				transform: 'rotate(-90deg)',
			},
			left: {
				transform: 'rotate(-270deg)',
			},
		},
	},
});

// end of generated

function Chevron(props: ChevronProps): ReactElement<ChevronProps> {
	const { up, right, down, left, size, className } = props;
	const directions = [
		['left', left],
		['right', right],
		['down', down],
		['up', up],
	] as const;
	const children = useMemo(() => <Icon name='chevron-down' size={size} />, [size]);
	const attributes = frameProps(props);

	return (
		<ChevronFrame
			direction={directions.find(([, on]) => on)?.[0]}
			className={cx(
				'rcx-box rcx-box--full',
				{ 'rcx-chevron--left': !!left, 'rcx-chevron--down': !!down, 'rcx-chevron--right': !!right, 'rcx-chevron--up': !!up },
				'rcx-chevron',
				className,
			)}
			ref={attributes.ref}
			id={attributes.id}
			title={attributes.title}
			data-qa={attributes['data-qa']}
			data-qa-id={attributes['data-qa-id']}
			data-qa-type={attributes['data-qa-type']}
			data-testid={attributes['data-testid']}
		>
			{children}
		</ChevronFrame>
	);
}

export default Chevron;
