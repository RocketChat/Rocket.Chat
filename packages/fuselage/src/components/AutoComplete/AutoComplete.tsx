export type AutoCompleteOption<TLabel> = {
	value: string;
	label: TLabel;
};

const getSelected = <TLabel,>(value: string | string[] | undefined, options: AutoCompleteOption<TLabel>[]) => {
	if (!value) {
		return [];
	}
	return typeof value === 'string'
		? options.filter((option) => option.value === value)
		: options?.filter((option) => value.includes(option.value));
};

const isSelectedValid =
	<TLabel,>(value: string | string[] | undefined) =>
	(selected: AutoCompleteOption<TLabel>) => {
		if (!value) {
			return false;
		}

		return typeof value === 'string' ? selected.value === value : value.includes(selected.value);
	};

/**
 * @deprecated Use `SelectFilteredProps` or `MultiSelectFilteredProps` instead.
 */
export type AutoCompleteProps<TLabel = ReactNode> = CommonAttributes &
	Omit<WebAttributes<InputElement>, 'ref'> &
	Omit<WebTextInputHandlers<InputElement>, 'onChange'> &
	Omit<TextControlAttributes, 'value'> &
	AriaAttributes & {
		role?: AriaRole;
		filter: string;
		setFilter?: (filter: string) => void;
		options?: AutoCompleteOption<TLabel>[];
		renderSelected?: ComponentType<{
			selected: AutoCompleteOption<TLabel>;
			onRemove?: (event: MouseEvent<ButtonElement>) => void;
		}>;
		onChange: (value: string | string[]) => void;
		renderItem?: ComponentType<{
			role?: string;
			label: TLabel;
			value: string;
			selected?: boolean;
			focus?: boolean;
			onMouseDown: MouseEventHandler;
		}>;
		renderEmpty?: ComponentType<{
			customEmpty?: string;
		}>;
		placeholder?: string;
		error?: boolean;
		disabled?: boolean;
		multiple?: boolean;
		value?: string | string[];
	} & RefAttributes<InputElement>;

