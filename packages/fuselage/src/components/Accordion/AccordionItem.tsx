// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const AccordionItemFrame = styled(View, accordionItemFrame);

const AccordionBar = styled(View, {
	...accordionBarFrame,
	variants: {
		state: accordionBarStates,
	},
});

const AccordionTitle = styled(Text, accordionTitleFrame);

const AccordionPanel = styled(Text, {
	...accordionPanelFrame,
	variants: {
		panel: accordionPanelStates,
	},
});

const AccordionItem = (props: AccordionItemProps) => {
	const {
		children,
		defaultExpanded,
		disabled = false,
		expanded: propExpanded,
		tabIndex = 0,
		title,
		noncollapsible = !title,
		onToggle,
		className,
	} = props;
	const { barProps, titleId, panelId, panelExpanded, expanded } = useCollapse({
		expanded: propExpanded,
		defaultExpanded,
		disabled,
		noncollapsible,
		tabIndex,
		onToggle,
	});

	const collapsible = 'onClick' in barProps;
	const state = (disabled && 'disabled') || (collapsible && barProps.tabIndex !== undefined ? 'interactive' : 'plain');

	return (
		<AccordionItemFrame
			className={prependClassName(className, 'rcx-box rcx-box--full rcx-accordion-item')}
			render={<section {...ariaAndDataAttributes(props)} />}
		>
			{title ? (
				<AccordionBar
					state={state}
					className={`rcx-box rcx-box--full rcx-box--animated rcx-accordion-item__bar${disabled ? ' rcx-accordion-item__bar--disabled' : ''}`}
					render={
						<div
							{...ariaAndDataAttributes(barProps)}
							role='button'
							tabIndex={collapsible ? barProps.tabIndex : undefined}
							onClick={collapsible ? barProps.onClick : undefined}
							onKeyDown={collapsible ? barProps.onKeyDown : undefined}
						/>
					}
				>
					<AccordionTitle className='rcx-box rcx-box--full rcx-accordion-item__title' render={<h2 id={titleId} />}>
						{title}
					</AccordionTitle>
					{!noncollapsible && <Chevron size='x24' up={expanded} />}
				</AccordionBar>
			) : null}
			<AccordionPanel
				panel={panelExpanded ? 'expanded' : 'collapsed'}
				className={`rcx-box rcx-box--full rcx-box--animated rcx-accordion-item__panel${panelExpanded ? ' rcx-accordion-item__panel--expanded' : ''}`}
				render={<div id={panelId} />}
			>
				{children}
			</AccordionPanel>
		</AccordionItemFrame>
	);
};

export default AccordionItem;
