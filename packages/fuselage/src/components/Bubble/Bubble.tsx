import type { Keys as IconName } from '@rocket.chat/icons';
import { styled, View } from '@tamagui/web';
import type { AriaAttributes, AriaRole, ReactNode } from 'react';

import { BubbleButton, type BubbleButtonAttributes } from './BubbleButton';
import { BubbleItem } from './BubbleItem';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import type { PartAttributes } from '../../types/ElementAttributes';

export type BubbleProps = {
	secondary?: boolean;
	children: ReactNode;
	small?: boolean;
	onClick?: () => void;
	icon?: IconName;
	onDismiss?: () => void;
	contentProps?: BubbleButtonAttributes;
	dismissProps?: BubbleButtonAttributes;
	// A bubble that announces a state is a live region
	role?: AriaRole;
} & PartAttributes<HTMLDivElement> &
	Pick<AriaAttributes, 'aria-label' | 'aria-live'>;

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

// Declared where they render: zero-runtime only erases a `styled()` whose every use is in its own module
const BubbleFrame = styled(View, {
	render: 'div',
	display: 'flex',
	flexDirection: 'row',
	alignItems: 'center',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	overflow: 'hidden',
});

// end of generated

const Bubble = (props: BubbleProps) => {
	const { secondary, children, onClick, icon, onDismiss, small, contentProps, dismissProps, className } = props;

	return (
		<BubbleFrame
			render={<div {...ariaAndDataAttributes(props)} ref={props.ref} id={props.id} title={props.title} role={props.role} />}
			className={['rcx-bubble', 'rcx-box', 'rcx-box--full', onDismiss && 'rcx-bubble__group', small && 'rcx-bubble--small', className]
				.filter(Boolean)
				.join(' ')}
		>
			{onClick ? (
				<BubbleButton onClick={onClick} secondary={secondary} icon={icon} label={children} {...contentProps} />
			) : (
				<BubbleItem secondary={secondary} icon={icon} label={children} {...contentProps} />
			)}
			{onDismiss && (
				<BubbleButton
					onClick={onDismiss}
					secondary={secondary}
					icon='cross-small'
					{...{ 'aria-label': `Dismiss ${children}`, ...dismissProps }}
				/>
			)}
		</BubbleFrame>
	);
};

export default Bubble;
