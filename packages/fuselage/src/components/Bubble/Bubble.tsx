import type { Keys as IconName } from '@rocket.chat/icons';
import { styled, View } from '@tamagui/web';
import type { AllHTMLAttributes, ButtonHTMLAttributes, ReactNode } from 'react';

import { BubbleButton } from './BubbleButton';
import { BubbleItem } from './BubbleItem';

export type BubbleProps = {
	secondary?: boolean;
	children: ReactNode;
	small?: boolean;
	onClick?: () => void;
	icon?: IconName;
	onDismiss?: () => void;
	contentProps?: Omit<ButtonHTMLAttributes<HTMLButtonElement>, 'onClick'>;
	dismissProps?: Omit<ButtonHTMLAttributes<HTMLButtonElement>, 'onClick'>;
} & Omit<AllHTMLAttributes<HTMLDivElement>, 'onClick'>;

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

// Declared where they render: zero-runtime only erases a `styled()` whose every use is in its own module
const BubbleFrame = styled(View, {
	render: 'div',
	display: 'flex',
	flexDirection: 'row',
	alignItems: 'center',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	overflow: 'hidden',
});

// end of generated

const Bubble = ({ secondary, children, onClick, icon, onDismiss, small, contentProps, dismissProps, className, ...props }: BubbleProps) => (
	<BubbleFrame
		// The caller's attributes go on the element `render` names: zero-runtime rejects spreads on a frame
		render={<div {...props} />}
		className={['rcx-bubble', 'rcx-box', 'rcx-box--full', onDismiss && 'rcx-bubble__group', small && 'rcx-bubble--small', className]
			.filter(Boolean)
			.join(' ')}
	>
		{onClick ? (
			<BubbleButton onClick={onClick} secondary={secondary} icon={icon} label={children} {...contentProps} />
		) : (
			<BubbleItem secondary={secondary} icon={icon} label={children} {...contentProps} />
		)}
		{onDismiss && (
			<BubbleButton
				onClick={onDismiss}
				secondary={secondary}
				icon='cross-small'
				{...{ 'aria-label': `Dismiss ${children}`, ...dismissProps }}
			/>
		)}
	</BubbleFrame>
);

export default Bubble;
