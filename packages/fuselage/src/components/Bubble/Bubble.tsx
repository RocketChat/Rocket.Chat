import type { Keys as IconName } from '@rocket.chat/icons';
import { styled, View } from '@tamagui/web';
import type { ReactNode } from 'react';

import { BubbleButton } from './BubbleButton';
import { BubbleItem } from './BubbleItem';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { pickWebPressHandlers } from '../../helpers/pickAttributes';
import { prependClassName } from '../../helpers/prependClassName';
import type { ActionAccessibilityAttributes, ButtonPartAttributes, DivAttributes, DivPressHandlers } from '../../types/ElementAttributes';

export type BubbleProps = {
	secondary?: boolean;
	children: ReactNode;
	small?: boolean;
	onClick?: () => void;
	icon?: IconName;
	onDismiss?: () => void;
	contentProps?: ButtonPartAttributes;
	dismissProps?: ButtonPartAttributes;
} & DivAttributes &
	Pick<ActionAccessibilityAttributes, 'role' | 'aria-label' | 'aria-live'> &
	Omit<DivPressHandlers, 'onClick'>;

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const bubbleFrame = {
	display: 'flex',
	flexDirection: 'row',
	alignItems: 'center',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	render: 'div',
	overflow: 'hidden',
} as const;

// end of generated

// Declared where they render: zero-runtime only erases a `styled()` whose every use is in its own module
const BubbleFrame = styled(View, { ...bubbleFrame });

const Bubble = (props: BubbleProps) => {
	const { secondary, children, onClick, icon, onDismiss, small, contentProps, dismissProps, className } = props;
	// A lone icon asks for more room at the end; in a group the dismiss button sits there
	const trailing = !!icon && !onDismiss;

	return (
		<BubbleFrame
			className={prependClassName(
				className,
				`rcx-box rcx-box--full${small ? ' rcx-bubble--small' : ''}${onDismiss ? ' rcx-bubble__group' : ''} rcx-bubble`,
			)}
			render={
				<div
					{...ariaAndDataAttributes(props)}
					// The bubble's `onClick` belongs to its button, not to the container around it
					{...pickWebPressHandlers({ ...props, onClick: undefined })}
					ref={props.ref}
					id={props.id}
					title={props.title}
					role={props.role}
				/>
			}
		>
			{onClick ? (
				<BubbleButton
					onClick={onClick}
					secondary={secondary}
					icon={icon}
					label={children}
					small={small}
					trailing={trailing}
					segment={onDismiss ? 'first' : undefined}
					{...contentProps}
				/>
			) : (
				<BubbleItem
					secondary={secondary}
					icon={icon}
					label={children}
					small={small}
					trailing={trailing}
					segment={onDismiss ? 'first' : undefined}
					{...contentProps}
				/>
			)}
			{onDismiss && (
				<BubbleButton
					onClick={onDismiss}
					secondary={secondary}
					icon='cross-small'
					small={small}
					segment='last'
					aria-label={`Dismiss ${children}`}
					{...dismissProps}
				/>
			)}
		</BubbleFrame>
	);
};

export default Bubble;
