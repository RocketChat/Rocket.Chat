import { styled, View } from '@tamagui/web';
import type { ReactNode, Ref } from 'react';

import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { cx } from '../../helpers/composeClassNames';
import { pickWebPressHandlers } from '../../helpers/pickAttributes';
import type { DivActionAttributes, DivElement } from '../../types/ElementAttributes';
import { ItemGroup, type ItemGroupProps } from '../Item';
import { SidebarGroupTitle } from './SidebarGroupTitle';
import { useCollapse } from './hooks/useCollapse';

export type SidebarCollapseGroupProps = {
	expanded?: boolean;
	defaultExpanded?: boolean;
	title: string;
	empty?: boolean;
	badge?: ReactNode;
	menu?: ReactNode;
	children?: ReactNode;
	/** Reaches the panel that holds the rows, not the group's own element. */
	ref?: Ref<DivElement>;
} & Pick<ItemGroupProps, 'dragging'> &
	Omit<DivActionAttributes, 'title' | 'ref'>;

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const sidebarCollapseGroupFrame = {
	display: 'flex',
	flexDirection: 'column',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	render: 'div',
} as const;

const sidebarCollapseGroupDragging = {
	opacity: 0.4,
} as const;

// end of generated

// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const SidebarCollapseGroupFrame = styled(View, {
	...sidebarCollapseGroupFrame,
	variants: { dragging: { true: sidebarCollapseGroupDragging } },
});

export function SidebarCollapseGroup(props: SidebarCollapseGroupProps) {
	const {
		ref,
		expanded: propExpanded,
		defaultExpanded,
		tabIndex,
		children,
		badge,
		menu,
		title,
		empty,
		role = 'group',
		dragging,
		className,
	} = props;
	const { barProps, expanded, panelExpanded, panelId, titleId } = useCollapse({
		expanded: propExpanded,
		defaultExpanded,
		tabIndex,
	});

	const labelledBy = props['aria-label'] ? undefined : titleId;

	return (
		<SidebarCollapseGroupFrame
			dragging={!!dragging}
			className={cx('rcx-box rcx-box--full rcx-sidebar-collapse-group', { 'rcx-item-group--dragging': !!dragging }, className)}
			render={
				<div role={role} aria-labelledby={labelledBy} {...ariaAndDataAttributes(props)} {...pickWebPressHandlers(props)} id={props.id} />
			}
		>
			<SidebarGroupTitle
				expanded={expanded}
				empty={empty}
				title={title}
				titleId={titleId}
				badge={badge}
				menu={menu}
				barProps={barProps}
				role='button'
			/>
			<ItemGroup
				role='list'
				aria-labelledby={titleId}
				ref={ref}
				hidden={!panelExpanded}
				className={cx(
					'rcx-sidebar-collapse-group__panel rcx-box--animated',
					panelExpanded && 'rcx-sidebar-collapse-group__panel--expanded',
				)}
				id={panelId}
			>
				{children}
			</ItemGroup>
		</SidebarCollapseGroupFrame>
	);
}
