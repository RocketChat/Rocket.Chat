import { styled, View } from '@tamagui/web';
import type { AriaAttributes, AriaRole, DOMAttributes, ReactNode } from 'react';

import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { cx } from '../../helpers/composeClassNames';
import type { PartAttributes } from '../../types/ElementAttributes';
import { ItemGroup } from '../Item';
import { SidebarGroupTitle } from './SidebarGroupTitle';
import { useCollapse } from './hooks/useCollapse';

type SidebarCollapseGroupProps = {
	expanded?: boolean;
	defaultExpanded?: boolean;
	/** The bar's place in the focus order. */
	tabIndex?: number;
	title: string;
	empty?: boolean;
	badge?: ReactNode;
	menu?: ReactNode;
	role?: AriaRole;
	children?: ReactNode;
} & Omit<PartAttributes<HTMLDivElement>, 'title'> &
	Pick<AriaAttributes, 'aria-label' | 'aria-labelledby'> &
	// The room list toggles a group on its bar's click and keys, and mounts the group's menu on focus or hover
	Pick<DOMAttributes<HTMLDivElement>, 'onClick' | 'onKeyDown' | 'onFocus' | 'onPointerEnter'>;

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const SidebarCollapseGroupFrame = styled(View, {
	render: 'div',
	position: 'static',
	display: 'flex',
	flexDirection: 'column',
	flexShrink: 1,
	alignItems: 'normal',
	minWidth: 'auto',
	minHeight: 'auto',
	boxSizing: 'border-box',
	flexWrap: 'nowrap',
});

// end of generated

export function SidebarCollapseGroup(props: SidebarCollapseGroupProps) {
	const { ref, expanded: propExpanded, defaultExpanded, tabIndex, children, badge, menu, title, empty, role = 'group', className } = props;
	const { barProps, expanded, panelExpanded, panelId, titleId } = useCollapse({
		expanded: propExpanded,
		defaultExpanded,
		tabIndex,
	});

	const labelledBy = props['aria-labelledby'] ?? (props['aria-label'] ? undefined : titleId);

	return (
		<SidebarCollapseGroupFrame
			render={
				<div
					{...ariaAndDataAttributes(props)}
					aria-labelledby={labelledBy}
					id={props.id}
					role={role}
					onClick={props.onClick}
					onKeyDown={props.onKeyDown}
					onFocus={props.onFocus}
					onPointerEnter={props.onPointerEnter}
				/>
			}
			className={cx('rcx-box rcx-box--full rcx-sidebar-collapse-group', className)}
		>
			<SidebarGroupTitle
				expanded={expanded}
				empty={empty}
				title={title}
				titleId={titleId}
				badge={badge}
				menu={menu}
				barProps={barProps}
				role='button'
			/>
			<ItemGroup
				role='list'
				aria-labelledby={titleId}
				ref={ref}
				className={cx(
					'rcx-sidebar-collapse-group__panel rcx-box--animated',
					panelExpanded && 'rcx-sidebar-collapse-group__panel--expanded',
				)}
				id={panelId}
			>
				{children}
			</ItemGroup>
		</SidebarCollapseGroupFrame>
	);
}
