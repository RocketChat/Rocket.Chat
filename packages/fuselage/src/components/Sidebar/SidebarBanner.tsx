export const SidebarBanner = (props: SidebarBannerProps) => {
	const { title, linkText, linkProps, variant = 'default', addon, onClose, closeLabel = 'Close', children, className } = props;

	return (
		<BannerFrame
			tone={variant}
			className={prependClassName(className, `rcx-box rcx-box--full rcx-sidebar-banner rcx-sidebar-banner--${variant}`)}
			render={<div {...ariaAndDataAttributes(props)} ref={props.ref} id={props.id} onClick={props.onClick} />}
		>
			<div className='rcx-box rcx-box--full rcx-sidebar-banner__content'>
				{title && <TitleFrame className='rcx-box rcx-box--full rcx-sidebar-banner__title'>{title}</TitleFrame>}
				{linkText &&
					(linkProps?.href ? (
						<AnchorFrame
							className='rcx-box rcx-box--full rcx-sidebar-banner__link'
							render={
								<a
									href={linkProps.href}
									target={linkProps.target}
									rel={linkProps.rel}
									tabIndex={linkProps.tabIndex}
									id={linkProps.id}
									title={linkProps.title}
									onClick={linkProps.onClick}
								/>
							}
						>
							{linkText}
						</AnchorFrame>
					) : (
						<ButtonFrame
							className='rcx-box rcx-box--full rcx-sidebar-banner__link'
							render={
								<button
									type='button'
									id={linkProps?.id}
									title={linkProps?.title}
									tabIndex={linkProps?.tabIndex}
									onClick={linkProps?.onClick}
								/>
							}
						>
							{linkText}
						</ButtonFrame>
					))}
				{children}
			</div>
			<AddonFrame className='rcx-box rcx-box--full rcx-sidebar-banner__addon'>
				{addon}
				{onClose && <IconButton aria-label={closeLabel} onClick={onClose} size='tiny' icon='cross' />}
			</AddonFrame>
		</BannerFrame>
	);
};
