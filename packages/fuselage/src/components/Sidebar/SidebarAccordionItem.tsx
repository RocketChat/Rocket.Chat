const SidebarAccordionItem = (props: SidebarAccordionItemProps) => {
	const { children, title, badge, noncollapsible, disabled, expanded: propExpanded, defaultExpanded, tabIndex, className } = props;
	const { barProps, expanded, panelExpanded, panelId, titleId } = useCollapse({
		expanded: propExpanded,
		defaultExpanded,
		tabIndex,
		disabled,
		noncollapsible,
	});

	let barMode: 'disabled' | 'static' | 'interactive' = 'interactive';
	if (disabled) {
		barMode = 'disabled';
	} else if (noncollapsible) {
		barMode = 'static';
	}

	return (
		<SectionFrame
			className={prependClassName(className, 'rcx-box rcx-box--full rcx-sidebar-accordion-item')}
			render={<section {...ariaAndDataAttributes(props)} {...pickWebPressHandlers(props)} ref={props.ref} id={props.id} />}
		>
			<BarFrame
				mode={barMode}
				className={`rcx-box rcx-box--full rcx-sidebar-accordion-item__bar rcx-box--animated${disabled ? ' rcx-sidebar-accordion-item__bar--disabled' : ''}`}
				render={
					<div
						role='button'
						aria-controls={barProps['aria-controls']}
						aria-expanded={barProps['aria-expanded']}
						aria-disabled={barProps['aria-disabled']}
						aria-labelledby={barProps['aria-labelledby']}
						tabIndex={barProps.tabIndex}
						onClick={barProps.onClick}
						onKeyDown={barProps.onKeyDown}
					/>
				}
			>
				{!noncollapsible && (
					<ChevronFrame className='rcx-sidebar-accordion-item__chevron'>
						<Chevron size='x16' right={!expanded} />
					</ChevronFrame>
				)}
				{title && (
					<TitleFrame className='rcx-sidebar-accordion-item__title' render={<h5 id={titleId} />}>
						{title}
					</TitleFrame>
				)}
				{!expanded && badge && badge}
			</BarFrame>
			<PanelFrame
				expanded={!!panelExpanded}
				className={`rcx-sidebar-accordion-item__panel rcx-box--animated${panelExpanded ? ' rcx-sidebar-accordion-item__panel--expanded' : ''}`}
				render={<div id={panelId} />}
			>
				{children}
			</PanelFrame>
		</SectionFrame>
	);
};

export default SidebarAccordionItem;
