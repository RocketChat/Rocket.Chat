// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const SidebarGroupHeadingFrame = styled(View, {
	...sidebarGroupHeadingFrame,
	variants: { tone: sidebarGroupHeadingTones },
});

const SidebarGroupTitleFrame = styled(Text, {
	...sidebarGroupTitleFrame,
	variants: { unread: { true: sidebarGroupTitleUnread } },
});

/**
 * The header of a sidebar group. It renders an `ItemGroupHeader`, so its menu reveals on hover like a row's.
 */
export const SidebarGroupTitle = ({
	title,
	titleId,
	badge,
	menu,
	barProps,
	expanded,
	empty,
	role,
	className,
	...props
}: SidebarGroupTitleProps) => {
	const collapsed = !expanded;
	const unread = collapsed && !!badge;
	const isEmpty = collapsed && !!empty;
	let tone: 'unread' | 'empty' | undefined;
	if (unread) tone = 'unread';
	else if (isEmpty) tone = 'empty';

	return (
		<ItemGroupHeader
			{...props}
			inset='md'
			interactive
			padding='large'
			className={cx(
				'rcx-sidebar-collapse-group__bar',
				isEmpty && 'rcx-sidebar-collapse-group__bar--empty',
				unread && 'rcx-sidebar-collapse-group__bar--unread',
				className,
			)}
		>
			<ItemGroupTitle
				role={role}
				ring='border'
				aria-controls={barProps?.['aria-controls']}
				aria-expanded={barProps?.['aria-expanded']}
				aria-disabled={barProps?.['aria-disabled']}
				aria-labelledby={barProps?.['aria-labelledby']}
				aria-label={barProps?.['aria-label']}
				tabIndex={barProps?.tabIndex}
				onClick={barProps?.onClick}
				onKeyDown={barProps?.onKeyDown}
				className='rcx-sidebar-collapse-group__bar-button'
			>
				<SidebarGroupHeadingFrame tone={tone} className='rcx-sidebar-collapse-group__heading'>
					{title && (
						<SidebarGroupTitleFrame unread={unread} className='rcx-sidebar-collapse-group__title' id={titleId} render={<h4 />}>
							{title}
						</SidebarGroupTitleFrame>
					)}
					{expanded !== undefined && <Chevron size='x20' right={!expanded} />}
				</SidebarGroupHeadingFrame>
				{!expanded && badge && badge}
			</ItemGroupTitle>
			{menu}
		</ItemGroupHeader>
	);
};
