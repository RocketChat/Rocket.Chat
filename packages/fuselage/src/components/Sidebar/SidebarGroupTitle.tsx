export type SidebarGroupTitleProps = {
	expanded?: boolean;
	empty?: boolean;
	title?: string;
	titleId?: string;
	badge?: ReactNode;
	menu?: ReactNode;
	/** What `useCollapse` returns for the bar, and the label a caller may add. */
	barProps?: Pick<AriaAttributes, 'aria-controls' | 'aria-expanded' | 'aria-disabled' | 'aria-labelledby' | 'aria-label'> & {
		tabIndex?: number;
		onClick?: (event: MouseEvent<HtmlElementOf>) => void;
		onKeyDown?: KeyboardEventHandler;
	};
} & ItemPartAttributes;

