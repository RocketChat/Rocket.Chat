// end of generated

// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const ItemDescriptionFrame = styled(Text, {
	...itemDescriptionFrame,
	variants: itemDescriptionVariants,
});

const scaleOf = (large: boolean, highlighted: boolean) => {
	if (large) return highlighted ? 'large-highlighted' : 'large';
	return highlighted ? 'highlighted' : undefined;
};

/**
 * The secondary line of an `Item`, such as a last message preview or a username.
 */
const ItemDescription = (props: ItemDescriptionProps) => {
	const { is, inline, truncate = true, size = 'default', className, children } = props;
	const { highlighted } = useItemContext();

	const classes = cx(cxx('rcx-item__description')({ inline: !!inline, wrap: !truncate, large: size === 'large' }), className);
	const tag = is ?? (inline ? 'span' : 'div');
	const scale = scaleOf(size === 'large', highlighted);

	return tag === 'span' ? (
		<ItemDescriptionFrame
			layout={inline ? 'inline' : 'span'}
			wrap={!truncate}
			scale={scale}
			className={classes}
			render={
				<span
					{...ariaAndDataAttributes(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{children}
		</ItemDescriptionFrame>
	) : (
		<ItemDescriptionFrame
			layout={inline ? 'inline' : undefined}
			wrap={!truncate}
			scale={scale}
			className={classes}
			render={
				<div
					{...ariaAndDataAttributes(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref as DivRef}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{children}
		</ItemDescriptionFrame>
	);
};

export default ItemDescription;
