import { styled, Text } from '@tamagui/web';

import type { ItemDescriptionContract } from './Item.contract';
import { useItemContext } from './ItemContext';
import { joinClasses } from './classes';
import type { ItemPartProps } from './types';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { pickWebInteractionHandlers } from '../../helpers/pickWebInteractionHandlers';
import { pickWebPressHandlers } from '../../helpers/pickWebPressHandlers';
import type { WebDivRef } from '../../types/WebElementAttributes';

export type ItemDescriptionProps = ItemPartProps<ItemDescriptionContract> & {
	/** A `span` unless set, when the description is `inline`; a `div` otherwise. */
	is?: 'div' | 'span';
};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const itemDescriptionFrame = {
	wordWrap: 'inherit',
	display: 'block',
	flexShrink: 1,
	minWidth: 0,
	minHeight: 'auto',
	render: 'div',
	overflow: 'hidden',
	flexGrow: 1,
	whiteSpace: 'nowrap',
	textOverflow: 'ellipsis',
	color: '$rcx-font-secondary-info',
	fontSize: '0.75rem',
	lineHeight: '1rem',
	fontWeight: '400',
	letterSpacing: 0,
} as const;

const itemDescriptionVariants = {
	wrap: {
		true: {
			overflow: 'visible',
			whiteSpace: 'normal',
			overflowWrap: 'anywhere',
		},
	},
	scale: {
		'large': {
			fontSize: '0.875rem',
			lineHeight: '1.25rem',
			fontWeight: '400',
			letterSpacing: 0,
		},
		'highlighted': {
			color: '$rcx-font-titles-labels',
			fontWeight: '500',
		},
		'large-highlighted': {
			fontSize: '0.875rem',
			lineHeight: '1.25rem',
			fontWeight: '500',
			letterSpacing: 0,
			color: '$rcx-font-titles-labels',
		},
	},
	layout: {
		span: {
			display: 'inline',
		},
		inline: {
			display: {
				'default': 'inline',
				'@narrow/rcx-item-group': 'block',
			},
			marginInlineStart: {
				'default': '$space.x4',
				'@narrow/rcx-item-group': 0,
			},
		},
	},
} as const;

// end of generated

const ItemDescriptionFrame = styled(Text, {
	...itemDescriptionFrame,
	variants: itemDescriptionVariants,
});

const scaleOf = (large: boolean, highlighted: boolean) => {
	if (large) {
		return highlighted ? 'large-highlighted' : 'large';
	}
	return highlighted ? 'highlighted' : undefined;
};

/**
 * The secondary line of an `Item`, such as a last message preview or a username.
 */
const ItemDescription = (props: ItemDescriptionProps) => {
	const { is, inline, truncate = true, size = 'default', children } = props;
	const { highlighted } = useItemContext();
	const classes = joinClasses(
		`rcx-item__description${inline ? ' rcx-item__description--inline' : ''}${truncate ? '' : ' rcx-item__description--wrap'}${size === 'large' ? ' rcx-item__description--large' : ''}`,
		props.className,
	);
	const tag = is ?? (inline ? 'span' : 'div');
	const scale = scaleOf(size === 'large', highlighted);

	// One literal element per tag: the zero-runtime compiler has to know the tag
	return tag === 'span' ? (
		<ItemDescriptionFrame
			layout={inline ? 'inline' : 'span'}
			wrap={!truncate}
			scale={scale}
			className={classes}
			render={
				<span
					{...ariaAndDataAttributes(props)}
					{...pickWebInteractionHandlers(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{children}
		</ItemDescriptionFrame>
	) : (
		<ItemDescriptionFrame
			layout={inline ? 'inline' : undefined}
			wrap={!truncate}
			scale={scale}
			className={classes}
			render={
				<div
					{...ariaAndDataAttributes(props)}
					{...pickWebInteractionHandlers(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref as WebDivRef}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{children}
		</ItemDescriptionFrame>
	);
};

export default ItemDescription;
