// A frame of its own: its group keys sit at the base, never inside a variant
const ItemActionsHoverFrame = styled(View, {
	...itemActionsHoverFrame,
	variants: {
		reveal: { pinned: itemActionsPinned, detached: itemActionsDetached },
		overhang: { true: itemActionsOverhang },
		end: { true: itemActionsEnd },
	},
});

const ItemActionsInner = styled(View, { ...itemActionsInner });

// One variant for both, because the compiler cannot resolve two variants that each set the margin
const revealOf = (pinned: boolean, detached: boolean) => {
	if (pinned) return 'pinned';
	return detached ? 'detached' : undefined;
};

/**
 * The trailing buttons, icon buttons or menu trigger of an `Item` or `ItemGroupHeader`.
 * Placed as a direct child it spans every row; placed inside an `ItemRow` it only takes space from that row.
 */
const ItemActions = (props: ItemActionsProps) => {
	const { reveal = 'always', justify = 'start', className, children } = props;
	const [pinned, setPinned] = useState(false);
	const row = useContext(ItemRowContext);

	const hidden = reveal === 'hover';
	const overhang = !!row && row !== 'detached' && (hidden || row.fixedHeight);
	const classes = cx(cxx('rcx-item__actions')({ 'reveal-hover': hidden }), className);
	const report = useMemo(() => (hidden ? setPinned : undefined), [hidden]);

	const renderActions = () => {
		if (hidden) {
			return (
				<ItemActionsHoverFrame
					reveal={revealOf(pinned, row === 'detached')}
					overhang={overhang}
					end={justify === 'end'}
					className={classes}
					render={
						<div
							{...ariaAndDataAttributes(props)}
							{...pickWebPressHandlers(props)}
							ref={props.ref as DivRef}
							id={props.id}
							title={props.title}
							role={props.role}
							tabIndex={props.tabIndex}
						/>
					}
				>
					<ItemActionsInner className='rcx-item__actions-inner'>{children}</ItemActionsInner>
				</ItemActionsHoverFrame>
			);
		}

		return (
			<ItemActionsFrame
				overhang={overhang}
				end={justify === 'end'}
				className={classes}
				render={
					<div
						{...ariaAndDataAttributes(props)}
						{...pickWebPressHandlers(props)}
						ref={props.ref as DivRef}
						id={props.id}
						title={props.title}
						role={props.role}
						tabIndex={props.tabIndex}
					/>
				}
			>
				{children}
			</ItemActionsFrame>
		);
	};

	return <ItemActionsContext.Provider value={report}>{renderActions()}</ItemActionsContext.Provider>;
};

export default ItemActions;
