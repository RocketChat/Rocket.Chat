/**
 * The trailing buttons, icon buttons or menu trigger of an `Item` or `ItemGroupHeader`.
 * Placed as a direct child it spans every row; placed inside an `ItemRow` it only takes space from that row.
 */
const ItemActions = (props: ItemActionsProps) => {
	const { reveal = 'always', justify = 'start', children } = props;
	const [holdsOpenMenu, setHoldsOpenMenu] = useState(false);
	const { wide } = useItemContext();
	const row = useContext(ItemRowContext);

	const hidden = reveal === 'hover';
	const onLine = !!row && row !== 'detached';
	const overhang = onLine && (hidden || row.fixedHeight);
	const classes = joinClasses(hidden ? 'rcx-item__actions rcx-item__actions--reveal-hover' : 'rcx-item__actions', props.className);

	if (!hidden) {
		return (
			<ItemActionsFrame
				overhang={overhang}
				end={justify === 'end'}
				className={classes}
				render={
					<div
						{...ariaAndDataAttributes(props)}
						{...pickWebInteractionHandlers(props)}
						{...pickWebPressHandlers(props)}
						ref={props.ref as WebDivRef}
						id={props.id}
						title={props.title}
						role={props.role}
						tabIndex={props.tabIndex}
					/>
				}
			>
				{children}
			</ItemActionsFrame>
		);
	}

	const revealOf = () => {
		if (holdsOpenMenu) {
			return 'open';
		}
		if (row === 'detached') {
			return 'detached';
		}
		return wide && !onLine ? 'wide' : 'narrow';
	};

	// A menu these actions hold is outside the row's element while open, and takes the focus with it: it says so here
	return (
		<ItemActionsContext.Provider value={setHoldsOpenMenu}>
			<ItemActionsHoverFrame
				reveal={revealOf()}
				overhang={overhang}
				end={justify === 'end'}
				className={classes}
				render={
					<div
						{...ariaAndDataAttributes(props)}
						{...pickWebInteractionHandlers(props)}
						{...pickWebPressHandlers(props)}
						ref={props.ref as WebDivRef}
						id={props.id}
						title={props.title}
						role={props.role}
						tabIndex={props.tabIndex}
					/>
				}
			>
				<ItemActionsInner className='rcx-item__actions-inner'>{children}</ItemActionsInner>
			</ItemActionsHoverFrame>
		</ItemActionsContext.Provider>
	);
};

export default ItemActions;
