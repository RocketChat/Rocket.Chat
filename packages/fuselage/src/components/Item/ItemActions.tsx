import { styled, View } from '@tamagui/web';
import type { DOMAttributes, ReactNode } from 'react';

import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { cx, cxx } from '../../helpers/composeClassNames';
import type { PartAttributes } from '../../types/ElementAttributes';

export type ItemActionsProps = PartAttributes<HTMLDivElement> &
	// A row that is itself a target keeps the clicks and keys of its actions from reaching it
	Pick<DOMAttributes<HTMLDivElement>, 'onClick' | 'onKeyDown'> & {
		/**
		 * `hover` hides the actions until the row is hovered, holds focus or has an expanded menu.
		 * They stay in the tab order, and touch screens always show them.
		 */
		reveal?: 'always' | 'hover';
		children?: ReactNode;
	};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const ItemActionsFrame = styled(View, {
	render: 'div',
	position: 'relative',
	display: 'flex',
	flexDirection: 'row',
	flexShrink: 0,
	alignItems: 'center',
	minWidth: 'auto',
	minHeight: 'auto',
	zIndex: 1,
	flexGrow: 0,
	flexBasis: 'auto',
	gap: '2px',
});

// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const ItemActionsInnerFrame = styled(View, {
	render: 'div',
	position: 'static',
	display: 'flex',
	flexDirection: 'row',
	flexShrink: 1,
	alignItems: 'center',
	minWidth: 0,
	minHeight: 'auto',
	overflow: 'hidden',
	gap: '2px',
});

// end of generated

/**
 * The trailing buttons, icon buttons or menu trigger of an `Item` or `ItemGroupHeader`.
 * Placed as a direct child it spans every row; placed inside an `ItemRow` it only takes space from that row.
 */
const ItemActions = (props: ItemActionsProps) => {
	const { reveal = 'always', children } = props;

	return (
		<ItemActionsFrame
			className={cx(cxx('rcx-item__actions')({ 'reveal-hover': reveal === 'hover' }), props.className)}
			render={
				// oxlint-disable-next-line jsx-a11y/no-static-element-interactions -- only stops the actions' events from reaching the row
				<div
					{...ariaAndDataAttributes(props)}
					ref={props.ref}
					id={props.id}
					title={props.title}
					onClick={props.onClick}
					onKeyDown={props.onKeyDown}
				/>
			}
		>
			{reveal === 'hover' ? <ItemActionsInnerFrame className='rcx-item__actions-inner'>{children}</ItemActionsInnerFrame> : children}
		</ItemActionsFrame>
	);
};

export default ItemActions;
