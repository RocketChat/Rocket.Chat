import { styled, Text } from '@tamagui/web';
import { useEffect, useId } from 'react';

import { useItemContext } from './ItemContext';
import type { ItemPartAttributes } from './types';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { cx, cxx } from '../../helpers/composeClassNames';
import { pickWebPressHandlers } from '../../helpers/pickAttributes';
import type { DivRef, LabelAttributes, LabelRef } from '../../types/ElementAttributes';

export type ItemTitleProps = {
	/** A `label` names the control its `htmlFor` points at, as a row's checkbox. */
	is?: 'div' | 'span' | 'label';
	/**
	 * Set to `false` to wrap long text instead of ending it in an ellipsis.
	 */
	truncate?: boolean;
} & LabelAttributes &
	ItemPartAttributes;

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const itemTitleFrame = {
	wordWrap: 'inherit',
	display: 'block',
	flexDirection: 'row',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 0,
	minHeight: 'auto',
	render: 'div',
	overflow: 'hidden',
	flexGrow: 1,
	flexBasis: 'auto',
	whiteSpace: 'nowrap',
	textOverflow: 'ellipsis',
	fontVariantNumeric: 'inherit',
	fontFamily: 'inherit',
	fontSize: 'inherit',
	fontWeight: 'inherit',
	lineHeight: 'inherit',
	letterSpacing: 'inherit',
} as const;

const itemTitleVariants = {
	wrap: {
		true: {
			overflow: 'visible',
			whiteSpace: 'normal',
			overflowWrap: 'anywhere',
		},
	},
	highlighted: {
		true: {
			color: 'var(--rcx-item-color-font-highlighted, var(--rcx-color-font-titles-labels, #1f2329))',
			fontWeight: 500,
		},
	},
} as const;

// end of generated

// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const ItemTitleFrame = styled(Text, {
	...itemTitleFrame,
	variants: itemTitleVariants,
});

/**
 * The main label of an `Item`. It truncates with an ellipsis.
 */
const ItemTitle = (props: ItemTitleProps) => {
	const { is = 'div', truncate = true, className, children } = props;
	const generatedId = useId();
	const id = props.id ?? generatedId;
	const { registerTitle, highlighted } = useItemContext();

	useEffect(() => registerTitle(id), [id, registerTitle]);

	const classes = cx(cxx('rcx-item__title')({ wrap: !truncate }), className);

	if (is === 'label') {
		return (
			<ItemTitleFrame
				wrap={!truncate}
				highlighted={highlighted}
				className={classes}
				render={
					<label
						{...ariaAndDataAttributes(props)}
						{...pickWebPressHandlers(props)}
						ref={props.ref as LabelRef}
						id={id}
						title={props.title}
						htmlFor={props.htmlFor}
						role={props.role}
						tabIndex={props.tabIndex}
					/>
				}
			>
				{children}
			</ItemTitleFrame>
		);
	}

	return is === 'span' ? (
		<ItemTitleFrame
			wrap={!truncate}
			highlighted={highlighted}
			className={classes}
			render={
				<span
					{...ariaAndDataAttributes(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref}
					id={id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{children}
		</ItemTitleFrame>
	) : (
		<ItemTitleFrame
			wrap={!truncate}
			highlighted={highlighted}
			className={classes}
			render={
				<div
					{...ariaAndDataAttributes(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref as DivRef}
					id={id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{children}
		</ItemTitleFrame>
	);
};

export default ItemTitle;
