import { styled, Text } from '@tamagui/web';
import type { LabelHTMLAttributes, ReactNode, Ref } from 'react';
import { useEffect, useId } from 'react';

import { useItemContext } from './ItemContext';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { cx } from '../../helpers/composeClassNames';
import type { PartAttributes } from '../../types/ElementAttributes';

export type ItemTitleProps = PartAttributes<HTMLElement> &
	Pick<LabelHTMLAttributes<HTMLLabelElement>, 'htmlFor'> & {
		/**
		 * The element to render. Use `label`, with `htmlFor`, when the title names the row's control.
		 */
		is?: 'div' | 'span' | 'label';
		children?: ReactNode;
	};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const ItemTitleFrame = styled(Text, {
	wordWrap: 'inherit',
	render: 'div',
	position: 'static',
	display: 'block',
	flexDirection: 'row',
	flexShrink: 1,
	alignItems: 'normal',
	minWidth: 0,
	minHeight: 'auto',
	overflow: 'hidden',
	whiteSpace: 'nowrap',
	textOverflow: 'ellipsis',
	flexGrow: 1,
	flexBasis: 'auto',
});

// end of generated

/**
 * The main label of an `Item`. It truncates with an ellipsis.
 */
const ItemTitle = (props: ItemTitleProps) => {
	const generatedId = useId();
	const id = props.id ?? generatedId;
	const { registerTitle } = useItemContext();

	useEffect(() => registerTitle(id), [id, registerTitle]);

	const className = cx('rcx-item__title', props.className);

	// One branch per tag: zero-runtime has to know it
	if (props.is === 'label') {
		return (
			<ItemTitleFrame
				className={className}
				render={
					<label
						{...ariaAndDataAttributes(props)}
						htmlFor={props.htmlFor}
						// The ref is typed for every tag, each branch renders one
						ref={props.ref as Ref<HTMLLabelElement>}
						id={id}
						title={props.title}
					/>
				}
			>
				{props.children}
			</ItemTitleFrame>
		);
	}

	if (props.is === 'span') {
		return (
			<ItemTitleFrame className={className} render={<span {...ariaAndDataAttributes(props)} ref={props.ref} id={id} title={props.title} />}>
				{props.children}
			</ItemTitleFrame>
		);
	}

	return (
		<ItemTitleFrame
			className={className}
			render={<div {...ariaAndDataAttributes(props)} ref={props.ref as Ref<HTMLDivElement>} id={id} title={props.title} />}
		>
			{props.children}
		</ItemTitleFrame>
	);
};

export default ItemTitle;
