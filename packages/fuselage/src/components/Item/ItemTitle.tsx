import { styled, Text } from '@tamagui/web';
import { useEffect, useId } from 'react';

import type { ItemTitleContract } from './Item.contract';
import { useItemContext } from './ItemContext';
import { joinClasses } from './classes';
import type { ItemPartProps } from './types';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { pickFramePressHandlers } from '../../helpers/pickFramePressHandlers';
import { pickWebInteractionHandlers } from '../../helpers/pickWebInteractionHandlers';
import { pickWebPressHandlers } from '../../helpers/pickWebPressHandlers';
import type { WebDivRef, WebLabelRef } from '../../types/WebElementAttributes';

export type ItemTitleProps = ItemPartProps<ItemTitleContract> & {
	/** A `label` names the control its `htmlFor` points at, as a row's checkbox. */
	is?: 'div' | 'span' | 'label';
	htmlFor?: string;
};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const itemTitleFrame = {
	wordWrap: 'inherit',
	display: 'block',
	flexShrink: 1,
	minWidth: 0,
	minHeight: 'auto',
	render: 'div',
	overflow: 'hidden',
	flexGrow: 1,
	whiteSpace: 'nowrap',
	textOverflow: 'ellipsis',
} as const;

const itemTitleVariants = {
	wrap: {
		true: {
			overflow: 'visible',
			whiteSpace: 'normal',
			overflowWrap: 'anywhere',
		},
	},
	highlighted: {
		true: {
			color: '$rcx-font-titles-labels',
			fontWeight: '500',
		},
	},
} as const;

// end of generated

const ItemTitleFrame = styled(Text, {
	...itemTitleFrame,
	variants: itemTitleVariants,
});

/**
 * The main label of an `Item`. It truncates with an ellipsis.
 */
const ItemTitle = (props: ItemTitleProps) => {
	const { is = 'div', truncate = true, children } = props;
	const generatedId = useId();
	const id = props.id ?? generatedId;
	const { registerTitle, highlighted } = useItemContext();
	const classes = joinClasses(truncate ? 'rcx-item__title' : 'rcx-item__title rcx-item__title--wrap', props.className);

	useEffect(() => registerTitle(id), [id, registerTitle]);

	// One literal element per tag: the zero-runtime compiler has to know the tag
	if (is === 'label') {
		return (
			<ItemTitleFrame
				wrap={!truncate}
				highlighted={highlighted}
				className={classes}
				{...pickFramePressHandlers(props)}
				render={
					<label
						{...ariaAndDataAttributes(props)}
						{...pickWebInteractionHandlers(props)}
						{...pickWebPressHandlers(props)}
						ref={props.ref as WebLabelRef}
						id={id}
						title={props.title}
						role={props.role}
						tabIndex={props.tabIndex}
						htmlFor={props.htmlFor}
					/>
				}
			>
				{children}
			</ItemTitleFrame>
		);
	}

	return is === 'span' ? (
		<ItemTitleFrame
			wrap={!truncate}
			highlighted={highlighted}
			className={classes}
			{...pickFramePressHandlers(props)}
			render={
				<span
					{...ariaAndDataAttributes(props)}
					{...pickWebInteractionHandlers(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref}
					id={id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{children}
		</ItemTitleFrame>
	) : (
		<ItemTitleFrame
			wrap={!truncate}
			highlighted={highlighted}
			className={classes}
			{...pickFramePressHandlers(props)}
			render={
				<div
					{...ariaAndDataAttributes(props)}
					{...pickWebInteractionHandlers(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref as WebDivRef}
					id={id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{children}
		</ItemTitleFrame>
	);
};

export default ItemTitle;
