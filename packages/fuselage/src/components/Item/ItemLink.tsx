import { styled, View } from '@tamagui/web';
import type { AnchorHTMLAttributes, ButtonHTMLAttributes, ElementType, RefAttributes } from 'react';

import { useItemContext } from './ItemContext';
import { cx } from '../../helpers/composeClassNames';

type ItemLinkAnchorProps = {
	is?: 'a';
	href: string;
} & Omit<AnchorHTMLAttributes<HTMLAnchorElement>, 'href'> &
	RefAttributes<HTMLAnchorElement>;

type ItemLinkButtonProps = {
	is: 'button';
} & ButtonHTMLAttributes<HTMLButtonElement> &
	RefAttributes<HTMLButtonElement>;

export type ItemLinkProps = ItemLinkAnchorProps | ItemLinkButtonProps;

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const ItemLinkFrame = styled(View, {
	render: 'div',
	position: 'static',
	display: 'block',
	flexDirection: 'row',
	flexShrink: 1,
	alignItems: 'normal',
	minWidth: 'auto',
	minHeight: 'auto',
	overflow: 'hidden',
	width: '100%',
	margin: 0,
	padding: 0,
	cursor: 'pointer',
	textAlign: 'start',
	whiteSpace: 'nowrap',
	textDecorationLine: 'none',
	textOverflow: 'ellipsis',
	color: 'inherit',
	borderWidth: 0,
	borderStyle: 'none',
	borderColor: 'currentcolor',
	backgroundColor: 'transparent',
});

// end of generated

/**
 * The primary target of an `Item`. It covers the whole row, so actions sit beside it instead of inside it.
 */
const ItemLink = (props: ItemLinkProps) => {
	const { descriptionIds } = useItemContext();

	const ariaDescribedBy = [props['aria-describedby'], ...descriptionIds].filter(Boolean).join(' ') || undefined;

	// The two variants differ only in the element and the button's `type`
	const {
		is = 'a',
		className,
		children,
		ref,
		...rest
	} = props as Omit<ItemLinkAnchorProps, 'is'> & { is?: 'a' | 'button' } & Pick<ItemLinkButtonProps, 'type'>;
	const Tag: ElementType = is;
	const attributes: Record<string, unknown> = {
		...rest,
		...(is === 'button' && { type: rest.type ?? 'button' }),
		'aria-describedby': ariaDescribedBy,
	};

	return (
		<ItemLinkFrame render={<Tag {...attributes} ref={ref as never} />} className={cx('rcx-item__link', className)}>
			{children}
		</ItemLinkFrame>
	);
};

export default ItemLink;
