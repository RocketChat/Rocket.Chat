import { styled, View } from '@tamagui/web';
import type { ReactNode, Ref } from 'react';

import { useItemContext } from './ItemContext';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { cx } from '../../helpers/composeClassNames';
import type { ButtonOrAnchorAttributes } from '../../types/ElementAttributes';

export type ItemLinkProps = ButtonOrAnchorAttributes & {
	/** Renders a button instead of a link, for a row that acts rather than navigates. */
	'is'?: 'a' | 'button';
	'children'?: ReactNode;
	// What the app's handlers read back from the link
	'data-id'?: string;
	'data-userid'?: string;
	'data-invitationdate'?: string;
};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const ItemLinkFrame = styled(View, {
	render: 'div',
	position: 'static',
	display: 'block',
	flexDirection: 'row',
	flexShrink: 1,
	alignItems: 'normal',
	minWidth: 'auto',
	minHeight: 'auto',
	overflow: 'hidden',
	width: '100%',
	margin: 0,
	padding: 0,
	cursor: 'pointer',
	textAlign: 'start',
	whiteSpace: 'nowrap',
	textDecorationLine: 'none',
	textOverflow: 'ellipsis',
	color: 'inherit',
	borderWidth: 0,
	borderStyle: 'none',
	borderColor: 'currentcolor',
	backgroundColor: 'transparent',
});

// end of generated

/**
 * The primary target of an `Item`. It covers the whole row, so actions sit beside it instead of inside it.
 */
const ItemLink = (props: ItemLinkProps) => {
	const { descriptionIds } = useItemContext();

	const ariaDescribedBy = [props['aria-describedby'], ...descriptionIds].filter(Boolean).join(' ') || undefined;
	const className = cx('rcx-item__link', props.className);

	// One branch per tag: zero-runtime has to know it
	if (props.is === 'button') {
		return (
			<ItemLinkFrame
				className={className}
				render={
					<button
						{...ariaAndDataAttributes(props)}
						aria-describedby={ariaDescribedBy}
						type={props.type ?? 'button'}
						form={props.form}
						name={props.name}
						value={props.value}
						// oxlint-disable-next-line jsx-a11y/no-autofocus -- the consumer's to set
						autoFocus={props.autoFocus}
						// The ref is typed for both tags, each branch renders one
						ref={props.ref as Ref<HTMLButtonElement>}
						id={props.id}
						title={props.title}
						role={props.role}
						tabIndex={props.tabIndex}
						onClick={props.onClick}
						onContextMenu={props.onContextMenu}
						onDragStart={props.onDragStart}
						onKeyDown={props.onKeyDown}
						onKeyUp={props.onKeyUp}
						onMouseDown={props.onMouseDown}
						onMouseEnter={props.onMouseEnter}
						onMouseLeave={props.onMouseLeave}
						onMouseUp={props.onMouseUp}
						onPointerDown={props.onPointerDown}
						onPointerEnter={props.onPointerEnter}
						onPointerLeave={props.onPointerLeave}
						onPointerUp={props.onPointerUp}
						onTouchCancel={props.onTouchCancel}
						onTouchEnd={props.onTouchEnd}
						onTouchMove={props.onTouchMove}
						onTouchStart={props.onTouchStart}
						onFocus={props.onFocus}
						onBlur={props.onBlur}
					/>
				}
			>
				{props.children}
			</ItemLinkFrame>
		);
	}

	return (
		<ItemLinkFrame
			className={className}
			render={
				<a
					{...ariaAndDataAttributes(props)}
					aria-describedby={ariaDescribedBy}
					href={props.href}
					target={props.target}
					rel={props.rel}
					download={props.download}
					ref={props.ref as Ref<HTMLAnchorElement>}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
					onClick={props.onClick}
					onContextMenu={props.onContextMenu}
					onDragStart={props.onDragStart}
					onKeyDown={props.onKeyDown}
					onKeyUp={props.onKeyUp}
					onMouseDown={props.onMouseDown}
					onMouseEnter={props.onMouseEnter}
					onMouseLeave={props.onMouseLeave}
					onMouseUp={props.onMouseUp}
					onPointerDown={props.onPointerDown}
					onPointerEnter={props.onPointerEnter}
					onPointerLeave={props.onPointerLeave}
					onPointerUp={props.onPointerUp}
					onTouchCancel={props.onTouchCancel}
					onTouchEnd={props.onTouchEnd}
					onTouchMove={props.onTouchMove}
					onTouchStart={props.onTouchStart}
					onFocus={props.onFocus}
					onBlur={props.onBlur}
				/>
			}
		>
			{props.children}
		</ItemLinkFrame>
	);
};

export default ItemLink;
