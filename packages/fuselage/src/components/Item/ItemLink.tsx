import { styled, Text } from '@tamagui/web';
import type { ReactNode } from 'react';

import { useItemContext } from './ItemContext';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { cx } from '../../helpers/composeClassNames';
import { pickWebPressHandlers } from '../../helpers/pickAttributes';
import type {
	AnchorActionAttributes,
	AnchorLinkAttributes,
	ButtonActionAttributes,
	ButtonFormAttributes,
} from '../../types/ElementAttributes';

type ItemLinkAnchorProps = {
	is?: 'a';
	href: string;
	children?: ReactNode;
} & AnchorActionAttributes &
	Omit<AnchorLinkAttributes, 'href'>;

type ItemLinkButtonProps = {
	is: 'button';
	children?: ReactNode;
} & ButtonActionAttributes &
	ButtonFormAttributes;

export type ItemLinkProps = ItemLinkAnchorProps | ItemLinkButtonProps;

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const itemLinkFrame = {
	flexBasis: 'auto',
	wordWrap: 'inherit',
	display: 'block',
	flexDirection: 'row',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	render: 'a',
	overflow: 'hidden',
	width: '100%',
	margin: 0,
	padding: 0,
	cursor: 'pointer',
	textAlign: 'start',
	whiteSpace: 'nowrap',
	textDecorationLine: 'none',
	textOverflow: 'ellipsis',
	color: 'inherit',
	borderWidth: 0,
	borderStyle: 'none',
	borderColor: 'currentcolor',
	outlineWidth: 0,
	outlineStyle: 'none',
	backgroundColor: 'transparent',
	fontVariantNumeric: 'inherit',
	fontFamily: 'inherit',
	fontSize: 'inherit',
	fontWeight: 'inherit',
	lineHeight: 'inherit',
	letterSpacing: 'inherit',
} as const;

// end of generated

// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const ItemLinkFrame = styled(Text, {
	...itemLinkFrame,
	variants: { grabbable: { true: { cursor: 'grab' } } },
});

/**
 * The primary target of an `Item`. It covers the whole row, so actions sit beside it instead of inside it.
 */
const ItemLink = (props: ItemLinkProps) => {
	const { descriptionIds, grabbable } = useItemContext();

	const ariaDescribedBy = [props['aria-describedby'], ...descriptionIds].filter(Boolean).join(' ') || undefined;
	const className = cx('rcx-item__link', props.className);

	if (props.is === 'button') {
		return (
			<ItemLinkFrame
				grabbable={grabbable}
				className={className}
				render={
					<button
						{...ariaAndDataAttributes(props)}
						{...pickWebPressHandlers(props)}
						ref={props.ref}
						id={props.id}
						title={props.title}
						role={props.role}
						tabIndex={props.tabIndex}
						type={props.type ?? 'button'}
						name={props.name}
						value={props.value}
						form={props.form}
						disabled={props.disabled}
						aria-describedby={ariaDescribedBy}
					/>
				}
			>
				{props.children}
			</ItemLinkFrame>
		);
	}

	return (
		<ItemLinkFrame
			grabbable={grabbable}
			className={className}
			render={
				<a
					{...ariaAndDataAttributes(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
					href={props.href}
					target={props.target}
					rel={props.rel}
					download={props.download}
					aria-describedby={ariaDescribedBy}
				/>
			}
		>
			{props.children}
		</ItemLinkFrame>
	);
};

export default ItemLink;
