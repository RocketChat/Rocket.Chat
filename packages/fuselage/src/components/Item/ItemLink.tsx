import { styled, Text } from '@tamagui/web';

import type { ItemLinkContract } from './Item.contract';
import { useItemContext } from './ItemContext';
import { joinClasses } from './classes';
import type { ItemPartProps } from './types';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { pickWebInteractionHandlers } from '../../helpers/pickWebInteractionHandlers';
import { pickWebPressHandlers } from '../../helpers/pickWebPressHandlers';
import type { WebAnchorAttributes, WebAnchorRef, WebButtonFormAttributes, WebButtonRef } from '../../types/WebElementAttributes';

type ItemLinkAnchorProps = {
	is?: 'a';
	href: string;
} & ItemPartProps<ItemLinkContract> &
	Omit<WebAnchorAttributes, 'href'>;

type ItemLinkButtonProps = {
	is: 'button';
} & ItemPartProps<ItemLinkContract> &
	WebButtonFormAttributes;

export type ItemLinkProps = ItemLinkAnchorProps | ItemLinkButtonProps;

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const itemLinkFrame = {
	wordWrap: 'inherit',
	display: 'block',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	render: 'a',
	overflow: 'hidden',
	width: '100%',
	margin: 0,
	padding: 0,
	cursor: 'pointer',
	textAlign: 'start',
	borderWidth: 0,
	borderStyle: 'none',
	borderColor: 'currentcolor',
	outlineWidth: 0,
	outlineStyle: 'none',
	backgroundColor: 'transparent',
	whiteSpace: 'nowrap',
	textDecorationLine: 'none',
	textOverflow: 'ellipsis',
	color: 'inherit',
	fontVariantNumeric: 'inherit',
	fontFamily: 'inherit',
	fontSize: 'inherit',
	fontWeight: 'inherit',
	lineHeight: 'inherit',
	letterSpacing: 'inherit',
} as const;

// end of generated

const ItemLinkFrame = styled(Text, {
	...itemLinkFrame,
	variants: { grabbable: { true: { cursor: 'grab' }, false: {} } },
});

/**
 * The primary target of an `Item`. It covers the whole row, so actions sit beside it instead of inside it.
 */
const ItemLink = (props: ItemLinkProps) => {
	const { children } = props;
	const { descriptionIds, grabbable } = useItemContext();

	const ariaDescribedBy = [props['aria-describedby'], ...descriptionIds].filter(Boolean).join(' ') || undefined;
	const classes = joinClasses('rcx-item__link', props.className);

	// One literal element per tag: the zero-runtime compiler has to know the tag
	if (props.is === 'button') {
		return (
			<ItemLinkFrame
				grabbable={grabbable}
				className={classes}
				render={
					<button
						{...ariaAndDataAttributes(props)}
						{...pickWebInteractionHandlers(props)}
						{...pickWebPressHandlers(props)}
						ref={props.ref as WebButtonRef}
						id={props.id}
						title={props.title}
						role={props.role}
						tabIndex={props.tabIndex}
						type={props.type ?? 'button'}
						name={props.name}
						value={props.value}
						form={props.form}
						disabled={props.disabled}
						aria-describedby={ariaDescribedBy}
					/>
				}
			>
				{children}
			</ItemLinkFrame>
		);
	}

	return (
		<ItemLinkFrame
			grabbable={grabbable}
			className={classes}
			render={
				<a
					{...ariaAndDataAttributes(props)}
					{...pickWebInteractionHandlers(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref as WebAnchorRef}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
					href={props.href}
					target={props.target}
					rel={props.rel}
					download={props.download}
					aria-describedby={ariaDescribedBy}
				/>
			}
		>
			{children}
		</ItemLinkFrame>
	);
};

export default ItemLink;
