import { styled, View } from '@tamagui/web';
import { useMemo } from 'react';

import type { ItemGroupContract } from './Item.contract';
import { ItemGroupContext } from './ItemGroupContext';
import type { ItemPartProps } from './types';
import { useIdRegistry } from './useIdRegistry';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { cx, cxx } from '../../helpers/composeClassNames';
import { pickFramePressHandlers } from '../../helpers/pickFramePressHandlers';
import { pickVirtualizedListStyle } from '../../helpers/pickVirtualizedListStyle';
import { pickWebInteractionHandlers } from '../../helpers/pickWebInteractionHandlers';
import { pickWebPressHandlers } from '../../helpers/pickWebPressHandlers';
import type { VirtualizedListAttributes, WebDivRef, WebOlRef, WebUlRef } from '../../types/WebElementAttributes';

export type ItemGroupProps = ItemPartProps<ItemGroupContract> &
	VirtualizedListAttributes & {
		/**
		 * The element to render. Use `ul` for a list, or set `role` for a listbox, group or menu.
		 */
		is?: 'div' | 'ul' | 'ol';
	};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const itemGroupFrame = {
	display: 'flex',
	flexDirection: 'column',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	render: 'div',
	margin: 0,
	padding: 0,
	listStyle: 'none',
	containerName: 'rcx-item-group',
	containerType: 'inline-size',
} as const;

const itemGroupPaints = {
	dropActive: {
		backgroundColor: '$rcx-status-background-info',
	},
	dropDisabled: {
		backgroundColor: 'transparent',
	},
} as const;

const itemGroupRings = {
	dropActive: {
		borderRadius: '$radius.medium',
		boxShadow: 'inset 0 0 0 2px $rcx-stroke-highlight',
	},
	dropAvailable: {
		borderRadius: '$radius.medium',
		outlineWidth: 1,
		outlineStyle: 'dashed',
		outlineColor: '$rcx-stroke-highlight',
		outlineOffset: -1,
	},
} as const;

const itemGroupPositioned = {
	position: 'relative',
} as const;

const itemGroupHidden = {
	display: 'none',
} as const;

// end of generated

// The group names the container its rows measure: a row in a narrow list gives up part of its inset
const ItemGroupFrame = styled(View, {
	...itemGroupFrame,
	variants: {
		dragging: { true: { opacity: 0.4 }, false: {} },
		paint: itemGroupPaints,
		ring: itemGroupRings,
		cursor: { 'not-allowed': { cursor: 'not-allowed' } },
		positioned: { true: itemGroupPositioned, false: {} },
		hidden: { true: itemGroupHidden, false: {} },
	},
});

const paintOf = (dropTarget: ItemGroupProps['dropTarget'], dropDisabled: boolean | undefined) => {
	if (dropDisabled) {
		return 'dropDisabled';
	}
	return dropTarget === 'active' ? 'dropActive' : undefined;
};

const ringOf = (dropTarget: ItemGroupProps['dropTarget']) => {
	if (dropTarget === 'active') {
		return 'dropActive';
	}
	return dropTarget === 'available' ? 'dropAvailable' : undefined;
};

/**
 * A list of `Item` rows. An `ItemGroupTitle` inside it labels the group, and its width drives the narrow layout.
 */
const ItemGroup = (props: ItemGroupProps) => {
	const { is = 'div', dragging, dropTarget, dropIndicator, dropDisabled, dropped, hidden, children } = props;
	const [titleIds, registerTitle] = useIdRegistry();

	const contextValue = useMemo(() => ({ registerTitle }), [registerTitle]);

	const hasOwnLabel = !!props['aria-label'] || !!props['aria-labelledby'];
	const ariaLabelledBy = !hasOwnLabel && titleIds.length > 0 ? titleIds.join(' ') : undefined;

	const classes = cx(
		cxx('rcx-item-group')({
			'dragging': !!dragging,
			'drop-target': dropTarget ?? false,
			'drop': dropIndicator ?? false,
			'drop-disabled': !!dropDisabled,
			'dropped': !!dropped,
		}),
		props.className,
	);

	const paint = paintOf(dropTarget, dropDisabled);
	const ring = ringOf(dropTarget);

	// One literal element per tag: the zero-runtime compiler has to know the tag
	const renderGroup = () => {
		if (is === 'ul') {
			return (
				<ItemGroupFrame
					dragging={!!dragging}
					paint={paint}
					ring={ring}
					cursor={dropDisabled ? 'not-allowed' : undefined}
					positioned={!!dropIndicator}
					hidden={!!hidden}
					className={classes}
					{...pickFramePressHandlers(props)}
					render={
						<ul
							aria-labelledby={ariaLabelledBy}
							{...ariaAndDataAttributes(props)}
							{...pickWebInteractionHandlers(props)}
							{...pickWebPressHandlers(props)}
							{...pickVirtualizedListStyle(props)}
							ref={props.ref as WebUlRef}
							id={props.id}
							title={props.title}
							role={props.role}
							tabIndex={props.tabIndex}
							hidden={hidden}
						/>
					}
				>
					{children}
				</ItemGroupFrame>
			);
		}

		if (is === 'ol') {
			return (
				<ItemGroupFrame
					dragging={!!dragging}
					paint={paint}
					ring={ring}
					cursor={dropDisabled ? 'not-allowed' : undefined}
					positioned={!!dropIndicator}
					hidden={!!hidden}
					className={classes}
					{...pickFramePressHandlers(props)}
					render={
						<ol
							aria-labelledby={ariaLabelledBy}
							{...ariaAndDataAttributes(props)}
							{...pickWebInteractionHandlers(props)}
							{...pickWebPressHandlers(props)}
							{...pickVirtualizedListStyle(props)}
							ref={props.ref as WebOlRef}
							id={props.id}
							title={props.title}
							role={props.role}
							tabIndex={props.tabIndex}
							hidden={hidden}
						/>
					}
				>
					{children}
				</ItemGroupFrame>
			);
		}

		return (
			<ItemGroupFrame
				dragging={!!dragging}
				paint={paint}
				ring={ring}
				cursor={dropDisabled ? 'not-allowed' : undefined}
				positioned={!!dropIndicator}
				hidden={!!hidden}
				className={classes}
				{...pickFramePressHandlers(props)}
				render={
					<div
						aria-labelledby={ariaLabelledBy}
						{...ariaAndDataAttributes(props)}
						{...pickWebInteractionHandlers(props)}
						{...pickWebPressHandlers(props)}
						{...pickVirtualizedListStyle(props)}
						ref={props.ref as WebDivRef}
						id={props.id}
						title={props.title}
						role={props.role}
						tabIndex={props.tabIndex}
						hidden={hidden}
					/>
				}
			>
				{children}
			</ItemGroupFrame>
		);
	};

	return <ItemGroupContext.Provider value={contextValue}>{renderGroup()}</ItemGroupContext.Provider>;
};

export default ItemGroup;
