import { styled, View } from '@tamagui/web';
import type { AriaAttributes, AriaRole, ReactNode, Ref } from 'react';
import { useMemo } from 'react';

import { ItemGroupContext } from './ItemGroupContext';
import { useIdRegistry } from './useIdRegistry';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { cx } from '../../helpers/composeClassNames';
import type { PartAttributes } from '../../types/ElementAttributes';

export type ItemGroupProps = PartAttributes<HTMLElement> &
	Pick<AriaAttributes, 'aria-label' | 'aria-labelledby' | 'aria-busy' | 'aria-multiselectable'> & {
		/**
		 * The element to render. Use `ul` for a list, or set `role` for a listbox, group or menu.
		 */
		is?: 'div' | 'ul';
		role?: AriaRole;
		hidden?: boolean;
		children?: ReactNode;
	};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const ItemGroupFrame = styled(View, {
	render: 'div',
	position: 'static',
	display: 'flex',
	flexDirection: 'column',
	flexShrink: 1,
	alignItems: 'normal',
	minWidth: 'auto',
	minHeight: 'auto',
	margin: 0,
	padding: 0,
});

// end of generated

/**
 * A list of `Item` rows. An `ItemGroupTitle` inside it labels the group, and its width drives the narrow layout.
 */
const ItemGroup = (props: ItemGroupProps) => {
	const [titleIds, registerTitle] = useIdRegistry();

	const contextValue = useMemo(() => ({ registerTitle }), [registerTitle]);

	const hasOwnLabel = !!props['aria-label'] || !!props['aria-labelledby'];
	const ariaLabelledBy = hasOwnLabel ? props['aria-labelledby'] : titleIds.join(' ') || undefined;

	const className = cx('rcx-item-group', props.className);

	// One branch per tag: zero-runtime has to know it
	if (props.is === 'ul') {
		return (
			<ItemGroupContext.Provider value={contextValue}>
				<ItemGroupFrame
					className={className}
					render={
						<ul
							{...ariaAndDataAttributes(props)}
							aria-labelledby={ariaLabelledBy}
							// The ref is typed for both tags, each branch renders one
							ref={props.ref as Ref<HTMLUListElement>}
							id={props.id}
							title={props.title}
							role={props.role}
							hidden={props.hidden}
						/>
					}
				>
					{props.children}
				</ItemGroupFrame>
			</ItemGroupContext.Provider>
		);
	}

	return (
		<ItemGroupContext.Provider value={contextValue}>
			<ItemGroupFrame
				className={className}
				render={
					<div
						{...ariaAndDataAttributes(props)}
						aria-labelledby={ariaLabelledBy}
						ref={props.ref as Ref<HTMLDivElement>}
						id={props.id}
						title={props.title}
						role={props.role}
						hidden={props.hidden}
					/>
				}
			>
				{props.children}
			</ItemGroupFrame>
		</ItemGroupContext.Provider>
	);
};

export default ItemGroup;
