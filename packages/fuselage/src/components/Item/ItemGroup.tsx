import { styled, View } from '@tamagui/web';
import { useMemo } from 'react';

import { ItemGroupContext } from './ItemGroupContext';
import type { ItemPartAttributes } from './types';
import { useIdRegistry } from './useIdRegistry';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { cx, cxx } from '../../helpers/composeClassNames';
import { pickVirtualizerStyle, pickWebPressHandlers } from '../../helpers/pickAttributes';
import type { DivRef, OlRef, UlRef, VirtualizedListAttributes } from '../../types/ElementAttributes';

export type ItemGroupProps = {
	/**
	 * The element to render. Use `ul` for a list, or set `role` for a listbox, group or menu.
	 */
	is?: 'div' | 'ul' | 'ol';
	/**
	 * Dims the whole group while it is being dragged.
	 */
	dragging?: boolean;
	/**
	 * Highlights the group as the place a dragged row goes into, when its rows keep their own order: `available` while a drag
	 * that could land on it is under way, `active` while the pointer is over it.
	 */
	dropTarget?: 'available' | 'active';
	/**
	 * Draws the line where a dragged group would land, on this group's top (`before`) or bottom (`after`) edge.
	 */
	dropIndicator?: 'before' | 'after';
	/**
	 * Marks the group as hovered by a drag that cannot land on it.
	 */
	dropDisabled?: boolean;
	/**
	 * Flashes the group once, where a dragged or keyboard-moved group has just landed.
	 */
	dropped?: boolean;
	/**
	 * Hides the group, as a collapsed panel does.
	 */
	hidden?: boolean;
} & ItemPartAttributes &
	VirtualizedListAttributes;

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const itemGroupFrame = {
	display: 'flex',
	flexDirection: 'column',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	render: 'div',
	margin: 0,
	padding: 0,
} as const;

const itemGroupPaints = {
	dropActive: {
		backgroundColor: 'var(--rcx-item-group-color-surface-drop-target, var(--rcx-color-status-background-info, #d1ebfe))',
	},
	dropDisabled: {
		backgroundColor: 'transparent',
	},
} as const;

const itemGroupRings = {
	dropActive: {
		borderRadius: '0.25rem',
		boxShadow: 'inset 0 0 0 2px var(--rcx-item-color-stroke-focus, var(--rcx-color-stroke-highlight, #156ff5))',
	},
	dropAvailable: {
		borderRadius: '0.25rem',
		outlineWidth: '1px',
		outlineStyle: 'dashed',
		outlineColor: 'var(--rcx-item-color-stroke-focus, var(--rcx-color-stroke-highlight, #156ff5))',
		outlineOffset: 'calc(-1 * 1px)',
	},
} as const;

const itemGroupPositioned = {
	position: 'relative',
} as const;

const itemGroupHidden = {
	display: 'none',
} as const;

// end of generated

// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const ItemGroupFrame = styled(View, {
	...itemGroupFrame,
	variants: {
		dragging: { true: { opacity: 0.4 } },
		paint: itemGroupPaints,
		ring: itemGroupRings,
		cursor: { 'not-allowed': { cursor: 'not-allowed' } },
		positioned: { true: itemGroupPositioned },
		hidden: { true: itemGroupHidden },
	},
});

const paintOf = (dropTarget: ItemGroupProps['dropTarget'], dropDisabled: boolean | undefined) => {
	if (dropTarget === 'active') return 'dropActive';
	return dropDisabled ? 'dropDisabled' : undefined;
};

const ringOf = (dropTarget: ItemGroupProps['dropTarget']) => {
	if (dropTarget === 'active') return 'dropActive';
	return dropTarget === 'available' ? 'dropAvailable' : undefined;
};

/**
 * A list of `Item` rows. An `ItemGroupTitle` inside it labels the group, and its width drives the narrow layout.
 */
const ItemGroup = (props: ItemGroupProps) => {
	const { is = 'div', dragging, dropTarget, dropIndicator, dropDisabled, dropped, hidden, className, children } = props;
	const [titleIds, registerTitle] = useIdRegistry();

	const contextValue = useMemo(() => ({ registerTitle }), [registerTitle]);

	const hasOwnLabel = !!props['aria-label'] || !!props['aria-labelledby'];
	const ariaLabelledBy = !hasOwnLabel && titleIds.length > 0 ? titleIds.join(' ') : undefined;

	const classes = cx(
		cxx('rcx-item-group')({
			'dragging': !!dragging,
			'drop-target': dropTarget ?? false,
			'drop': dropIndicator ?? false,
			'drop-disabled': !!dropDisabled,
			'dropped': !!dropped,
		}),
		className,
	);

	const paint = paintOf(dropTarget, dropDisabled);
	const ring = ringOf(dropTarget);

	// One frame per tag, each with a literal `render` element: zero-runtime has to know the tag
	const renderGroup = () => {
		if (is === 'ul') {
			return (
				<ItemGroupFrame
					dragging={!!dragging}
					paint={paint}
					ring={ring}
					cursor={dropDisabled ? 'not-allowed' : undefined}
					positioned={!!dropIndicator}
					hidden={!!hidden}
					className={classes}
					render={
						<ul
							aria-labelledby={ariaLabelledBy}
							{...ariaAndDataAttributes(props)}
							{...pickWebPressHandlers(props)}
							{...pickVirtualizerStyle(props)}
							ref={props.ref as UlRef}
							id={props.id}
							title={props.title}
							hidden={hidden}
							role={props.role}
							tabIndex={props.tabIndex}
						/>
					}
				>
					{children}
				</ItemGroupFrame>
			);
		}

		if (is === 'ol') {
			return (
				<ItemGroupFrame
					dragging={!!dragging}
					paint={paint}
					ring={ring}
					cursor={dropDisabled ? 'not-allowed' : undefined}
					positioned={!!dropIndicator}
					hidden={!!hidden}
					className={classes}
					render={
						<ol
							aria-labelledby={ariaLabelledBy}
							{...ariaAndDataAttributes(props)}
							{...pickWebPressHandlers(props)}
							{...pickVirtualizerStyle(props)}
							ref={props.ref as OlRef}
							id={props.id}
							title={props.title}
							hidden={hidden}
							role={props.role}
							tabIndex={props.tabIndex}
						/>
					}
				>
					{children}
				</ItemGroupFrame>
			);
		}

		return (
			<ItemGroupFrame
				dragging={!!dragging}
				paint={paint}
				ring={ring}
				cursor={dropDisabled ? 'not-allowed' : undefined}
				positioned={!!dropIndicator}
				hidden={!!hidden}
				className={classes}
				render={
					<div
						aria-labelledby={ariaLabelledBy}
						{...ariaAndDataAttributes(props)}
						{...pickWebPressHandlers(props)}
						{...pickVirtualizerStyle(props)}
						ref={props.ref as DivRef}
						id={props.id}
						title={props.title}
						hidden={hidden}
						role={props.role}
						tabIndex={props.tabIndex}
					/>
				}
			>
				{children}
			</ItemGroupFrame>
		);
	};

	return <ItemGroupContext.Provider value={contextValue}>{renderGroup()}</ItemGroupContext.Provider>;
};

export default ItemGroup;
