import { styled, Text } from '@tamagui/web';

import type { ItemMetaContract } from './Item.contract';
import { useItemContext } from './ItemContext';
import { joinClasses } from './classes';
import type { ItemPartProps } from './types';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { pickFramePressHandlers } from '../../helpers/pickFramePressHandlers';
import { pickWebInteractionHandlers } from '../../helpers/pickWebInteractionHandlers';
import { pickWebPressHandlers } from '../../helpers/pickWebPressHandlers';
import type { WebDivRef } from '../../types/WebElementAttributes';

export type ItemMetaProps = ItemPartProps<ItemMetaContract> & {
	is?: 'div' | 'span';
};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const itemMetaFrame = {
	wordWrap: 'inherit',
	display: 'block',
	flexShrink: 0,
	minWidth: 'auto',
	minHeight: 'auto',
	render: 'div',
	flexGrow: 0,
	whiteSpace: 'nowrap',
	color: '$rcx-font-secondary-info',
	fontSize: '0.75rem',
	lineHeight: '1rem',
	fontWeight: '400',
	letterSpacing: 0,
} as const;

const itemMetaVariants = {
	truncate: {
		true: {
			overflow: 'hidden',
			flexShrink: 1,
			minWidth: 0,
			textOverflow: 'ellipsis',
		},
	},
	highlighted: {
		true: {
			color: '$rcx-font-titles-labels',
			fontWeight: '500',
		},
	},
} as const;

// end of generated

const ItemMetaFrame = styled(Text, {
	...itemMetaFrame,
	variants: itemMetaVariants,
});

/**
 * Short trailing text, such as a timestamp, count or file size. It never truncates unless `truncate` is set.
 */
const ItemMeta = (props: ItemMetaProps) => {
	const { is = 'div', truncate, children } = props;
	const { highlighted } = useItemContext();
	const classes = joinClasses(truncate ? 'rcx-item__meta rcx-item__meta--truncate' : 'rcx-item__meta', props.className);

	// One literal element per tag: the zero-runtime compiler has to know the tag
	return is === 'span' ? (
		<ItemMetaFrame
			truncate={!!truncate}
			highlighted={highlighted}
			className={classes}
			{...pickFramePressHandlers(props)}
			render={
				<span
					{...ariaAndDataAttributes(props)}
					{...pickWebInteractionHandlers(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{children}
		</ItemMetaFrame>
	) : (
		<ItemMetaFrame
			truncate={!!truncate}
			highlighted={highlighted}
			className={classes}
			{...pickFramePressHandlers(props)}
			render={
				<div
					{...ariaAndDataAttributes(props)}
					{...pickWebInteractionHandlers(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref as WebDivRef}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{children}
		</ItemMetaFrame>
	);
};

export default ItemMeta;
