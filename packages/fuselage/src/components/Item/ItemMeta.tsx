import { styled, Text } from '@tamagui/web';

import { useItemContext } from './ItemContext';
import type { ItemPartAttributes } from './types';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { cx, cxx } from '../../helpers/composeClassNames';
import { pickWebPressHandlers } from '../../helpers/pickAttributes';
import type { DivRef } from '../../types/ElementAttributes';

export type ItemMetaProps = {
	is?: 'div' | 'span';
	/**
	 * Lets longer trailing text, such as a command description, shrink and end in an ellipsis.
	 */
	truncate?: boolean;
} & ItemPartAttributes;

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const itemMetaFrame = {
	wordWrap: 'inherit',
	display: 'block',
	flexDirection: 'row',
	alignItems: 'normal',
	flexShrink: 0,
	minWidth: 'auto',
	minHeight: 'auto',
	render: 'div',
	flexGrow: 0,
	flexBasis: 'auto',
	whiteSpace: 'nowrap',
	color: 'var(--rcx-item-color-font-secondary, var(--rcx-color-font-secondary-info, #6c737a))',
	fontVariantNumeric: 'inherit',
	fontFamily: 'inherit',
	fontSize: '0.75rem',
	fontWeight: 400,
	lineHeight: '1rem',
	letterSpacing: '0rem',
} as const;

const itemMetaVariants = {
	truncate: {
		true: {
			overflow: 'hidden',
			flexShrink: 1,
			minWidth: 0,
			textOverflow: 'ellipsis',
		},
	},
	highlighted: {
		true: {
			color: 'var(--rcx-item-color-font-highlighted, var(--rcx-color-font-titles-labels, #1f2329))',
			fontWeight: 500,
		},
	},
} as const;

// end of generated

// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const ItemMetaFrame = styled(Text, {
	...itemMetaFrame,
	variants: itemMetaVariants,
});

/**
 * Short trailing text, such as a timestamp, count or file size. It never truncates unless `truncate` is set.
 */
const ItemMeta = (props: ItemMetaProps) => {
	const { is = 'div', truncate, className, children } = props;
	const { highlighted } = useItemContext();

	const classes = cx(cxx('rcx-item__meta')({ truncate: !!truncate }), className);

	return is === 'span' ? (
		<ItemMetaFrame
			truncate={!!truncate}
			highlighted={highlighted}
			className={classes}
			render={
				<span
					{...ariaAndDataAttributes(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{children}
		</ItemMetaFrame>
	) : (
		<ItemMetaFrame
			truncate={!!truncate}
			highlighted={highlighted}
			className={classes}
			render={
				<div
					{...ariaAndDataAttributes(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref as DivRef}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{children}
		</ItemMetaFrame>
	);
};

export default ItemMeta;
