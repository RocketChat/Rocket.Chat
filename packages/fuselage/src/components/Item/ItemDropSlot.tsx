import { styled, Text } from '@tamagui/web';

import type { ItemPartAttributes } from './types';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { cx, cxx } from '../../helpers/composeClassNames';
import { pickWebPressHandlers } from '../../helpers/pickAttributes';
import type { DivRef, LiRef } from '../../types/ElementAttributes';

export type ItemDropSlotProps = {
	/**
	 * The element to render. Inside an `ItemGroup` rendered as `ul`, pass `li`.
	 */
	is?: 'div' | 'li';
	/**
	 * `available` while a drag that could land in the empty group is under way, `active` while the pointer is over it.
	 */
	dropTarget?: 'available' | 'active';
} & ItemPartAttributes;

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const itemDropSlotFrame = {
	flexBasis: 'auto',
	whiteSpace: 'inherit',
	wordWrap: 'inherit',
	display: 'flex',
	flexDirection: 'row',
	alignItems: 'center',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: '1.75rem',
	render: 'div',
	justifyContent: 'center',
	margin: 0,
	padding: '4px',
	color: 'var(--rcx-item-color-font-secondary, var(--rcx-color-font-secondary-info, #6c737a))',
	borderWidth: '1px',
	borderStyle: 'dashed',
	borderColor: 'var(--rcx-item-color-stroke-slot, var(--rcx-color-stroke-light, #cbced1))',
	borderRadius: '0.125rem',
	fontFamily:
		"var(--rcx-font-family-sans, Inter, -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Oxygen, Ubuntu, Cantarell, 'Helvetica Neue', 'Apple Color Emoji', 'Segoe UI Emoji', 'Segoe UI Symbol', 'Meiryo UI', Arial, sans-serif)",
	fontSize: '0.75rem',
	fontWeight: 400,
	lineHeight: '1rem',
	letterSpacing: '0rem',
} as const;

const itemDropSlotTargets = {
	available: {
		borderColor: 'var(--rcx-item-color-stroke-focus, var(--rcx-color-stroke-highlight, #156ff5))',
	},
	active: {
		color: 'var(--rcx-item-color-font-highlighted, var(--rcx-color-font-titles-labels, #1f2329))',
		borderStyle: 'solid',
		borderColor: 'var(--rcx-item-color-stroke-focus, var(--rcx-color-stroke-highlight, #156ff5))',
		backgroundColor: 'var(--rcx-item-group-color-surface-drop-target, var(--rcx-color-status-background-info, #d1ebfe))',
	},
} as const;

// end of generated

// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const ItemDropSlotFrame = styled(Text, {
	...itemDropSlotFrame,
	variants: { target: itemDropSlotTargets },
});

/**
 * The row-high place a dragged row can land in an empty group. Its children are the hint, such as "Drop here".
 */
const ItemDropSlot = (props: ItemDropSlotProps) => {
	const { is = 'div', dropTarget, className, children } = props;
	const classes = cx(cxx('rcx-item-drop-slot')({ 'drop-target': dropTarget ?? false }), className);

	return is === 'li' ? (
		<ItemDropSlotFrame
			target={dropTarget}
			className={classes}
			render={
				<li
					{...ariaAndDataAttributes(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref as LiRef}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{children}
		</ItemDropSlotFrame>
	) : (
		<ItemDropSlotFrame
			target={dropTarget}
			className={classes}
			render={
				<div
					{...ariaAndDataAttributes(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref as DivRef}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{children}
		</ItemDropSlotFrame>
	);
};

export default ItemDropSlot;
