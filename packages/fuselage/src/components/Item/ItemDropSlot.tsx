import { styled, Text } from '@tamagui/web';

import type { ItemDropSlotContract } from './Item.contract';
import type { ItemPartProps } from './types';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { cx, cxx } from '../../helpers/composeClassNames';
import { pickWebInteractionHandlers } from '../../helpers/pickWebInteractionHandlers';
import { pickWebPressHandlers } from '../../helpers/pickWebPressHandlers';
import type { WebDivRef, WebLiRef } from '../../types/WebElementAttributes';

export type ItemDropSlotProps = ItemPartProps<ItemDropSlotContract> & {
	/**
	 * The element to render. Inside an `ItemGroup` rendered as `ul`, pass `li`.
	 */
	is?: 'div' | 'li';
};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const itemDropSlotFrame = {
	whiteSpace: 'inherit',
	wordWrap: 'inherit',
	display: 'flex',
	flexDirection: 'row',
	alignItems: 'center',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: '$size.x28',
	render: 'div',
	justifyContent: 'center',
	margin: 0,
	padding: '$space.x4',
	listStyle: 'none',
	color: '$rcx-font-secondary-info',
	borderWidth: 1,
	borderStyle: 'dashed',
	borderColor: '$rcx-stroke-light',
	borderRadius: '$radius.small',
	fontSize: '0.75rem',
	lineHeight: '1rem',
	fontWeight: '400',
	letterSpacing: 0,
} as const;

const itemDropSlotTargets = {
	available: {
		borderColor: '$rcx-stroke-highlight',
	},
	active: {
		color: '$rcx-font-titles-labels',
		borderStyle: 'solid',
		borderColor: '$rcx-stroke-highlight',
		backgroundColor: '$rcx-status-background-info',
	},
} as const;

// end of generated

const ItemDropSlotFrame = styled(Text, {
	...itemDropSlotFrame,
	variants: { target: itemDropSlotTargets },
});

/**
 * The row-high place a dragged row can land in an empty group. Its children are the hint, such as "Drop here".
 */
const ItemDropSlot = (props: ItemDropSlotProps) => {
	const { is = 'div', dropTarget, children } = props;
	const classes = cx(cxx('rcx-item-drop-slot')({ 'drop-target': dropTarget ?? false }), props.className);

	// One literal element per tag: the zero-runtime compiler has to know the tag
	return is === 'li' ? (
		<ItemDropSlotFrame
			target={dropTarget}
			className={classes}
			render={
				<li
					{...ariaAndDataAttributes(props)}
					{...pickWebInteractionHandlers(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref as WebLiRef}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{children}
		</ItemDropSlotFrame>
	) : (
		<ItemDropSlotFrame
			target={dropTarget}
			className={classes}
			render={
				<div
					{...ariaAndDataAttributes(props)}
					{...pickWebInteractionHandlers(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref as WebDivRef}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{children}
		</ItemDropSlotFrame>
	);
};

export default ItemDropSlot;
