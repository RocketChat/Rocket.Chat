import { styled, View } from '@tamagui/web';
import { useEffect, useId } from 'react';

import { useItemContext } from './ItemContext';
import type { ItemPartAttributes } from './types';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { cx } from '../../helpers/composeClassNames';
import { pickWebPressHandlers } from '../../helpers/pickAttributes';
import type { DivRef } from '../../types/ElementAttributes';

export type ItemIconProps = {
	/**
	 * Names what the icon conveys, such as "Private channel" or "Away".
	 * The label also describes the row's `ItemLink`, or the row itself when it is a menu item. Without it, the icon is decorative.
	 */
	label?: string;
} & ItemPartAttributes;

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const itemIconFrame = {
	display: 'flex',
	flexDirection: 'row',
	alignItems: 'center',
	flexShrink: 0,
	minWidth: 'auto',
	minHeight: 'auto',
	render: 'div',
	justifyContent: 'center',
	flexGrow: 0,
	flexBasis: 'auto',
	width: '1.25rem',
	height: '1.25rem',
} as const;

const itemIconHighlighted = {
	color: 'var(--rcx-item-color-font-highlighted, var(--rcx-color-font-titles-labels, #1f2329))',
	fontWeight: 500,
} as const;

// end of generated

// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const ItemIconFrame = styled(View, {
	...itemIconFrame,
	variants: { highlighted: { true: itemIconHighlighted } },
});

/**
 * A 20px slot for the room type icon or a user status, placed before the title.
 */
const ItemIcon = (props: ItemIconProps) => {
	const { label, className, children } = props;
	const generatedId = useId();
	const id = props.id ?? generatedId;
	const { registerDescription, highlighted } = useItemContext();

	useEffect(() => {
		if (!label) {
			return undefined;
		}

		return registerDescription(id);
	}, [id, label, registerDescription]);

	return (
		<ItemIconFrame
			highlighted={highlighted}
			className={cx('rcx-item__icon', className)}
			render={
				<div
					{...ariaAndDataAttributes(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref as DivRef}
					id={id}
					title={props.title}
					role={props.role ?? (label ? 'img' : undefined)}
					aria-label={props['aria-label'] ?? label}
					aria-hidden={label ? props['aria-hidden'] : (props['aria-hidden'] ?? true)}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{children}
		</ItemIconFrame>
	);
};

export default ItemIcon;
