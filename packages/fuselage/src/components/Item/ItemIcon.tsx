import { styled, View } from '@tamagui/web';
import { useEffect, useId } from 'react';

import type { ItemIconContract } from './Item.contract';
import { useItemContext } from './ItemContext';
import { joinClasses } from './classes';
import type { ItemPartProps } from './types';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { pickFramePressHandlers } from '../../helpers/pickFramePressHandlers';
import { pickWebInteractionHandlers } from '../../helpers/pickWebInteractionHandlers';
import { pickWebPressHandlers } from '../../helpers/pickWebPressHandlers';
import type { WebDivRef } from '../../types/WebElementAttributes';

export type ItemIconProps = ItemPartProps<ItemIconContract>;

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const itemIconFrame = {
	display: 'flex',
	flexDirection: 'row',
	alignItems: 'center',
	flexShrink: 0,
	minWidth: 'auto',
	minHeight: 'auto',
	render: 'div',
	justifyContent: 'center',
	flexGrow: 0,
	flexBasis: 'auto',
	width: '$size.x20',
	height: '$size.x20',
} as const;

const itemIconHighlighted = {
	color: '$rcx-font-titles-labels',
	fontWeight: '500',
} as const;

// end of generated

const ItemIconFrame = styled(View, {
	...itemIconFrame,
	variants: { highlighted: { true: itemIconHighlighted, false: {} } },
});

/**
 * A 20px slot for the room type icon or a user status, placed before the title.
 */
const ItemIcon = (props: ItemIconProps) => {
	const { label, children } = props;
	const generatedId = useId();
	const id = props.id ?? generatedId;
	const { registerDescription, highlighted } = useItemContext();
	const classes = joinClasses('rcx-item__icon', props.className);

	useEffect(() => {
		if (!label) {
			return undefined;
		}
		return registerDescription(id);
	}, [id, label, registerDescription]);

	return (
		<ItemIconFrame
			highlighted={highlighted}
			className={classes}
			{...pickFramePressHandlers(props)}
			render={
				<div
					aria-label={label}
					aria-hidden={label ? undefined : true}
					{...ariaAndDataAttributes(props)}
					{...pickWebInteractionHandlers(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref as WebDivRef}
					id={id}
					title={props.title}
					role={props.role ?? (label ? 'img' : undefined)}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{children}
		</ItemIconFrame>
	);
};

export default ItemIcon;
