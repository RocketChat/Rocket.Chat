import { styled, View } from '@tamagui/web';
import type { AllHTMLAttributes, ElementType, RefAttributes } from 'react';
import { useEffect, useId } from 'react';

import { useItemContext } from './ItemContext';
import { cx } from '../../helpers/composeClassNames';

export type ItemIconProps = {
	is?: ElementType;
	/**
	 * Names what the icon conveys, such as "Private channel" or "Away".
	 * The label also describes the row's `ItemLink`, or the row itself when it is a menu item. Without it, the icon is decorative.
	 */
	label?: string;
} & Omit<AllHTMLAttributes<HTMLElement>, 'is' | 'label'> &
	RefAttributes<HTMLElement>;

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const ItemIconFrame = styled(View, {
	render: 'div',
	position: 'static',
	display: 'flex',
	flexDirection: 'row',
	flexShrink: 0,
	alignItems: 'center',
	minWidth: 'auto',
	minHeight: 'auto',
	justifyContent: 'center',
	flexGrow: 0,
	flexBasis: 'auto',
	width: '1.25rem',
	height: '1.25rem',
});

// end of generated

/**
 * A 20px slot for the room type icon or a user status, placed before the title.
 */
const ItemIcon = ({ is: Tag = 'div', label, id: propId, className, children, ref, ...props }: ItemIconProps) => {
	const generatedId = useId();
	const id = propId ?? generatedId;
	const { registerDescription } = useItemContext();

	useEffect(() => {
		if (!label) {
			return undefined;
		}

		return registerDescription(id);
	}, [id, label, registerDescription]);

	const a11yProps = label ? { 'role': 'img', 'aria-label': label } : { 'aria-hidden': true };

	const attributes = { ...a11yProps, ...props, id };

	return (
		<ItemIconFrame render={<Tag {...attributes} ref={ref} />} className={cx('rcx-item__icon', className)}>
			{children}
		</ItemIconFrame>
	);
};

export default ItemIcon;
