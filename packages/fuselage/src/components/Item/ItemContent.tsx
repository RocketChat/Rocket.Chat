import { styled, View } from '@tamagui/web';
import { useLayoutEffect } from 'react';

import type { ItemContentContract } from './Item.contract';
import { ItemRowContext, useItemContext } from './ItemContext';
import { joinClasses } from './classes';
import { countLines } from './lines';
import type { ItemPartProps } from './types';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { pickFramePressHandlers } from '../../helpers/pickFramePressHandlers';
import { pickWebInteractionHandlers } from '../../helpers/pickWebInteractionHandlers';
import { pickWebPressHandlers } from '../../helpers/pickWebPressHandlers';
import type { WebDivRef } from '../../types/WebElementAttributes';

export type ItemContentProps = ItemPartProps<ItemContentContract>;

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const itemContentFrame = {
	display: 'flex',
	flexDirection: 'column',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 0,
	minHeight: 'auto',
	render: 'div',
	flexGrow: 1,
	flexBasis: 'auto',
} as const;

// end of generated

const ItemContentFrame = styled(View, { ...itemContentFrame });

/**
 * The flexible, truncating column that holds the title and description, or one `ItemRow` per line.
 */
const ItemContent = (props: ItemContentProps) => {
	const { children } = props;
	const { reportLines } = useItemContext();
	// Counted only for a row that asked
	const lines = !!reportLines && countLines(children) > 1;
	const classes = joinClasses('rcx-item__content', props.className);

	useLayoutEffect(() => reportLines?.(lines), [lines, reportLines]);

	return (
		<ItemRowContext.Provider value='detached'>
			<ItemContentFrame
				className={classes}
				{...pickFramePressHandlers(props)}
				render={
					<div
						{...ariaAndDataAttributes(props)}
						{...pickWebInteractionHandlers(props)}
						{...pickWebPressHandlers(props)}
						ref={props.ref as WebDivRef}
						id={props.id}
						title={props.title}
						role={props.role}
						tabIndex={props.tabIndex}
					/>
				}
			>
				{children}
			</ItemContentFrame>
		</ItemRowContext.Provider>
	);
};

export default ItemContent;
