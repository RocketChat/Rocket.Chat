import { styled, View } from '@tamagui/web';

import type { ItemPartAttributes } from './types';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { cx, cxx } from '../../helpers/composeClassNames';
import { pickWebPressHandlers } from '../../helpers/pickAttributes';
import type { DivRef } from '../../types/ElementAttributes';

export type ItemMediaProps = {
	/**
	 * `icon` centers its child in a 20px box, for icons and status bullets; `slot` keeps at least that size, so an empty
	 * slot lines up rows with and without an icon.
	 */
	variant?: 'default' | 'icon' | 'slot';
} & ItemPartAttributes;

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const itemMediaFrame = {
	display: 'flex',
	flexDirection: 'row',
	alignItems: 'center',
	flexShrink: 0,
	minWidth: 'auto',
	minHeight: 'auto',
	render: 'div',
	justifyContent: 'center',
	flexGrow: 0,
	flexBasis: 'auto',
} as const;

const itemMediaVariants = {
	default: {},
	icon: {
		width: '1.25rem',
		height: '1.25rem',
	},
	slot: {
		minWidth: '1.25rem',
		minHeight: '1.25rem',
	},
} as const;

// end of generated

// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const ItemMediaFrame = styled(View, {
	...itemMediaFrame,
	variants: { variant: itemMediaVariants },
});

/**
 * The leading avatar, icon or thumbnail of an `Item`. Its box fits its child, so the child's size sets the row height.
 */
const ItemMedia = (props: ItemMediaProps) => {
	const { variant = 'default' } = props;

	return (
		<ItemMediaFrame
			variant={variant}
			className={cx(cxx('rcx-item__media')({ icon: variant === 'icon' }), props.className)}
			render={
				<div
					{...ariaAndDataAttributes(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref as DivRef}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{props.children}
		</ItemMediaFrame>
	);
};

export default ItemMedia;
