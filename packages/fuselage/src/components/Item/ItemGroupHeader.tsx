// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const ItemGroupHeaderFrame = styled(View, {
	...itemGroupHeaderFrame,
	group: 'item',
	variants: { surface: itemGroupHeaderSurfaces, density: itemGroupHeaderDensities },
});

const surfaceOf = (sticky: boolean | undefined, interactive: boolean | undefined) => {
	if (sticky) return interactive ? 'sticky-interactive' : 'sticky';
	return interactive ? 'interactive' : undefined;
};

/**
 * The label row of a group, such as Favorites, Recent or Moderators. It holds an `ItemGroupTitle` and optional trailing content.
 */
const ItemGroupHeader = (props: ItemGroupHeaderProps) => {
	const { is = 'div', inset = 'none', sticky, interactive, padding = 'default', className, children } = props;

	const classes = cx(
		cxx('rcx-item-group-header')({
			[`inset-${inset}`]: inset !== 'none',
			sticky: !!sticky,
		}),
		className,
	);
	const surface = surfaceOf(sticky, interactive);
	const density = padding === 'large' ? 'large' : undefined;

	return is === 'li' ? (
		<ItemGroupHeaderFrame
			surface={surface}
			density={density}
			className={classes}
			render={
				<li
					{...ariaAndDataAttributes(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref as LiRef}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{children}
		</ItemGroupHeaderFrame>
	) : (
		<ItemGroupHeaderFrame
			surface={surface}
			density={density}
			className={classes}
			render={
				<div
					{...ariaAndDataAttributes(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref as DivRef}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{children}
		</ItemGroupHeaderFrame>
	);
};

export default ItemGroupHeader;
