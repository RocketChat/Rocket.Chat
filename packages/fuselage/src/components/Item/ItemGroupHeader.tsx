import { styled, View } from '@tamagui/web';
import { useCallback, useState } from 'react';

import type { ItemGroupHeaderContract } from './Item.contract';
import { ItemGroupHeaderContext, ItemRowContext } from './ItemContext';
import type { ItemPartProps } from './types';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { cx, cxx } from '../../helpers/composeClassNames';
import { pickFramePressHandlers } from '../../helpers/pickFramePressHandlers';
import { pickWebInteractionHandlers } from '../../helpers/pickWebInteractionHandlers';
import { pickWebPressHandlers } from '../../helpers/pickWebPressHandlers';
import type { WebDivRef, WebLiRef } from '../../types/WebElementAttributes';

export type ItemGroupHeaderProps = ItemPartProps<ItemGroupHeaderContract> & {
	/**
	 * The element to render. Inside an `ItemGroup` rendered as `ul`, pass `li` with `aria-hidden`:
	 * the title still names the list, and the list reports only its rows.
	 * A header with interactive content, such as a collapse button, goes outside the list.
	 */
	is?: 'div' | 'li';
};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const itemGroupHeaderFrame = {
	display: 'flex',
	flexDirection: 'row',
	alignItems: 'center',
	flexShrink: 1,
	minWidth: 0,
	minHeight: '$size.x28',
	render: 'div',
	position: 'relative',
	margin: 0,
	paddingBlock: '$space.x4',
	listStyle: 'none',
	color: '$rcx-font-secondary-info',
	borderRadius: '$radius.small',
	gap: '$space.x4',
	fontSize: '0.75rem',
	lineHeight: '1rem',
	fontWeight: '700',
	letterSpacing: 0,
} as const;

const itemGroupHeaderInsets = {
	none: {
		paddingInline: '$space.x4',
	},
	sm: {
		paddingInline: '$space.x8',
	},
	md: {
		paddingInline: '$space.x12',
	},
	lg: {
		paddingInline: {
			'default': '$space.x24',
			'@narrow/rcx-item-group': '$space.x16',
		},
	},
} as const;

const itemGroupHeaderBlockInsets = {
	sm: {
		paddingBlock: '$space.x8',
	},
	md: {
		paddingBlock: '$space.x12',
	},
	lg: {
		paddingBlock: '$space.x16',
	},
} as const;

const itemGroupHeaderSurfaces = {
	'sticky': {
		position: 'sticky',
		zIndex: '$zIndex.overlap',
		top: 0,
		backgroundColor: '$rcx-surface-light',
	},
	'interactive': {
		backgroundColor: {
			hover: '$rcx-surface-hover',
		},
	},
	'sticky-interactive': {
		position: 'sticky',
		zIndex: '$zIndex.overlap',
		top: 0,
		backgroundColor: {
			default: '$rcx-surface-light',
			hover: '$rcx-surface-hover',
		},
	},
} as const;

// end of generated

// The header is a group of the same name as a row, so the actions it holds follow its hover and its focus as they do a row's
const ItemGroupHeaderFrame = styled(View, {
	...itemGroupHeaderFrame,
	group: 'item',
	variants: {
		inset: itemGroupHeaderInsets,
		insetBlock: itemGroupHeaderBlockInsets,
		surface: itemGroupHeaderSurfaces,
	},
});

const surfaceOf = (sticky: boolean | undefined, interactive: boolean | undefined) => {
	if (sticky) {
		return interactive ? 'sticky-interactive' : 'sticky';
	}
	return interactive ? 'interactive' : undefined;
};

/**
 * The label row of a group, such as Favorites, Recent or Moderators. It holds an `ItemGroupTitle` and optional trailing content.
 */
const ItemGroupHeader = (props: ItemGroupHeaderProps) => {
	const { is = 'div', inset = 'none', insetBlock = 'none', sticky, children } = props;
	const [holdsButton, setHoldsButton] = useState(false);
	const interactive = props.interactive ?? holdsButton;

	const reportButton = useCallback(() => {
		setHoldsButton(true);
		return () => setHoldsButton(false);
	}, []);

	const classes = cx(
		cxx('rcx-item-group-header')({
			[`inset-${inset}`]: inset !== 'none',
			[`inset-block-${insetBlock}`]: insetBlock !== 'none',
			sticky: !!sticky,
			interactive,
		}),
		props.className,
	);
	const surface = surfaceOf(sticky, interactive);

	// One literal element per tag: the zero-runtime compiler has to know the tag
	return (
		<ItemGroupHeaderContext.Provider value={props.interactive === undefined ? reportButton : undefined}>
			<ItemRowContext.Provider value={null}>
				{is === 'li' ? (
					<ItemGroupHeaderFrame
						inset={inset}
						insetBlock={insetBlock}
						surface={surface}
						className={classes}
						{...pickFramePressHandlers(props)}
						render={
							<li
								{...ariaAndDataAttributes(props)}
								{...pickWebInteractionHandlers(props)}
								{...pickWebPressHandlers(props)}
								ref={props.ref as WebLiRef}
								id={props.id}
								title={props.title}
								role={props.role}
								tabIndex={props.tabIndex}
							/>
						}
					>
						{children}
					</ItemGroupHeaderFrame>
				) : (
					<ItemGroupHeaderFrame
						inset={inset}
						insetBlock={insetBlock}
						surface={surface}
						className={classes}
						{...pickFramePressHandlers(props)}
						render={
							<div
								{...ariaAndDataAttributes(props)}
								{...pickWebInteractionHandlers(props)}
								{...pickWebPressHandlers(props)}
								ref={props.ref as WebDivRef}
								id={props.id}
								title={props.title}
								role={props.role}
								tabIndex={props.tabIndex}
							/>
						}
					>
						{children}
					</ItemGroupHeaderFrame>
				)}
			</ItemRowContext.Provider>
		</ItemGroupHeaderContext.Provider>
	);
};

export default ItemGroupHeader;
