const paintOf = ({
	dropTarget,
	dropDisabled,
	disabled,
	selected,
	focused,
	hoverable,
	interactive,
}: Pick<ItemProps, 'dropTarget' | 'dropDisabled' | 'disabled' | 'selected' | 'focused' | 'hoverable'> & { interactive: boolean }) => {
	if (dropTarget === 'active') return 'dropActive';
	if (dropDisabled) return 'dropDisabled';
	if (disabled) return 'disabled';
	if (selected) return 'selected';
	if (focused) return 'focused';
	return hoverable || interactive ? 'hover' : undefined;
};

const cursorOf = ({
	disabled,
	dropDisabled,
	grabbable,
	interactive,
}: Pick<ItemProps, 'disabled' | 'dropDisabled' | 'grabbable'> & { interactive: boolean }) => {
	if (disabled || dropDisabled) return 'not-allowed';
	if (grabbable) return 'grab';
	return interactive ? 'pointer' : undefined;
};

const ringOf = ({ dropTarget, focusVisible }: Pick<ItemProps, 'dropTarget' | 'focusVisible'>) => {
	if (dropTarget === 'active') return 'dropActive';
	if (dropTarget === 'available') return 'dropAvailable';
	if (focusVisible === undefined) return 'native';
	return focusVisible ? 'managed-visible' : 'managed';
};

/**
 * A list row composed from slots: media, icon, content and actions.
 */
const Item = (props: ItemProps) => {
	const {
		is = 'div',
		inset = 'none',
		align = 'center',
		hoverable,
		selected,
		highlighted,
		focused,
		focusVisible,
		disabled,
		variant,
		multiline,
		grabbable,
		dragging,
		dropIndicator,
		dropTarget,
		dropDisabled,
		dropped,
		wrap,
		className,
		onClick,
		children,
	} = props;
	const [descriptionIds, registerDescription] = useIdRegistry();
	const [titleIds, registerTitle] = useIdRegistry();

	// A menu item is named by its titles and described by its labelled icons, as an `ItemLink` is.
	const isMenuItem = !!props.role?.startsWith('menuitem');

	// Only a menu item reads its titles' ids, so any other row skips the render a title's registration causes on mount
	const contextValue = useMemo(
		() => ({
			descriptionIds,
			registerDescription,
			registerTitle: isMenuItem ? registerTitle : skipRegistration,
			highlighted: !!highlighted,
			grabbable: !!grabbable,
			dragging: !!dragging,
		}),
		[descriptionIds, registerDescription, registerTitle, isMenuItem, highlighted, grabbable, dragging],
	);

	const ariaLabelledBy = isMenuItem ? (props['aria-labelledby'] ?? (titleIds.join(' ') || undefined)) : props['aria-labelledby'];

	const ariaDescribedBy = isMenuItem
		? [props['aria-describedby'], ...descriptionIds].filter(Boolean).join(' ') || undefined
		: props['aria-describedby'];

	const handleClick: ItemProps['onClick'] = onClick
		? (event) => {
				if (disabled) {
					return;
				}
				onClick(event);
			}
		: undefined;

	const interactive = !!props.interactive || !!onClick || is === 'a' || props.role === 'option' || isMenuItem;

	const classes = cx(
		cxx('rcx-item')({
			[`inset-${inset}`]: inset !== 'none',
			[`align-${align}`]: align !== 'center',
			'hoverable': !!hoverable,
			'clickable': !!onClick,
			'interactive': !!props.interactive,
			'multiline': !!multiline,
			'selected': !!selected,
			'highlighted': !!highlighted,
			'focused': !!focused,
			'focus-managed': focusVisible !== undefined,
			'focus-visible': !!focusVisible,
			'disabled': !!disabled,
			'danger': variant === 'danger',
			'grabbable': !!grabbable,
			'dragging': !!dragging,
			'drop': dropIndicator ?? false,
			'drop-target': dropTarget ?? false,
			'drop-disabled': !!dropDisabled,
			'dropped': !!dropped,
		}),
		className,
	);

	const tone = disabled ? 'disabled' : (variant ?? 'default');
	const paint = paintOf({ dropTarget, dropDisabled, disabled, selected, focused, hoverable, interactive });
	const cursor = cursorOf({ disabled, dropDisabled, grabbable, interactive });
	const ring = ringOf({ dropTarget, focusVisible });

	// One frame per tag, each with a literal `render` element: zero-runtime has to know the tag
	const renderRow = () => {
		if (is === 'li') {
			return (
				<ItemFrame
					align={align}
					tone={tone}
					paint={paint}
					cursor={cursor}
					ring={ring}
					dragging={!!dragging}
					wrap={!!wrap}
					className={classes}
					render={
						<li
							{...ariaAndDataAttributes(props)}
							{...pickWebRowHandlers(props)}
							ref={props.ref as LiRef}
							id={props.id}
							title={props.title}
							role={props.role}
							tabIndex={props.tabIndex}
							value={props.value}
							aria-labelledby={ariaLabelledBy}
							aria-describedby={ariaDescribedBy}
							onClick={handleClick}
						/>
					}
				>
					{children}
				</ItemFrame>
			);
		}

		if (is === 'a') {
			return (
				<ItemFrame
					align={align}
					tone={tone}
					paint={paint}
					cursor={cursor}
					ring={ring}
					dragging={!!dragging}
					wrap={!!wrap}
					className={classes}
					render={
						<a
							{...ariaAndDataAttributes(props)}
							{...pickWebRowHandlers(props)}
							ref={props.ref as AnchorRef}
							id={props.id}
							title={props.title}
							role={props.role}
							tabIndex={props.tabIndex}
							href={props.href}
							target={props.target}
							rel={props.rel}
							download={props.download}
							aria-labelledby={ariaLabelledBy}
							aria-describedby={ariaDescribedBy}
							onClick={handleClick}
						/>
					}
				>
					{children}
				</ItemFrame>
			);
		}

		if (is === 'label') {
			return (
				<ItemFrame
					align={align}
					tone={tone}
					paint={paint}
					cursor={cursor}
					ring={ring}
					dragging={!!dragging}
					wrap={!!wrap}
					className={classes}
					render={
						<label
							{...ariaAndDataAttributes(props)}
							{...pickWebRowHandlers(props)}
							ref={props.ref as LabelRef}
							id={props.id}
							title={props.title}
							role={props.role}
							tabIndex={props.tabIndex}
							aria-labelledby={ariaLabelledBy}
							aria-describedby={ariaDescribedBy}
							onClick={handleClick}
						/>
					}
				>
					{children}
				</ItemFrame>
			);
		}

		return (
			<ItemFrame
				align={align}
				tone={tone}
				paint={paint}
				cursor={cursor}
				ring={ring}
				dragging={!!dragging}
				wrap={!!wrap}
				className={classes}
				render={
					<div
						{...ariaAndDataAttributes(props)}
						{...pickWebRowHandlers(props)}
						ref={props.ref as DivRef}
						id={props.id}
						title={props.title}
						role={props.role}
						tabIndex={props.tabIndex}
						aria-labelledby={ariaLabelledBy}
						aria-describedby={ariaDescribedBy}
						onClick={handleClick}
					/>
				}
			>
				{children}
			</ItemFrame>
		);
	};

	return <ItemContext.Provider value={contextValue}>{renderRow()}</ItemContext.Provider>;
};

export default Item;
