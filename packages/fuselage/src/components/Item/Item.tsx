/**
 * A list row composed from slots: media, icon, content and actions.
 */
const Item = ({
	is: Tag = 'div',
	inset = 'none',
	selected,
	highlighted,
	focused,
	focusVisible,
	disabled,
	variant,
	className,
	onClick,
	children,
	ref,
	...props
}: ItemProps) => {
	const [descriptionIds, registerDescription] = useIdRegistry();
	const [titleIds, registerTitle] = useIdRegistry();

	const contextValue = useMemo(
		() => ({ descriptionIds, registerDescription, registerTitle }),
		[descriptionIds, registerDescription, registerTitle],
	);

	// A menu item is named by its titles and described by its labelled icons, as an `ItemLink` is.
	const isMenuItem = !!props.role?.startsWith('menuitem');

	const ariaLabelledBy = isMenuItem ? (props['aria-labelledby'] ?? (titleIds.join(' ') || undefined)) : props['aria-labelledby'];

	const ariaDescribedBy = isMenuItem
		? [props['aria-describedby'], ...descriptionIds].filter(Boolean).join(' ') || undefined
		: props['aria-describedby'];

	const handleClick = onClick
		? (event: MouseEvent<HTMLElement>) => {
				if (disabled) {
					return;
				}
				onClick(event);
			}
		: undefined;

	// The caller's attributes go on the element `render` names: zero-runtime rejects spreads on a frame
	const attributes = { ...props, 'aria-labelledby': ariaLabelledBy, 'aria-describedby': ariaDescribedBy, 'onClick': handleClick };

	const classes = cx(
		cxx('rcx-item')({
			[`inset-${inset}`]: inset !== 'none',
			'clickable': !!onClick,
			'selected': !!selected,
			'highlighted': !!highlighted,
			'focused': !!focused,
			'focus-managed': focusVisible !== undefined,
			'focus-visible': !!focusVisible,
			'disabled': !!disabled,
			'danger': variant === 'danger',
		}),
		className,
	);

	// Disabled wins over danger; selected over focused
	const tone = [disabled && 'disabled', variant === 'danger' && 'danger'].find(Boolean) || 'default';
	const surface = [disabled && 'disabled', selected && 'selected', focused && 'focused'].find(Boolean) || 'none';

	return (
		<ItemContext.Provider value={contextValue}>
			<ItemFrame
				render={<Tag {...attributes} ref={ref} />}
				tone={tone}
				surface={surface}
				ring={focusVisible === undefined ? 'native' : 'managed'}
				className={classes}
			>
				{children}
			</ItemFrame>
		</ItemContext.Provider>
	);
};

export default Item;
