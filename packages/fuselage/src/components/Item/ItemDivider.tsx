import { styled, View } from '@tamagui/web';

import type { ItemPartAttributes, ItemInset } from './types';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { cx, cxx } from '../../helpers/composeClassNames';
import { pickWebPressHandlers } from '../../helpers/pickAttributes';
import type { DivRef, LiRef } from '../../types/ElementAttributes';

export type ItemDividerProps = {
	/**
	 * The element to render. Inside an `ItemGroup` rendered as `ul`, pass `li` with `aria-hidden`.
	 * Add `role='separator'` where the divider should be announced, as between menu sections.
	 */
	is?: 'div' | 'li';
	/**
	 * Aligns the line with the content of the rows. Without it, the line spans the full width.
	 */
	inset?: ItemInset;
	/**
	 * `light` draws the line in the light stroke, for a divider on the sidebar's surface.
	 */
	variation?: 'light';
} & ItemPartAttributes;

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const itemDividerFrame = {
	display: 'block',
	flexDirection: 'row',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	render: 'div',
	margin: 0,
	paddingBlock: '4px',
	paddingInline: 0,
	borderWidth: 0,
	borderStyle: 'none',
	borderColor: 'currentcolor',
} as const;

const itemDividerInsets = {
	sm: {
		marginInline: 'calc(4px + var(--rcx-item-inset-inline))',
	},
	md: {
		marginInline: 'calc(4px + var(--rcx-item-inset-inline))',
	},
	lg: {
		marginInline: 'calc(4px + var(--rcx-item-inset-inline))',
	},
} as const;

// end of generated

// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const ItemDividerFrame = styled(View, {
	...itemDividerFrame,
	variants: { inset: itemDividerInsets },
});

/**
 * The divider between groups, menu sections, or a header and its rows.
 */
const ItemDivider = (props: ItemDividerProps) => {
	const { is = 'div', inset = 'none', variation, className } = props;

	const classes = cx(cxx('rcx-item-divider')({ [`inset-${inset}`]: inset !== 'none', light: variation === 'light' }), className);
	const frameInset = inset === 'none' ? undefined : inset;

	return is === 'li' ? (
		<ItemDividerFrame
			inset={frameInset}
			className={classes}
			render={
				<li
					{...ariaAndDataAttributes(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref as LiRef}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		/>
	) : (
		<ItemDividerFrame
			inset={frameInset}
			className={classes}
			render={
				<div
					{...ariaAndDataAttributes(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref as DivRef}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		/>
	);
};

export default ItemDivider;
