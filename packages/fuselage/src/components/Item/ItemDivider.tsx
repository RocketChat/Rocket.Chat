import { styled, View } from '@tamagui/web';

import type { ItemDividerContract } from './Item.contract';
import type { ItemPartProps } from './types';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { cx, cxx } from '../../helpers/composeClassNames';
import { pickFramePressHandlers } from '../../helpers/pickFramePressHandlers';
import { pickWebInteractionHandlers } from '../../helpers/pickWebInteractionHandlers';
import { pickWebPressHandlers } from '../../helpers/pickWebPressHandlers';
import type { WebDivRef, WebLiRef } from '../../types/WebElementAttributes';

export type ItemDividerProps = ItemPartProps<ItemDividerContract> & {
	/**
	 * The element to render. Inside an `ItemGroup` rendered as `ul`, pass `li` with `aria-hidden`.
	 * Add `role='separator'` where the divider should be announced, as between menu sections.
	 */
	is?: 'div' | 'li';
};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const itemDividerFrame = {
	display: 'block',
	flexDirection: 'row',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	render: 'div',
	margin: 0,
	paddingBlock: '$space.x4',
	paddingInline: 0,
	listStyle: 'none',
	borderWidth: 0,
	borderStyle: 'none',
	borderColor: 'currentcolor',
} as const;

const itemDividerInsets = {
	sm: {
		marginInline: '$space.x8',
	},
	md: {
		marginInline: '$space.x12',
	},
	lg: {
		marginInline: {
			'default': '$space.x24',
			'@narrow/rcx-item-group': '$space.x16',
		},
	},
} as const;

// end of generated

const ItemDividerFrame = styled(View, {
	...itemDividerFrame,
	variants: { inset: itemDividerInsets },
});

/**
 * The divider between groups, menu sections, or a header and its rows.
 */
const ItemDivider = (props: ItemDividerProps) => {
	const { is = 'div', inset = 'none' } = props;
	const classes = cx(cxx('rcx-item-divider')({ [`inset-${inset}`]: inset !== 'none' }), props.className);
	const frameInset = inset === 'none' ? undefined : inset;

	// One literal element per tag: the zero-runtime compiler has to know the tag
	return is === 'li' ? (
		<ItemDividerFrame
			inset={frameInset}
			className={classes}
			{...pickFramePressHandlers(props)}
			render={
				<li
					{...ariaAndDataAttributes(props)}
					{...pickWebInteractionHandlers(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref as WebLiRef}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		/>
	) : (
		<ItemDividerFrame
			inset={frameInset}
			className={classes}
			{...pickFramePressHandlers(props)}
			render={
				<div
					{...ariaAndDataAttributes(props)}
					{...pickWebInteractionHandlers(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref as WebDivRef}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		/>
	);
};

export default ItemDivider;
