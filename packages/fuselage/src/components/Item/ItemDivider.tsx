import { styled, View } from '@tamagui/web';
import type { AriaRole, ReactNode, Ref } from 'react';

import type { ItemInset } from './types';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { cx, cxx } from '../../helpers/composeClassNames';
import type { PartAttributes } from '../../types/ElementAttributes';

export type ItemDividerProps = PartAttributes<HTMLElement> & {
	/**
	 * The element to render. Inside an `ItemGroup` rendered as `ul`, pass `li` with `aria-hidden`.
	 * Add `role='separator'` where the divider should be announced, as between menu sections.
	 */
	'is'?: 'div' | 'li';
	/**
	 * Aligns the line with the content of the rows. Without it, the line spans the full width.
	 */
	'inset'?: ItemInset;
	'role'?: AriaRole;
	'aria-hidden'?: boolean;
	'aria-orientation'?: 'horizontal' | 'vertical';
	'children'?: ReactNode;
};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const ItemDividerFrame = styled(View, {
	render: 'div',
	position: 'static',
	display: 'block',
	flexDirection: 'row',
	flexShrink: 1,
	alignItems: 'normal',
	minWidth: 'auto',
	minHeight: 'auto',
	margin: 0,
	paddingBlock: '4px',
	paddingInline: 0,
	borderWidth: 0,
	borderStyle: 'none',
});

// end of generated

/**
 * The divider between groups, menu sections, or a header and its rows.
 */
const ItemDivider = (props: ItemDividerProps) => {
	const { inset = 'none' } = props;
	const className = cx(cxx('rcx-item-divider')({ [`inset-${inset}`]: inset !== 'none' }), props.className);

	// One branch per tag: zero-runtime has to know it
	if (props.is === 'li') {
		return (
			<ItemDividerFrame
				className={className}
				render={
					<li
						{...ariaAndDataAttributes(props)}
						// The ref is typed for both tags, each branch renders one
						ref={props.ref as Ref<HTMLLIElement>}
						id={props.id}
						title={props.title}
						role={props.role}
					/>
				}
			>
				{props.children}
			</ItemDividerFrame>
		);
	}

	return (
		<ItemDividerFrame
			className={className}
			render={
				<div {...ariaAndDataAttributes(props)} ref={props.ref as Ref<HTMLDivElement>} id={props.id} title={props.title} role={props.role} />
			}
		>
			{props.children}
		</ItemDividerFrame>
	);
};

export default ItemDivider;
