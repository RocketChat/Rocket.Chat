/* oxlint-disable jsx-a11y/heading-has-content -- the children are the consumer's title */
import { styled, Text } from '@tamagui/web';
import { useEffect, useId } from 'react';

import { useItemGroupContext } from './ItemGroupContext';
import type { ItemPartAttributes } from './types';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { cx } from '../../helpers/composeClassNames';
import { pickWebPressHandlers } from '../../helpers/pickAttributes';
import type { ButtonRef, DivRef, HeadingRef } from '../../types/ElementAttributes';

export type ItemGroupTitleProps = {
	/**
	 * The element to render. Use a heading level, or `button` when the owner makes the group collapsible.
	 */
	is?: 'div' | 'button' | 'h2' | 'h3' | 'h4';
	/** The type of the `button`, which is `button` unless set. */
	type?: 'button' | 'submit' | 'reset';
} & ItemPartAttributes;

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const itemGroupTitleFrame = {
	wordWrap: 'inherit',
	display: 'block',
	flexDirection: 'row',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 0,
	minHeight: 'auto',
	render: 'div',
	overflow: 'hidden',
	flexGrow: 1,
	flexBasis: 'auto',
	margin: 0,
	whiteSpace: 'nowrap',
	textOverflow: 'ellipsis',
	color: 'inherit',
	fontVariantNumeric: 'inherit',
	fontFamily: 'inherit',
	fontSize: 'inherit',
	fontWeight: 'inherit',
	lineHeight: 'inherit',
	letterSpacing: 'inherit',
} as const;

const itemGroupTitleButton = {
	display: 'flex',
	alignItems: 'center',
	padding: 0,
	cursor: 'pointer',
	textAlign: 'start',
	borderWidth: 0,
	borderStyle: 'none',
	borderColor: 'currentcolor',
	outlineWidth: 0,
	outlineStyle: 'none',
	backgroundColor: 'transparent',
	gap: '4px',
} as const;

// end of generated

// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const ItemGroupTitleFrame = styled(Text, {
	...itemGroupTitleFrame,
	variants: { button: { true: itemGroupTitleButton } },
});

/**
 * The text of an `ItemGroupHeader`. Inside an `ItemGroup`, it becomes the group's accessible name.
 */
const ItemGroupTitle = (props: ItemGroupTitleProps) => {
	const { is = 'div', className, children } = props;
	const generatedId = useId();
	const id = props.id ?? generatedId;
	const { registerTitle } = useItemGroupContext();

	useEffect(() => registerTitle(id), [id, registerTitle]);

	const classes = cx('rcx-item-group-title', className);

	if (is === 'button') {
		return (
			<ItemGroupTitleFrame
				button
				className={classes}
				render={
					<button
						{...ariaAndDataAttributes(props)}
						{...pickWebPressHandlers(props)}
						ref={props.ref as ButtonRef}
						id={id}
						title={props.title}
						role={props.role}
						tabIndex={props.tabIndex}
						type={props.type ?? 'button'}
					/>
				}
			>
				{children}
			</ItemGroupTitleFrame>
		);
	}

	if (is === 'div') {
		return (
			<ItemGroupTitleFrame
				className={classes}
				button={false}
				render={
					<div
						{...ariaAndDataAttributes(props)}
						{...pickWebPressHandlers(props)}
						ref={props.ref as DivRef}
						id={id}
						title={props.title}
						role={props.role}
						tabIndex={props.tabIndex}
					/>
				}
			>
				{children}
			</ItemGroupTitleFrame>
		);
	}

	if (is === 'h2') {
		return (
			<ItemGroupTitleFrame
				className={classes}
				button={false}
				render={
					<h2
						{...ariaAndDataAttributes(props)}
						{...pickWebPressHandlers(props)}
						ref={props.ref as HeadingRef}
						id={id}
						title={props.title}
						role={props.role}
						tabIndex={props.tabIndex}
					/>
				}
			>
				{children}
			</ItemGroupTitleFrame>
		);
	}

	if (is === 'h3') {
		return (
			<ItemGroupTitleFrame
				className={classes}
				button={false}
				render={
					<h3
						{...ariaAndDataAttributes(props)}
						{...pickWebPressHandlers(props)}
						ref={props.ref as HeadingRef}
						id={id}
						title={props.title}
						role={props.role}
						tabIndex={props.tabIndex}
					/>
				}
			>
				{children}
			</ItemGroupTitleFrame>
		);
	}

	return (
		<ItemGroupTitleFrame
			className={classes}
			button={false}
			render={
				<h4
					{...ariaAndDataAttributes(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref as HeadingRef}
					id={id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{children}
		</ItemGroupTitleFrame>
	);
};

export default ItemGroupTitle;
