// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const ItemGroupTitleFrame = styled(Text, {
	...itemGroupTitleFrame,
	variants: { look: itemGroupTitleLooks },
});

/**
 * The text of an `ItemGroupHeader`. Inside an `ItemGroup`, it becomes the group's accessible name.
 */
const ItemGroupTitle = (props: ItemGroupTitleProps) => {
	const { is = 'div', ring, className, children } = props;
	const generatedId = useId();
	const id = props.id ?? generatedId;
	const { registerTitle } = useItemGroupContext();

	useEffect(() => registerTitle(id), [id, registerTitle]);

	const classes = cx('rcx-item-group-title', className);
	const look = ring === 'border' ? 'border' : undefined;

	if (is === 'button') {
		return (
			<ItemGroupTitleFrame
				look={ring === 'border' ? 'border' : 'button'}
				className={classes}
				render={
					<button
						{...ariaAndDataAttributes(props)}
						{...pickWebPressHandlers(props)}
						ref={props.ref as ButtonRef}
						id={id}
						title={props.title}
						role={props.role}
						tabIndex={props.tabIndex}
						type={props.type ?? 'button'}
					/>
				}
			>
				{children}
			</ItemGroupTitleFrame>
		);
	}

	if (is === 'div') {
		return (
			<ItemGroupTitleFrame
				className={classes}
				look={look}
				render={
					<div
						{...ariaAndDataAttributes(props)}
						{...pickWebPressHandlers(props)}
						ref={props.ref as DivRef}
						id={id}
						title={props.title}
						role={props.role}
						tabIndex={props.tabIndex}
					/>
				}
			>
				{children}
			</ItemGroupTitleFrame>
		);
	}

	if (is === 'h2') {
		return (
			<ItemGroupTitleFrame
				className={classes}
				look={look}
				render={
					<h2
						{...ariaAndDataAttributes(props)}
						{...pickWebPressHandlers(props)}
						ref={props.ref as HeadingRef}
						id={id}
						title={props.title}
						role={props.role}
						tabIndex={props.tabIndex}
					/>
				}
			>
				{children}
			</ItemGroupTitleFrame>
		);
	}

	if (is === 'h3') {
		return (
			<ItemGroupTitleFrame
				className={classes}
				look={look}
				render={
					<h3
						{...ariaAndDataAttributes(props)}
						{...pickWebPressHandlers(props)}
						ref={props.ref as HeadingRef}
						id={id}
						title={props.title}
						role={props.role}
						tabIndex={props.tabIndex}
					/>
				}
			>
				{children}
			</ItemGroupTitleFrame>
		);
	}

	return (
		<ItemGroupTitleFrame
			className={classes}
			look={look}
			render={
				<h4
					{...ariaAndDataAttributes(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref as HeadingRef}
					id={id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{children}
		</ItemGroupTitleFrame>
	);
};

export default ItemGroupTitle;
