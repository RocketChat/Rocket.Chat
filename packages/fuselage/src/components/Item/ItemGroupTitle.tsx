import type { ButtonRef, DivRef, HeadingRef } from '../../types/ElementAttributes';

export type ItemGroupTitleProps = {
	/**
	 * The element to render. Use a heading level, or `button` when the owner makes the group collapsible.
	 */
	is?: 'div' | 'button' | 'h2' | 'h3' | 'h4';
	/** The type of the `button`, which is `button` unless set. */
	type?: 'button' | 'submit' | 'reset';
	/**
	 * `border` shows the focus ring as a 1px border that turns highlight, for a title that acts as a button without being one.
	 * Use it with `is='div'` and a `role`, not with `is='button'`.
	 */
	ring?: 'border';
} & ItemPartAttributes;

