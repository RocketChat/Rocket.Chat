import { styled, Text } from '@tamagui/web';
import { useContext, useEffect, useId, useLayoutEffect } from 'react';

import type { ItemGroupTitleContract } from './Item.contract';
import { ItemGroupHeaderContext } from './ItemContext';
import { useItemGroupContext } from './ItemGroupContext';
import type { ItemPartProps } from './types';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { cx } from '../../helpers/composeClassNames';
import { pickWebInteractionHandlers } from '../../helpers/pickWebInteractionHandlers';
import { pickWebPressHandlers } from '../../helpers/pickWebPressHandlers';
import type { WebButtonRef, WebDivRef, WebHeadingRef } from '../../types/WebElementAttributes';

export type ItemGroupTitleProps = ItemPartProps<ItemGroupTitleContract> & {
	/**
	 * The element to render. Use a heading level, or `button` when the owner makes the group collapsible.
	 */
	is?: 'div' | 'button' | 'h2' | 'h3' | 'h4';
	/** The type of the `button`, which is `button` unless set. */
	type?: 'button' | 'submit' | 'reset';
};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const itemGroupTitleFrame = {
	wordWrap: 'inherit',
	display: 'block',
	flexShrink: 1,
	minWidth: 0,
	minHeight: 'auto',
	render: 'div',
	overflow: 'hidden',
	flexGrow: 1,
	margin: 0,
	whiteSpace: 'nowrap',
	textOverflow: 'ellipsis',
	color: 'inherit',
	fontVariantNumeric: 'inherit',
	fontFamily: 'inherit',
	fontSize: 'inherit',
	fontWeight: 'inherit',
	lineHeight: 'inherit',
	letterSpacing: 'inherit',
} as const;

const itemGroupTitleButton = {
	display: 'flex',
	alignItems: 'center',
	padding: 0,
	cursor: 'pointer',
	textAlign: 'start',
	borderWidth: 0,
	borderStyle: 'none',
	borderColor: 'currentcolor',
	outlineWidth: 0,
	outlineStyle: 'none',
	backgroundColor: 'transparent',
	gap: '$space.x4',
} as const;

// end of generated

const ItemGroupTitleFrame = styled(Text, {
	...itemGroupTitleFrame,
	variants: { button: { true: itemGroupTitleButton, false: {} } },
});

/**
 * The text of an `ItemGroupHeader`. Inside an `ItemGroup`, it becomes the group's accessible name.
 */
const ItemGroupTitle = (props: ItemGroupTitleProps) => {
	const { is = 'div', children } = props;
	const generatedId = useId();
	const id = props.id ?? generatedId;
	const { registerTitle } = useItemGroupContext();
	const reportButton = useContext(ItemGroupHeaderContext);
	const classes = cx('rcx-item-group-title', props.className);

	useEffect(() => registerTitle(id), [id, registerTitle]);
	useLayoutEffect(() => (is === 'button' ? reportButton?.() : undefined), [is, reportButton]);

	// One literal element per tag: the zero-runtime compiler has to know the tag
	if (is === 'button') {
		return (
			<ItemGroupTitleFrame
				button={true}
				className={classes}
				render={
					<button
						{...ariaAndDataAttributes(props)}
						{...pickWebInteractionHandlers(props)}
						{...pickWebPressHandlers(props)}
						ref={props.ref as WebButtonRef}
						id={id}
						title={props.title}
						role={props.role}
						tabIndex={props.tabIndex}
						type={props.type ?? 'button'}
					/>
				}
			>
				{children}
			</ItemGroupTitleFrame>
		);
	}

	if (is === 'h2') {
		return (
			<ItemGroupTitleFrame
				button={false}
				className={classes}
				render={
					<h2
						{...ariaAndDataAttributes(props)}
						{...pickWebInteractionHandlers(props)}
						{...pickWebPressHandlers(props)}
						ref={props.ref as WebHeadingRef}
						id={id}
						title={props.title}
						role={props.role}
						tabIndex={props.tabIndex}
					/>
				}
			>
				{children}
			</ItemGroupTitleFrame>
		);
	}

	if (is === 'h3') {
		return (
			<ItemGroupTitleFrame
				button={false}
				className={classes}
				render={
					<h3
						{...ariaAndDataAttributes(props)}
						{...pickWebInteractionHandlers(props)}
						{...pickWebPressHandlers(props)}
						ref={props.ref as WebHeadingRef}
						id={id}
						title={props.title}
						role={props.role}
						tabIndex={props.tabIndex}
					/>
				}
			>
				{children}
			</ItemGroupTitleFrame>
		);
	}

	if (is === 'h4') {
		return (
			<ItemGroupTitleFrame
				button={false}
				className={classes}
				render={
					<h4
						{...ariaAndDataAttributes(props)}
						{...pickWebInteractionHandlers(props)}
						{...pickWebPressHandlers(props)}
						ref={props.ref as WebHeadingRef}
						id={id}
						title={props.title}
						role={props.role}
						tabIndex={props.tabIndex}
					/>
				}
			>
				{children}
			</ItemGroupTitleFrame>
		);
	}

	return (
		<ItemGroupTitleFrame
			button={false}
			className={classes}
			render={
				<div
					{...ariaAndDataAttributes(props)}
					{...pickWebInteractionHandlers(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref as WebDivRef}
					id={id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{children}
		</ItemGroupTitleFrame>
	);
};

export default ItemGroupTitle;
