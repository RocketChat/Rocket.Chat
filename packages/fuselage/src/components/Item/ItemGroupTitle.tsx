import { styled, Text } from '@tamagui/web';
import type { AriaAttributes, AriaRole, DOMAttributes, ReactNode, Ref } from 'react';
import { useEffect, useId } from 'react';

import { useItemGroupContext } from './ItemGroupContext';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { cx } from '../../helpers/composeClassNames';
import type { PartAttributes } from '../../types/ElementAttributes';

export type ItemGroupTitleProps = PartAttributes<HTMLElement> &
	Pick<DOMAttributes<HTMLElement>, 'onClick' | 'onKeyDown'> &
	Pick<AriaAttributes, 'aria-expanded' | 'aria-controls' | 'aria-disabled' | 'aria-labelledby' | 'aria-hidden'> & {
		/**
		 * The element to render. Use a heading, or `button` when the owner makes the group collapsible.
		 */
		is?: 'div' | 'h3' | 'button';
		role?: AriaRole;
		tabIndex?: number;
		children?: ReactNode;
	};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const ItemGroupTitleFrame = styled(Text, {
	wordWrap: 'inherit',
	render: 'div',
	position: 'static',
	display: 'block',
	flexDirection: 'row',
	flexShrink: 1,
	alignItems: 'normal',
	minWidth: 0,
	minHeight: 'auto',
	overflow: 'hidden',
	whiteSpace: 'nowrap',
	textOverflow: 'ellipsis',
	flexGrow: 1,
	flexBasis: 'auto',
	margin: 0,
	color: 'inherit',
});

// end of generated

/**
 * The text of an `ItemGroupHeader`. Inside an `ItemGroup`, it becomes the group's accessible name.
 */
const ItemGroupTitle = (props: ItemGroupTitleProps) => {
	const generatedId = useId();
	const id = props.id ?? generatedId;
	const { registerTitle } = useItemGroupContext();

	useEffect(() => registerTitle(id), [id, registerTitle]);

	const className = cx('rcx-item-group-title', props.className);

	// One branch per tag: zero-runtime has to know it
	if (props.is === 'button') {
		return (
			<ItemGroupTitleFrame
				className={className}
				render={
					<button
						{...ariaAndDataAttributes(props)}
						type='button'
						// The ref is typed for every tag, each branch renders one
						ref={props.ref as Ref<HTMLButtonElement>}
						id={id}
						title={props.title}
						role={props.role}
						tabIndex={props.tabIndex}
						onClick={props.onClick}
						onKeyDown={props.onKeyDown}
					/>
				}
			>
				{props.children}
			</ItemGroupTitleFrame>
		);
	}

	if (props.is === 'h3') {
		return (
			<ItemGroupTitleFrame
				className={className}
				render={
					// oxlint-disable-next-line jsx-a11y/heading-has-content, jsx-a11y/no-noninteractive-element-interactions -- the frame's children are the content; the handlers are the consumer's
					<h3
						{...ariaAndDataAttributes(props)}
						ref={props.ref as Ref<HTMLHeadingElement>}
						id={id}
						title={props.title}
						role={props.role}
						tabIndex={props.tabIndex}
						onClick={props.onClick}
						onKeyDown={props.onKeyDown}
					/>
				}
			>
				{props.children}
			</ItemGroupTitleFrame>
		);
	}

	return (
		<ItemGroupTitleFrame
			className={className}
			render={
				<div
					{...ariaAndDataAttributes(props)}
					ref={props.ref as Ref<HTMLDivElement>}
					id={id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
					onClick={props.onClick}
					onKeyDown={props.onKeyDown}
				/>
			}
		>
			{props.children}
		</ItemGroupTitleFrame>
	);
};

export default ItemGroupTitle;
