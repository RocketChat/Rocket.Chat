import { styled, View } from '@tamagui/web';

import { ItemRowContext } from './ItemContext';
import type { ItemPartAttributes } from './types';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { cx } from '../../helpers/composeClassNames';
import { pickWebPressHandlers } from '../../helpers/pickAttributes';
import type { DivRef } from '../../types/ElementAttributes';

export type ItemRowProps = {
	/**
	 * Keeps the height of the line when actions sit on it, as in a list whose rows all share one height.
	 */
	fixedHeight?: boolean;
} & ItemPartAttributes;

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const itemRowFrame = {
	display: 'flex',
	flexDirection: 'row',
	alignItems: 'center',
	flexShrink: 1,
	minWidth: 0,
	minHeight: 'auto',
	render: 'div',
	gap: 'var(--rcx-item-gap)',
} as const;

// end of generated

// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const ItemRowFrame = styled(View, { ...itemRowFrame });

const flexibleRow = { fixedHeight: false };
const fixedRow = { fixedHeight: true };

/**
 * A horizontal line inside `ItemContent`, such as a title with a timestamp or a description with a badge.
 */
const ItemRow = (props: ItemRowProps) => (
	<ItemRowContext.Provider value={props.fixedHeight ? fixedRow : flexibleRow}>
		<ItemRowFrame
			className={cx('rcx-item__row', props.className)}
			render={
				<div
					{...ariaAndDataAttributes(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref as DivRef}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{props.children}
		</ItemRowFrame>
	</ItemRowContext.Provider>
);

export default ItemRow;
