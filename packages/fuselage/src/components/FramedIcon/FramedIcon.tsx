import type { Keys } from '@rocket.chat/icons';
import nameToCharacterMapping from '@rocket.chat/icons';
import { styled, Text } from '@tamagui/web';
import type { CSSProperties } from 'react';

import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { resolveFontScale, size as sizeToken } from '../../styleTokens';
import type { PartAttributes } from '../../types/ElementAttributes';
import type { IconProps } from '../Icon';

export type FramedIconProps = PartAttributes<HTMLElement> & {
	'info'?: boolean;
	'success'?: boolean;
	'warning'?: boolean;
	'danger'?: boolean;
	'neutral'?: boolean;
	'icon': Keys;
	'size'?: IconProps['size'];
	'aria-hidden'?: boolean | 'true' | 'false';
};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

// Declared where they render: zero-runtime only erases a `styled()` whose every use is in its own module
const FramedIconFrame = styled(Text, {
	flexBasis: 'auto',
	whiteSpace: 'inherit',
	wordWrap: 'inherit',
	render: 'i',
	display: 'inline-block',
	flexDirection: 'row',
	alignItems: 'normal',
	flexShrink: 0,
	minWidth: 'auto',
	minHeight: 'auto',
	fontSize: 'var(--rcx-framed-icon-size)',
	padding: '4px',
	color: 'var(--rcx-color-font-secondary-info, #6c737a)',
	borderRadius: 'var(--rcx-border-radius-medium, 0.25rem)',
	backgroundColor: 'var(--rcx-color-surface-tint, #f7f8fa)',
	variants: {
		tone: {
			neutral: {},
			info: {
				color: 'var(--rcx-color-status-font-on-info, #095ad2)',
			},
			success: {
				color: 'var(--rcx-color-status-font-on-success, #148660)',
			},
			warning: {
				color: 'var(--rcx-color-status-font-on-warning, #895f00)',
			},
			danger: {
				color: 'var(--rcx-color-status-font-on-danger, #9b1325)',
			},
		},
	},
});

// end of generated

const FramedIcon = (props: FramedIconProps) => {
	const { info, success, warning, danger, neutral, icon, size = 20, className } = props;
	// The open size reaches the frame as a custom property: zero-runtime can't lower a style it doesn't know at build time
	const sized = { style: { '--rcx-framed-icon-size': resolveFontScale(size)?.fontSize ?? sizeToken(size) } as CSSProperties };

	return (
		<FramedIconFrame
			render={
				<i
					{...ariaAndDataAttributes(props)}
					{...sized}
					aria-hidden={props['aria-hidden'] ?? 'true'}
					ref={props.ref}
					id={props.id}
					title={props.title}
				/>
			}
			tone={
				(
					[
						['danger', danger],
						['warning', warning],
						['success', success],
						['info', info],
					] as const
				).find(([, on]) => on)?.[0] ?? 'neutral'
			}
			className={[
				'rcx-box rcx-box--full',
				`rcx-icon--name-${icon}`,
				'rcx-icon',
				className,
				'rcx-framed-icon',
				info && 'rcx-framed-icon--info',
				success && 'rcx-framed-icon--success',
				warning && 'rcx-framed-icon--warning',
				danger && 'rcx-framed-icon--danger',
				(neutral || (!info && !success && !warning && !danger)) && 'rcx-framed-icon--neutral',
			]
				.filter(Boolean)
				.join(' ')}
		>
			{nameToCharacterMapping[icon]}
		</FramedIconFrame>
	);
};

export default FramedIcon;
