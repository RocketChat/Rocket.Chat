import { styled, Text, View } from '@tamagui/web';
import type { AriaAttributes, ReactElement } from 'react';

import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { prependClassName } from '../../helpers/prependClassName';
import type { PreAttributes } from '../../types/ElementAttributes';
import { Button } from '../Button';
import { Skeleton } from '../Skeleton';

export type CodeSnippetProps = PreAttributes &
	Pick<AriaAttributes, 'aria-label' | 'aria-labelledby' | 'aria-describedby'> & {
		children: string;
		buttonText?: string;
		buttonDisabled?: boolean;
		/** Copies the code; the snippet shows its button only with it. */
		onClick?: () => void;
	};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const codeSnippetFrame = {
	render: 'pre',
	display: 'flex',
	flexDirection: 'row',
	alignItems: 'center',
	justifyContent: 'space-between',
	flexShrink: 1,
	minWidth: 'auto',
	width: '100%',
	minHeight: '3.75rem',
	padding: '16px',
	color: 'var(--rcx-color-font-default, #2f343d)',
	borderRadius: 'var(--rcx-code-snippet-border-radius, var(--rcx-border-radius-medium, 0.25rem))',
	backgroundColor: 'var(--rcx-color-surface-neutral, #e4e7ea)',
} as const;

const codeSnippetCodeBox = {
	flexBasis: 'auto',
	wordWrap: 'inherit',
	render: 'div',
	display: 'block',
	flexDirection: 'row',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	marginRight: '8px',
	whiteSpace: 'pre-line',
	wordBreak: 'break-all',
	fontFamily: 'monospace',
} as const;

const codeSnippetAction = {
	render: 'div',
	display: 'block',
	flexDirection: 'row',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
} as const;

// end of generated

// Declared where they render: zero-runtime only erases a `styled()` whose every use is in its own module
const CodeSnippetFrame = styled(View, { ...codeSnippetFrame });

const CodeSnippetCodeBox = styled(Text, { ...codeSnippetCodeBox });

const CodeSnippetAction = styled(View, { ...codeSnippetAction });

/**
 * The `CodeSnippet` is used to show code or commands and make easier to copy them.
 *
 * The default button text is `Copy` but you can use the `buttonText` prop to handle translations in your project.
 *
 * Please check the `useClipBoard` hook in `fuselage-hooks` package, to handle the copy behaviour.
 */
const CodeSnippet = (props: CodeSnippetProps): ReactElement<CodeSnippetProps> => {
	const { children, onClick, buttonText = 'Copy', buttonDisabled = false, className } = props;
	const classes = prependClassName(className, 'rcx-box rcx-box--full rcx-code-snippet');

	if (!children) {
		return (
			<CodeSnippetFrame
				className={classes}
				render={<pre {...ariaAndDataAttributes(props)} ref={props.ref} id={props.id} title={props.title} />}
			>
				<Skeleton width='100%' aria-hidden aria-busy />
			</CodeSnippetFrame>
		);
	}

	return (
		<CodeSnippetFrame
			className={classes}
			render={<pre {...ariaAndDataAttributes(props)} ref={props.ref} id={props.id} title={props.title} />}
		>
			<CodeSnippetCodeBox className='rcx-box rcx-box--full rcx-code-snippet__codebox' render={<div role='code' />}>
				{children}
			</CodeSnippetCodeBox>
			{onClick && (
				<CodeSnippetAction className='rcx-box rcx-box--full'>
					<Button size='small' variant='primary' onClick={onClick} disabled={buttonDisabled}>
						{buttonText}
					</Button>
				</CodeSnippetAction>
			)}
		</CodeSnippetFrame>
	);
};

export default CodeSnippet;
