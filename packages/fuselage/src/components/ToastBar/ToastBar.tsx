/**
 * Shows alerts in a toast component.
 */
function ToastBar(props: ToastBarProps) {
	const { children, className, variant = 'info', time = 5, isPaused, id, onClose, buttonLabel = 'Dismiss alert' } = props;
	const iconName = (variant === 'success' && 'circle-check') || (variant === 'error' && 'ban') || 'info';

	const uniqueId = useId();
	const toastId = id || uniqueId;

	const role = variant === 'error' ? 'alert' : 'status';

	return (
		<ToastBarFrame
			className={prependClassName(className, `rcx-box rcx-box--full rcx-toastbar rcx-toastbar--${variant}`)}
			render={
				<div
					{...ariaAndDataAttributes(props)}
					ref={props.ref}
					id={id}
					title={props.title}
					onPointerEnter={props.onPointerEnter}
					onPointerLeave={props.onPointerLeave}
				/>
			}
		>
			<ToastBarInner className='rcx-toastbar_inner'>
				<Icon className={`rcx-toastbar_icon--${variant}`} size='x20' name={iconName} />
				<ToastBarContent className='rcx-toastbar_content' render={<div role={role} />}>
					{children}
				</ToastBarContent>
				{onClose && (
					<div className='rcx-toastbar-close'>
						<IconButton size='tiny' aria-label={buttonLabel} onClick={() => onClose(toastId)} icon='cross' />
					</div>
				)}
			</ToastBarInner>
			<ToastBarProgress
				className={`rcx-box rcx-box--full rcx-toastbar_progressbar${isPaused ? ' rcx-toastbar_progressbar--paused' : ''}`}
				render={<div {...customProperties({ '--rcx-toastbar-time': `${time}s` })} />}
			/>
		</ToastBarFrame>
	);
}

export default ToastBar;
