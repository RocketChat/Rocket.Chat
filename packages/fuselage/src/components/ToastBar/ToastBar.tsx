/**
 * Shows alerts in a toast component.
 */
function ToastBar(props: ToastBarProps) {
	const { children, className, variant = 'info', time = 5, isPaused, id, onClose, buttonLabel = 'Dismiss alert' } = props;
	const iconName = (variant === 'success' && 'circle-check') || (variant === 'error' && 'ban') || 'info';

	const uniqueId = useId();
	const toastId = id || uniqueId;

	const role = variant === 'error' ? 'alert' : 'status';

	// It goes in an attributes object because zero-runtime rejects a `style` written on a frame or its render element
	const progressAttributes = {
		style: {
			'--rcx-toastbar-progress-time': `${time}s`,
			'--rcx-toastbar-progress-state': isPaused ? 'paused' : 'running',
		} as CSSProperties,
	};

	return (
		<ToastBarFrame
			render={
				<div
					{...ariaAndDataAttributes(props)}
					ref={props.ref}
					id={id}
					title={props.title}
					onPointerEnter={props.onPointerEnter}
					onPointerLeave={props.onPointerLeave}
				/>
			}
			className={['rcx-box rcx-box--full rcx-toastbar', `rcx-toastbar--${variant}`, className].filter(Boolean).join(' ')}
		>
			<ToastBarInnerFrame className='rcx-toastbar_inner'>
				<Icon className={`rcx-toastbar_icon--${variant}`} size='x20' name={iconName} />
				<ToastBarContentFrame render={<div role={role} />} className='rcx-toastbar_content'>
					{children}
				</ToastBarContentFrame>
				{onClose && (
					<div className='rcx-toastbar-close'>
						<IconButton size='tiny' aria-label={buttonLabel} onClick={() => onClose(toastId)} icon='cross' />
					</div>
				)}
			</ToastBarInnerFrame>
			<ToastBarProgressFrame render={<div {...progressAttributes} />} className='rcx-box rcx-box--full rcx-toastbar_progressbar' />
		</ToastBarFrame>
	);
}

export default ToastBar;
