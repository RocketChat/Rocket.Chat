/**
 * Used for mentions
 */
const Tag = (props: TagProps) => {
	const { large, medium, pill, className, disabled, onClick, variant, children, icon, href } = props;
	const modifiers = [
		variant,
		medium && 'medium',
		large && 'large',
		pill && 'pill',
		disabled && 'disabled',
		onClick && 'clickable',
		href && 'clickable',
	]
		.filter(Boolean)
		.map((modifier) => `rcx-tag--${modifier}`)
		.join(' ');

	const clickable = Boolean(onClick || href);
	const kind = variant ?? 'default';
	// A disabled tag that isn't clickable looks the same whatever its kind
	const muted = disabled && !clickable;
	const state = clickable ? 'clickable' : 'rest';
	const tone = muted ? 'muted' : (`${kind}|${state}` as const);
	const fill = muted ? 'muted' : (`${kind}|${disabled && clickable ? 'clickable-disabled' : state}` as const);
	const action = (disabled && 'muted') || (clickable && 'clickable') || undefined;
	// `large` outranks `medium`, as it did in the stylesheet
	const scale = (large && 'large') || (medium && 'medium') || 'default';
	const classes = prependClassName(className, `rcx-box rcx-box--full rcx-tag ${modifiers}`);

	const content = (
		<>
			{icon}
			<TagLabel className='rcx-tag__inner'>{children}</TagLabel>
		</>
	);

	// One literal element per tag, as zero-runtime has to know the tag; what the consumer passes goes on that element
	if (href) {
		return (
			<TagFrame
				tone={tone}
				fill={fill}
				shape={pill ? 'pill' : 'regular'}
				action={action}
				scale={scale}
				className={classes}
				render={
					<a
						{...ariaAndDataAttributes(props)}
						{...pickWebPressHandlers(props)}
						href={href}
						target={props.target}
						rel={props.rel}
						ref={props.ref as AnchorRef}
						id={props.id}
						title={props.title}
						role={props.role}
						tabIndex={props.tabIndex}
					/>
				}
			>
				{content}
			</TagFrame>
		);
	}

	return (
		<TagFrame
			tone={tone}
			fill={fill}
			shape={pill ? 'pill' : 'regular'}
			action={action}
			scale={scale}
			className={classes}
			render={
				<span
					{...ariaAndDataAttributes(props)}
					{...pickWebPressHandlers(props)}
					ref={props.ref}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{content}
		</TagFrame>
	);
};

export default Tag;
