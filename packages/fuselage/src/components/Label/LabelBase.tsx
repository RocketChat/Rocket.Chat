import { styled, Text } from '@tamagui/web';
import type { ReactNode } from 'react';
import { createContext, useContext } from 'react';

import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { pickWebPressHandlers } from '../../helpers/pickAttributes';
import { prependClassName } from '../../helpers/prependClassName';
import type { ElementActionAttributes, LabelAttributes, LabelRef } from '../../types/ElementAttributes';

/** Whether a label is already above, which makes the next one a `span`. */
export const LabelContext = createContext(false);

export type LabelBaseProps = ElementActionAttributes &
	LabelAttributes & {
		/** Renders a `span` instead of the `label`. A label inside another label is always a `span`. */
		is?: 'label' | 'span';
		disabled?: boolean;
		required?: boolean;
		/** The label of a field, which aligns to the start of its column and keeps its own spacing. */
		field?: boolean;
		children?: ReactNode;
	};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const labelFrame = {
	flexBasis: 'auto',
	whiteSpace: 'inherit',
	wordWrap: 'inherit',
	render: 'label',
	display: 'flex',
	flexDirection: 'row',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	cursor: 'default',
	color: 'var(--rcx-color-font-default, #2f343d)',
	fontSize: '0.875rem',
	fontWeight: 500,
	lineHeight: '1.25rem',
	letterSpacing: '0rem',
} as const;

const labelDisabled = {
	pointerEvents: 'none',
	color: 'var(--rcx-color-font-secondary-info, #6c737a)',
} as const;

const labelInField = {
	alignSelf: 'flex-start',
	marginBlock: '2px',
	marginInlineEnd: '8px',
} as const;

const labelRequired = {
	flexBasis: 'auto',
	whiteSpace: 'inherit',
	wordWrap: 'inherit',
	render: 'span',
	display: 'inline',
	flexDirection: 'row',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	marginInlineStart: '4px',
	color: 'var(--rcx-color-font-danger, #d40c26)',
} as const;

// end of generated

// Declared where they render: zero-runtime only erases a `styled()` whose every use is in its own module
const LabelFrame = styled(Text, {
	...labelFrame,
	variants: {
		// not `disabled`: a frame's own `disabled` compiles to aria-disabled
		look: { enabled: {}, disabled: { ...labelDisabled } },
		field: { true: { ...labelInField }, false: {} },
	},
});

const LabelRequired = styled(Text, labelRequired);

/** The caption of an input, shared by `Label` and the label of a field. */
function LabelBase(props: LabelBaseProps) {
	const { disabled, is, required, field, children, className } = props;
	const isInsideLabel = useContext(LabelContext);
	const tag = is ?? (isInsideLabel ? 'span' : 'label');
	const classes = prependClassName(
		className,
		`rcx-box rcx-box--full rcx-label${disabled ? ' rcx-label--disabled' : ''}${field ? ' rcx-field__label' : ''}`,
	);

	// One literal element per tag, as zero-runtime has to know the tag; what the consumer passes goes on that element
	const content = (
		<>
			{children}
			{required && (
				<LabelRequired className='rcx-box rcx-box--full rcx-label__required' render={<span aria-hidden='true' />}>
					*
				</LabelRequired>
			)}
		</>
	);

	return (
		<LabelContext.Provider value={true}>
			{tag === 'span' ? (
				<LabelFrame
					look={disabled ? 'disabled' : 'enabled'}
					field={Boolean(field)}
					className={classes}
					render={
						<span
							{...ariaAndDataAttributes(props)}
							{...pickWebPressHandlers(props)}
							ref={props.ref}
							id={props.id}
							title={props.title}
							role={props.role}
							tabIndex={props.tabIndex}
						/>
					}
				>
					{content}
				</LabelFrame>
			) : (
				<LabelFrame
					look={disabled ? 'disabled' : 'enabled'}
					field={Boolean(field)}
					className={classes}
					render={
						<label
							{...ariaAndDataAttributes(props)}
							{...pickWebPressHandlers(props)}
							htmlFor={props.htmlFor}
							ref={props.ref as LabelRef}
							id={props.id}
							title={props.title}
							role={props.role}
							tabIndex={props.tabIndex}
						/>
					}
				>
					{content}
				</LabelFrame>
			)}
		</LabelContext.Provider>
	);
}

export default LabelBase;
