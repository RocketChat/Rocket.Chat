import { styled, Text } from '@tamagui/web';
import { createContext, useContext } from 'react';

import type { LabelContract } from './Label.contract';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { pickFramePressHandlers } from '../../helpers/pickFramePressHandlers';
import { pickWebInteractionHandlers } from '../../helpers/pickWebInteractionHandlers';
import { pickWebPressHandlers } from '../../helpers/pickWebPressHandlers';
import { prependClassName } from '../../helpers/prependClassName';
import type { WebLabelProps, WebLabelRef, WebLegendRef } from '../../types/WebElementAttributes';

/** Whether a label is already above, which makes the next one a `span`. */
export const LabelContext = createContext(false);

export type LabelBaseProps = WebLabelProps<LabelContract> & {
	/** The label of a field, which aligns to the start of its column and keeps its own spacing. */
	field?: boolean;
};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const labelFrame = {
	flexBasis: 'auto',
	whiteSpace: 'inherit',
	wordWrap: 'inherit',
	render: 'label',
	display: 'flex',
	flexDirection: 'row',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	cursor: 'default',
	color: '$rcx-font-default',
	fontSize: '0.875rem',
	lineHeight: '1.25rem',
	fontWeight: '500',
	letterSpacing: 0,
} as const;

const labelDisabled = {
	pointerEvents: 'none',
	color: '$rcx-font-secondary-info',
} as const;

const labelInField = {
	alignSelf: 'flex-start',
	marginBlock: 2,
	marginInlineEnd: '$space.x8',
} as const;

const labelRequired = {
	flexBasis: 'auto',
	whiteSpace: 'inherit',
	wordWrap: 'inherit',
	render: 'span',
	display: 'inline',
	flexDirection: 'row',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	marginInlineStart: '$space.x4',
	color: '$rcx-font-danger',
} as const;

// end of generated

const LabelFrame = styled(Text, {
	...labelFrame,
	variants: {
		// not `disabled`: a frame's own `disabled` compiles to aria-disabled
		look: { enabled: {}, disabled: { ...labelDisabled } },
		field: { true: { ...labelInField }, false: {} },
	},
});

const LabelRequired = styled(Text, { ...labelRequired });

/** The caption of an input, shared by `Label` and the label of a field. */
function LabelBase(props: LabelBaseProps) {
	const { disabled, is, required, field, children, className } = props;
	const isInsideLabel = useContext(LabelContext);
	const tag = is ?? (isInsideLabel ? 'span' : 'label');
	const classes = prependClassName(
		className,
		`rcx-box rcx-box--full${field ? ' rcx-field__label' : ''} rcx-label${disabled ? ' rcx-label--disabled' : ''}`,
	);

	const content = (
		<>
			{children}
			{required && (
				<LabelRequired className='rcx-box rcx-box--full rcx-label__required' render={<span aria-hidden='true' />}>
					*
				</LabelRequired>
			)}
		</>
	);

	// One literal element per tag: the zero-runtime compiler has to know the tag
	return (
		<LabelContext.Provider value={true}>
			{tag === 'legend' && (
				<LabelFrame
					look={disabled ? 'disabled' : 'enabled'}
					field={Boolean(field)}
					className={classes}
					{...pickFramePressHandlers(props)}
					render={
						<legend
							{...ariaAndDataAttributes(props)}
							{...pickWebInteractionHandlers(props)}
							{...pickWebPressHandlers(props)}
							ref={props.ref as WebLegendRef}
							id={props.id}
							title={props.title}
							role={props.role}
						/>
					}
				>
					{content}
				</LabelFrame>
			)}
			{tag === 'span' && (
				<LabelFrame
					look={disabled ? 'disabled' : 'enabled'}
					field={Boolean(field)}
					className={classes}
					{...pickFramePressHandlers(props)}
					render={
						<span
							{...ariaAndDataAttributes(props)}
							{...pickWebInteractionHandlers(props)}
							{...pickWebPressHandlers(props)}
							ref={props.ref}
							id={props.id}
							title={props.title}
							role={props.role}
						/>
					}
				>
					{content}
				</LabelFrame>
			)}
			{tag === 'label' && (
				<LabelFrame
					look={disabled ? 'disabled' : 'enabled'}
					field={Boolean(field)}
					className={classes}
					{...pickFramePressHandlers(props)}
					render={
						<label
							{...ariaAndDataAttributes(props)}
							{...pickWebInteractionHandlers(props)}
							{...pickWebPressHandlers(props)}
							htmlFor={props.htmlFor}
							ref={props.ref as WebLabelRef}
							id={props.id}
							title={props.title}
							role={props.role}
						/>
					}
				>
					{content}
				</LabelFrame>
			)}
		</LabelContext.Provider>
	);
}

export default LabelBase;
