const Divider = (props: DividerProps) => {
	const { variation, children, vertical, flush, small, stretch, className } = props;

	if (!children) {
		// Direction, size, flush and tone set overlapping properties, so each combination is one variant
		const look = `${vertical ? 'vertical' : 'horizontal'}${vertical && small ? '-small' : ''}${vertical && stretch ? '-stretch' : ''}${
			flush ? '-flush' : ''
		}:${variation ?? 'default'}`;
		// Listed in the order `Box` gave the `rcx-` props it used to take: each one went in front of the last
		const classes = [
			'rcx-box rcx-box--full',
			variation === 'light' && 'rcx-divider--light',
			variation === 'danger' && 'rcx-divider--danger',
			flush && 'rcx-divider--flush',
			vertical && stretch && 'rcx-divider--stretch',
			vertical && small && 'rcx-divider--small',
			vertical && 'rcx-divider--vertical',
			'rcx-divider',
			className,
		]
			.filter(Boolean)
			.join(' ');

		return (
			<DividerLine
				render={<hr {...ariaAndDataAttributes(props)} ref={props.ref as Ref<HTMLHRElement>} id={props.id} title={props.title} />}
				look={look}
				className={classes}
			/>
		);
	}

	// The labelled divider takes its look from the Message divider's stylesheet
	return (
		<div
			{...ariaAndDataAttributes(props)}
			role='separator'
			ref={props.ref as Ref<HTMLDivElement>}
			id={props.id}
			title={props.title}
			className={['rcx-box rcx-box--full rcx-divider--labelled rcx-message-divider', className].filter(Boolean).join(' ')}
		>
			<DividerBar className='rcx-divider__bar' />
			<DividerLabel className='rcx-divider__wrapper'>{children}</DividerLabel>
			<DividerBar className='rcx-divider__bar' />
		</div>
	);
};

export default Divider;
