const RuleFrame = styled(View, {
	...dividerRule,
	variants: {
		look: dividerLooks,
		spacing: dividerSpacings,
		stretch: dividerStretches,
	},
});

const LabelledFrame = styled(Text, { ...dividerLabelled });

const BarFrame = styled(View, { ...dividerBar });

const LabelFrame = styled(Text, { ...dividerLabel });

const Divider = (props: DividerProps) => {
	const { variation, children, vertical, flush, small, stretch, className } = props;

	if (!children) {
		// The order a `Box` emitted them in, which the A/B checks compare
		const modifiers = [
			variation === 'light' && 'light',
			variation === 'danger' && 'danger',
			flush && 'flush',
			vertical && stretch && 'stretch',
			vertical && small && 'small',
			vertical && 'vertical',
		]
			.filter(Boolean)
			.map((modifier) => `rcx-divider--${modifier} `)
			.join('');

		const verticalLook = variation ? (`vertical-${variation}` as const) : 'vertical';
		const height = stretch ? 'fill' : 'fixed';

		return (
			<RuleFrame
				look={vertical ? verticalLook : (variation ?? 'default')}
				spacing={(flush && 'flush') || (vertical && (small ? 'vertical-small' : 'vertical')) || 'rule'}
				stretch={vertical ? height : undefined}
				className={prependClassName(className, `rcx-box rcx-box--full ${modifiers}rcx-divider`)}
				render={<hr {...ariaAndDataAttributes(props)} ref={props.ref as HrRef} id={props.id} title={props.title} />}
			/>
		);
	}

	return (
		<LabelledFrame
			className={prependClassName(className, 'rcx-box rcx-box--full rcx-divider--labelled')}
			render={<div {...ariaAndDataAttributes(props)} ref={props.ref as DivRef} id={props.id} title={props.title} role='separator' />}
		>
			<BarFrame className='rcx-divider__bar' />
			<LabelFrame className='rcx-divider__wrapper'>{children}</LabelFrame>
			<BarFrame className='rcx-divider__bar' />
		</LabelledFrame>
	);
};

export default Divider;
