import { styled, View } from '@tamagui/web';
import type { ComponentType, MouseEventHandler, ReactNode } from 'react';
import { useId, useLayoutEffect, useMemo, useRef } from 'react';

import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { cx } from '../../helpers/composeClassNames';
import { customProperties, positionedCustomProperties } from '../../helpers/customProperties';
import { pickWebAnimationHandlers } from '../../helpers/pickAttributes';
import { prevent } from '../../helpers/prevent';
import type {
	DivAnimationHandlers,
	DivRef,
	ElementActionAttributes,
	HtmlElementOf,
	OlElement,
	PositionedAttributes,
} from '../../types/ElementAttributes';
import { ItemDivider } from '../Item';
import { Option, OptionHeader } from '../Option';
import { PopoverSurface } from '../PopoverSurface';
import type { OptionType } from './OptionType';
import OptionsEmpty from './OptionsEmpty';
import { toCSSSize, type OptionsSize } from './optionsSize';

export type OptionsProps<TValue extends string | number = string | number, TLabel = ReactNode> = Pick<
	ElementActionAttributes,
	'id' | 'className' | 'title' | 'ref' | 'role' | 'aria-label' | 'aria-labelledby'
> &
	DivAnimationHandlers &
	PositionedAttributes & {
		/** A number is a height in pixels; a string is any CSS size. */
		maxHeight?: OptionsSize;
		/** A number is a width in pixels; a string is any CSS size. */
		width?: OptionsSize;
		multiple?: boolean;
		options: OptionType<TValue, TLabel>[];
		cursor: number;
		renderItem?: ComponentType<{
			id?: string;
			role?: string;
			label: TLabel;
			value: TValue;
			selected?: boolean;
			focus?: boolean;
			disabled?: boolean;
			onMouseDown: MouseEventHandler;
		}>;
		renderEmpty?: ComponentType<{
			customEmpty?: string;
		}>;
		onSelect: (option: OptionType<TValue, TLabel>) => void;
		customEmpty?: string;
	};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const optionsFrame = {
	display: 'block',
	flexDirection: 'row',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	render: 'div',
	width: 'var(--rcx-options-width, auto)',
} as const;

const optionsListFrame = {
	display: 'block',
	flexDirection: 'row',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	render: 'ol',
	position: 'relative',
	overflowY: 'auto',
	maxHeight: 'var(--rcx-options-max-height, 144px)',
	borderRadius: '0.25rem',
	backgroundColor: 'var(--rcx-color-surface-light, #ffffff)',
	scrollBehavior: 'smooth',
} as const;

// end of generated

// Declared where they render: zero-runtime only erases a `styled()` whose every use is in its own module
const OptionsFrame = styled(View, { ...optionsFrame, group: 'options' });

const OptionsListFrame = styled(View, { ...optionsListFrame });

/**
 * An input for selection of options.
 */
function Options<TValue extends string | number = string | number, TLabel = ReactNode>(props: OptionsProps<TValue, TLabel>) {
	const {
		maxHeight,
		width,
		multiple,
		renderEmpty: EmptyComponent = OptionsEmpty,
		options,
		cursor,
		renderItem: OptionComponent = Option,
	} = props;
	const { onSelect, customEmpty, id } = props;
	const liRef = useRef<OlElement>(null);
	const optionIdPrefix = useId();

	useLayoutEffect(() => {
		if (!liRef.current) {
			return;
		}
		const { current } = liRef;
		const li = current.querySelector<HtmlElementOf>(`[id="${optionIdPrefix}-${cursor}"]`);
		if (!li) {
			return;
		}
		if (li.offsetTop + li.clientHeight > current.scrollTop + current.clientHeight || li.offsetTop - li.clientHeight < current.scrollTop) {
			current.scrollTop = li.offsetTop;
		}
	}, [cursor, optionIdPrefix]);

	const activeType = options[cursor]?.[4];
	const activeDescendant =
		options[cursor] && activeType !== 'heading' && activeType !== 'divider' ? `${optionIdPrefix}-${cursor}` : undefined;

	const optionsMemoized = useMemo(
		() =>
			options.map(([value, label, selected, disabled, type, url], i) => {
				switch (type) {
					case 'heading':
						return <OptionHeader key={value}>{label}</OptionHeader>;
					case 'divider':
						return <ItemDivider key={value} is='li' aria-hidden />;
					default:
						return (
							<OptionComponent
								id={`${optionIdPrefix}-${i}`}
								role='option'
								label={label}
								onMouseDown={(e) => {
									if (disabled) return;

									prevent(e);
									onSelect([value, label, selected, disabled, type, url]);
								}}
								key={value}
								value={value}
								selected={!!selected}
								disabled={disabled}
								focus={cursor === i}
							/>
						);
				}
			}),
		[options, cursor, onSelect, OptionComponent, optionIdPrefix],
	);

	return (
		<OptionsFrame
			className={cx('rcx-box rcx-box--full rcx-options', props.className)}
			render={
				<div
					{...ariaAndDataAttributes(props)}
					{...pickWebAnimationHandlers(props)}
					{...positionedCustomProperties(props, { '--rcx-options-width': width === undefined ? undefined : toCSSSize(width) })}
					ref={props.ref as DivRef}
					title={props.title}
					role={props.role}
				/>
			}
		>
			<PopoverSurface>
				<OptionsListFrame
					className='rcx-box rcx-box--full rcx-options__list'
					render={
						<ol
							aria-multiselectable={!!multiple}
							{...customProperties({ '--rcx-options-max-height': maxHeight === undefined ? undefined : toCSSSize(maxHeight) })}
							ref={liRef}
							onMouseDown={prevent}
							onClick={prevent}
							role='listbox'
							id={id}
							aria-activedescendant={activeDescendant}
						/>
					}
				>
					{!options.length && <EmptyComponent customEmpty={customEmpty} />}
					{optionsMemoized}
				</OptionsListFrame>
			</PopoverSurface>
		</OptionsFrame>
	);
}

export default Options;
