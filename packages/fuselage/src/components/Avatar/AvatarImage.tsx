import { styled, View } from '@tamagui/web';
import { useContext } from 'react';

import type { AvatarContract } from './Avatar.contract';
import { AvatarStackContext } from './AvatarStackContext';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { cx } from '../../helpers/composeClassNames';
import { pickWebInteractionHandlers } from '../../helpers/pickWebInteractionHandlers';
import { pickWebPressHandlers } from '../../helpers/pickWebPressHandlers';
import type { WebImageProps } from '../../types/WebTriggerProps';

// The container takes the `className`, so the image has none of its own
export type AvatarImageProps = Omit<WebImageProps<AvatarContract>, 'className'>;

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const avatarImageFrame = {
	flexDirection: 'row',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	display: 'block',
	position: 'relative',
	width: '100%',
	height: '100%',
} as const;

const avatarImageShape = {
	small: {
		borderRadius: '$radius.small',
	},
	medium: {
		borderRadius: '$radius.medium',
	},
	large: {
		borderRadius: '$radius.large',
	},
	rounded: {
		borderRadius: '$radius.full',
	},
} as const;

const avatarImageObjectFit = {
	'contain': {
		objectFit: 'contain',
	},
	'cover': {
		objectFit: 'cover',
	},
	'fill': {
		objectFit: 'fill',
	},
	'none': {
		objectFit: 'none',
	},
	'scale-down': {
		objectFit: 'scale-down',
	},
} as const;

const avatarImageRing = {
	true: {
		borderWidth: 1,
		borderStyle: 'solid',
		borderColor: 'transparent',
	},
	false: {},
} as const;

const avatarImageInteractive = {
	true: {
		cursor: 'pointer',
	},
	false: {},
} as const;

// end of generated

const AvatarImageFrame = styled(View, {
	render: 'img',
	...avatarImageFrame,
	variants: {
		shape: avatarImageShape,
		objectFit: avatarImageObjectFit,
		ring: avatarImageRing,
		interactive: avatarImageInteractive,
	},
});

const shapeOf = (size: NonNullable<AvatarContract['size']>) => {
	if (size === 'x16' || size === 'x18') {
		return 'small';
	}
	return size === 'x332' ? 'large' : 'medium';
};

/** The image of an `Avatar`: an `img` on the web, an `Image` on React Native. */
const AvatarImage = (props: AvatarImageProps) => {
	const { size = 'x36', rounded = false, objectFit, url, alt } = props;
	const stacked = useContext(AvatarStackContext);

	return (
		<AvatarImageFrame
			shape={rounded ? 'rounded' : shapeOf(size)}
			objectFit={objectFit}
			ring={stacked}
			interactive={Boolean(props.onPress || props.onClick)}
			className={cx(
				'rcx-avatar__element',
				`rcx-avatar__element--${size}`,
				rounded && 'rcx-avatar__element--rounded',
				objectFit && `rcx-avatar__element--object-fit-${objectFit}`,
			)}
			render={
				<img
					{...ariaAndDataAttributes(props)}
					{...pickWebPressHandlers(props)}
					{...pickWebInteractionHandlers(props)}
					src={url}
					alt={alt || ''}
					title={props.title}
					onLoad={props.onLoad}
					onError={props.onError}
					ref={props.ref}
					id={props.id}
					role={props.role}
				/>
			}
		/>
	);
};

export default AvatarImage;
