import { styled, Text } from '@tamagui/web';
import type { AriaRole, ReactNode } from 'react';

import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { pickPositionStyle, pickWebAnimationHandlers } from '../../helpers/pickAttributes';
import { prependClassName } from '../../helpers/prependClassName';
import type { DivAnimationHandlers, DivAttributes, DivPressHandlers, PositionedAttributes } from '../../types/ElementAttributes';

export type TooltipProps = DivAttributes &
	PositionedAttributes &
	DivAnimationHandlers &
	Pick<DivPressHandlers, 'onMouseEnter' | 'onMouseLeave'> & {
		children?: ReactNode;
		role?: AriaRole;
		variation?: 'dark' | 'light';
	};

const parsePlacement = (placement: string | null | undefined) => {
	const [direction, position] = placement ? placement.split('-') : [undefined, undefined];

	if (direction === 'right' || direction === 'left') {
		return [direction, undefined];
	}

	return [direction, position];
};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const tooltipFrame = {
	alignItems: 'stretch',
	flexDirection: 'column',
	flexBasis: 'auto',
	minWidth: 0,
	minHeight: 0,
	whiteSpace: 'inherit',
	wordWrap: 'inherit',
	render: 'div',
	position: 'relative',
	display: 'inline-block',
	flexShrink: 1,
	maxWidth: '240px',
	paddingBlock: '8px',
	paddingInline: '12px',
	userSelect: 'none',
	wordBreak: 'break-word',
	pointerEvents: 'none',
	borderRadius: 'var(--rcx-tooltip-border-radius, var(--rcx-border-radius-medium, 0.25rem))',
	fontSize: '0.875rem',
	fontWeight: 500,
	lineHeight: '1.25rem',
	letterSpacing: '0rem',
} as const;

const tooltipLooks = {
	dark: {
		color: 'var(--rcx-tooltip-dark-text-color, var(--rcx-color-font-white, #ffffff))',
		backgroundColor: 'var(--rcx-tooltip-dark-background-color, var(--rcx-color-surface-dark, #1f2329))',
	},
	light: {
		color: 'var(--rcx-tooltip-light-text-color, var(--rcx-color-font-default, #2f343d))',
		backgroundColor: 'var(--rcx-tooltip-light-background-color, var(--rcx-color-surface-neutral, #e4e7ea))',
	},
} as const;

// end of generated

const TooltipFrame = styled(Text, {
	...tooltipFrame,
	variants: {
		look: tooltipLooks,
	},
});

function Tooltip(props: TooltipProps) {
	const { variation = 'dark', placement, className, children } = props;
	const [direction, position] = parsePlacement(placement);

	const placed = [direction && `rcx-tooltip--dir-${direction}`, position && `rcx-tooltip--pos-${position}`].filter(Boolean).join(' ');

	return (
		<TooltipFrame
			look={variation}
			className={prependClassName(className, `rcx-box rcx-box--full rcx-tooltip rcx-tooltip--${variation}${placed && ` ${placed}`}`)}
			render={
				<div
					{...ariaAndDataAttributes(props)}
					{...pickPositionStyle(props)}
					{...pickWebAnimationHandlers(props)}
					ref={props.ref}
					id={props.id}
					title={props.title}
					role={props.role}
					onMouseEnter={props.onMouseEnter}
					onMouseLeave={props.onMouseLeave}
				/>
			}
		>
			{children}
		</TooltipFrame>
	);
}

export default Tooltip;
