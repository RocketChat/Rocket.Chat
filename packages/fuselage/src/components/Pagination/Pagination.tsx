const defaultItemsPerPageLabel = () => 'Items per page:';

const defaultShowingResultsLabel = ({ count, current, itemsPerPage }: { count: number; current: number; itemsPerPage: ItemsPerPage }) =>
	`Showing results ${current + 1} - ${Math.min(current + itemsPerPage, count)} of ${count}`;

const itemsPerPageOptions = [25, 50, 100] as const;

const Pagination = ({
	count,
	current = 0,
	itemsPerPage = 25,
	itemsPerPageLabel = defaultItemsPerPageLabel,
	showingResultsLabel = defaultShowingResultsLabel,
	onSetItemsPerPage,
	onSetCurrent,
	divider,
	...props
}: PaginationProps) => {
	const paginationResultLabelId = useId();
	const itemsPerPageLabelId = useId();

	const hasItemsPerPageSelection = itemsPerPageOptions.length > 1;
	const currentPage = Math.floor(current / itemsPerPage);
	const pages = Math.ceil(count / itemsPerPage);
	const displayedPages = useMemo(() => {
		if (pages <= 7) {
			// 0 1 2 3 4 5 6
			return Array.from({ length: pages }, (_, i) => i);
		}

		if (currentPage < 5) {
			// 0 1 2 3 4 ... N
			return [0, 1, 2, 3, 4, '⋯', pages - 1];
		}

		if (currentPage > pages - 5) {
			// 0 ... N-4 N-3 N-2 N-1 N
			return [0, '⋯', pages - 5, pages - 4, pages - 3, pages - 2, pages - 1];
		}

		// 0 ... x-1 x x-2 ... N
		return [0, '⋯', currentPage - 1, currentPage, currentPage + 1, '⋯', pages - 1];
	}, [pages, currentPage]);

	const renderingContext = { count, pages, current, currentPage, itemsPerPage };

	const handleSetItemsPerPageLinkClick = (itemsPerPageOption: ItemsPerPage) => () => {
		onSetItemsPerPage?.(itemsPerPageOption);
	};

	const handleSetPageLinkClick = (page: number) => () => {
		onSetCurrent?.(page * itemsPerPage);
	};

	return (
		<PaginationFrame
			divider={divider ? 'with' : 'without'}
			className={prependClassName(props.className, `rcx-box rcx-box--full rcx-pagination${divider ? ' rcx-pagination--divider' : ''}`)}
			render={
				<nav
					{...ariaAndDataAttributes(props)}
					{...pickWebPressHandlers(props)}
					aria-label={props['aria-label'] ?? 'Pagination Navigation'}
					ref={props.ref}
					id={props.id}
					title={props.title}
				/>
			}
		>
			{hasItemsPerPageSelection && (
				<PaginationLeft className='rcx-pagination__left'>
					<PaginationLabel className='rcx-pagination__label' render={<span id={itemsPerPageLabelId} />}>
						{itemsPerPageLabel(renderingContext)}
					</PaginationLabel>
					<PaginationList className='rcx-box rcx-box--full rcx-pagination__list' render={<ol aria-labelledby={itemsPerPageLabelId} />}>
						{itemsPerPageOptions.map((itemsPerPageOption) => (
							<PaginationItem key={itemsPerPageOption} className='rcx-pagination__list-item'>
								<PaginationLink
									kind={itemsPerPage === itemsPerPageOption ? 'current' : 'page'}
									className='rcx-box rcx-box--full rcx-pagination__link'
									render={
										<button
											tabIndex={itemsPerPage === itemsPerPageOption ? -1 : 0}
											disabled={itemsPerPage === itemsPerPageOption}
											aria-label={`Show ${itemsPerPageOption} items per page`}
											onClick={handleSetItemsPerPageLinkClick(itemsPerPageOption)}
										/>
									}
								>
									{itemsPerPageOption}
								</PaginationLink>
							</PaginationItem>
						))}
					</PaginationList>
				</PaginationLeft>
			)}
			<PaginationRight className='rcx-pagination__right'>
				<PaginationLabel className='rcx-pagination__label' render={<span id={paginationResultLabelId} />}>
					{showingResultsLabel(renderingContext)}
				</PaginationLabel>
				<PaginationList className='rcx-box rcx-box--full rcx-pagination__list' render={<ol aria-labelledby={paginationResultLabelId} />}>
					<PaginationItem className='rcx-pagination__list-item'>
						<PaginationStep
							kind={currentPage === 0 ? 'disabled' : 'enabled'}
							className='rcx-box rcx-box--full rcx-pagination__back'
							render={<button disabled={currentPage === 0} aria-label='Previous page' onClick={handleSetPageLinkClick(currentPage - 1)} />}
						>
							<Chevron left size='x16' />
						</PaginationStep>
					</PaginationItem>
					{displayedPages.map((page, i) => (
						<PaginationItem key={i} className='rcx-pagination__list-item'>
							{page === '⋯' ? (
								'⋯'
							) : (
								<PaginationLink
									kind={currentPage === page ? 'current' : 'page'}
									className='rcx-box rcx-box--full rcx-pagination__link'
									render={
										<button
											disabled={currentPage === page}
											aria-label={`Page ${Number(page) + 1}`}
											onClick={handleSetPageLinkClick(Number(page))}
										/>
									}
								>
									{Number(page) + 1}
								</PaginationLink>
							)}
						</PaginationItem>
					))}
					<PaginationItem className='rcx-pagination__list-item'>
						<PaginationStep
							kind={currentPage === pages - 1 ? 'disabled' : 'enabled'}
							className='rcx-box rcx-box--full rcx-pagination__forward'
							render={
								<button disabled={currentPage === pages - 1} aria-label='Next page' onClick={handleSetPageLinkClick(currentPage + 1)} />
							}
						>
							<Chevron right size='x16' />
						</PaginationStep>
					</PaginationItem>
				</PaginationList>
			</PaginationRight>
		</PaginationFrame>
	);
};

export default Pagination;
