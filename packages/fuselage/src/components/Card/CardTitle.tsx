/* oxlint-disable jsx-a11y/heading-has-content -- the children are the consumer's title */
import { styled, Text } from '@tamagui/web';
import type { ReactNode } from 'react';

import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { pickWebPressHandlers } from '../../helpers/pickAttributes';
import { prependClassName } from '../../helpers/prependClassName';
import type { HeadingAttributes } from '../../types/ElementAttributes';
import { LabelInfo } from '../Label/LabelInfo';

export type CardTitleProps = HeadingAttributes & {
	children: ReactNode;
	info?: string;
	variant?: 'h3' | 'h4' | 'h5';
};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const cardTitleFrame = {
	flexBasis: 'auto',
	whiteSpace: 'inherit',
	wordWrap: 'inherit',
	render: 'h4',
	display: 'flex',
	flexDirection: 'row',
	alignItems: 'center',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	rowGap: '8px',
	columnGap: '8px',
} as const;

const cardTitleVariants = {
	h3: {
		fontSize: '1.25rem',
		fontWeight: 700,
		lineHeight: '1.75rem',
		letterSpacing: '0rem',
	},
	h4: {
		fontSize: '1rem',
		fontWeight: 700,
		lineHeight: '1.5rem',
		letterSpacing: '0rem',
	},
	h5: {
		fontSize: '0.875rem',
		fontWeight: 700,
		lineHeight: '1.25rem',
		letterSpacing: '0rem',
	},
} as const;

// end of generated

// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const CardTitleFrame = styled(Text, {
	...cardTitleFrame,
	variants: {
		scale: cardTitleVariants,
	},
});

const CardTitle = (props: CardTitleProps) => {
	const { children, info, variant = 'h4' } = props;
	const className = prependClassName(props.className, 'rcx-box rcx-box--full rcx-card__title');
	const content = (
		<>
			{children}
			{info && <LabelInfo title={info} />}
		</>
	);

	// One literal element per tag, as zero-runtime has to know the tag
	if (variant === 'h3') {
		return (
			<CardTitleFrame
				scale='h3'
				className={className}
				render={<h3 {...ariaAndDataAttributes(props)} {...pickWebPressHandlers(props)} ref={props.ref} id={props.id} title={props.title} />}
			>
				{content}
			</CardTitleFrame>
		);
	}

	if (variant === 'h5') {
		return (
			<CardTitleFrame
				scale='h5'
				className={className}
				render={<h5 {...ariaAndDataAttributes(props)} {...pickWebPressHandlers(props)} ref={props.ref} id={props.id} title={props.title} />}
			>
				{content}
			</CardTitleFrame>
		);
	}

	return (
		<CardTitleFrame
			scale='h4'
			className={className}
			render={<h4 {...ariaAndDataAttributes(props)} {...pickWebPressHandlers(props)} ref={props.ref} id={props.id} title={props.title} />}
		>
			{content}
		</CardTitleFrame>
	);
};

export default CardTitle;
