const TableCellPlaceholder = styled(View, tableCellPlaceholderFrame);

const TableCell = (props: TableCellProps) => {
	const { align, clickable, rowHeader, truncate, color, strong, children } = props;
	const headerKind = useContext(TableHeadContext);

	const innerElement =
		children ??
		(!headerKind ? <TableCellPlaceholder className='rcx-box rcx-box--full rcx-table__cell-placeholder' render={<hr />} /> : undefined);

	const scale = (strong || rowHeader) && 'strong';
	const className = prependClassName(
		props.className,
		`rcx-box rcx-box--full rcx-table__cell${align ? ` rcx-table__cell--align-${align}` : ''}${headerKind ? ' rcx-table__cell--header' : ''}${
			rowHeader ? ' rcx-table__cell--row-header' : ''
		}${clickable ? ' rcx-table__cell--clickable' : ''}${truncate ? ' rcx-table__cell--truncate' : ''}${color ? ` rcx-table__cell--color-${color}` : ''}${
			strong ? ' rcx-table__cell--strong' : ''
		}`,
	);
	const stickyHeader = headerKind === 'sticky';

	if ((props.is ?? (headerKind || rowHeader ? 'th' : 'td')) === 'th') {
		return (
			<TableCellFrame
				scale={scale || (headerKind ? 'caption' : 'body')}
				tone={color ?? (rowHeader ? 'hint' : 'secondary')}
				header={headerKind || 'none'}
				surface={stickyHeader || rowHeader ? 'light' : 'none'}
				breaking={!!rowHeader}
				clickable={!!clickable}
				truncate={!!truncate}
				align={align}
				className={className}
				render={
					<th
						{...ariaAndDataAttributes(props)}
						{...pickWebPressHandlers(props)}
						scope={props.scope ?? (rowHeader ? 'row' : undefined)}
						colSpan={props.colSpan}
						rowSpan={props.rowSpan}
						headers={props.headers}
						ref={props.ref}
						id={props.id}
						title={props.title}
						role={props.role}
						tabIndex={props.tabIndex}
					/>
				}
			>
				{innerElement}
			</TableCellFrame>
		);
	}

	return (
		<TableCellFrame
			scale={scale || (headerKind ? 'caption' : 'body')}
			tone={color ?? (rowHeader ? 'hint' : 'secondary')}
			header={headerKind || 'none'}
			surface={stickyHeader || rowHeader ? 'light' : 'none'}
			breaking={!!rowHeader}
			clickable={!!clickable}
			truncate={!!truncate}
			align={align}
			className={className}
			render={
				<td
					{...ariaAndDataAttributes(props)}
					{...pickWebPressHandlers(props)}
					scope={props.scope ?? (rowHeader ? 'row' : undefined)}
					colSpan={props.colSpan}
					rowSpan={props.rowSpan}
					headers={props.headers}
					ref={props.ref}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{innerElement}
		</TableCellFrame>
	);
};

