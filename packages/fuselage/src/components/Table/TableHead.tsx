import { styled, View } from '@tamagui/web';
import { createContext, useContext } from 'react';
import type { ReactNode } from 'react';

import { TableStickyContext } from './TableContext';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { pickWebPressHandlers } from '../../helpers/pickAttributes';
import { prependClassName } from '../../helpers/prependClassName';
import type { TableSectionAttributes } from '../../types/ElementAttributes';

/** What a cell learns from the section that holds it: `false` outside a head, and whether the head sticks inside one. */
export const TableHeadContext = createContext<false | 'static' | 'sticky'>(false);

export type TableHeadProps = TableSectionAttributes & { children?: ReactNode };

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const tableHeadFrame = {
	render: 'thead',
	display: 'table-header-group',
	flexDirection: 'row',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
} as const;

// end of generated

// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const TableHeadFrame = styled(View, tableHeadFrame);

const TableHead = (props: TableHeadProps) => {
	const sticky = useContext(TableStickyContext);

	return (
		<TableHeadContext.Provider value={sticky ? 'sticky' : 'static'}>
			<TableHeadFrame
				className={prependClassName(props.className, 'rcx-box rcx-box--full rcx-table__head')}
				render={
					<thead
						{...ariaAndDataAttributes(props)}
						{...pickWebPressHandlers(props)}
						ref={props.ref}
						id={props.id}
						title={props.title}
						role={props.role}
						tabIndex={props.tabIndex}
					/>
				}
			>
				{props.children}
			</TableHeadFrame>
		</TableHeadContext.Provider>
	);
};

export default TableHead;
