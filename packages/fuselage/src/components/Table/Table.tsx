const isSizeToken = (width: TableColumnWidth): width is keyof typeof tableColumnSizes =>
	typeof width === 'string' && Object.hasOwn(tableColumnSizes, width);

// A `col` takes any other width as an attribute: the frame cannot state a length that is only known when it renders
const columnWidthAttribute = (width: TableColumnWidth) => {
	if (width === 'auto' || isSizeToken(width)) {
		return undefined;
	}
	if (typeof width === 'string' && width.endsWith('%')) {
		return width;
	}
	return typeof width === 'number' ? width : parseFloat(width.replace(/^x/, ''));
};

