import { styled, View } from '@tamagui/web';
import type { ReactNode } from 'react';

import { TableStickyContext } from './TableContext';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { customProperties } from '../../helpers/customProperties';
import { pickWebPressHandlers } from '../../helpers/pickAttributes';
import { prependClassName } from '../../helpers/prependClassName';
import { size } from '../../styleTokens';
import type { TableElementAttributes } from '../../types/ElementAttributes';

/** A column width: a Fuselage size (`x40`), a length in pixels or a share of the table's width. */
export type TableColumnWidth = `x${number}` | `${number}px` | `${number}%` | number | 'auto';

export type TableProps = TableElementAttributes & {
	children?: ReactNode;
	striped?: boolean;
	sticky?: boolean;
	fixed?: boolean;
	/** The width of each column, in order. In a `fixed` table they take precedence over the cells' widths. */
	columns?: TableColumnWidth[];
};

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const tableWrapperFrame = {
	render: 'div',
	display: 'block',
	flexDirection: 'row',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	position: 'relative',
} as const;

const tableFrame = {
	render: 'table',
	display: 'table',
	flexDirection: 'row',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	width: '100%',
	borderCollapse: 'collapse',
	borderSpacing: '0 2px',
} as const;

const tableLayouts = {
	auto: {
		tableLayout: 'auto',
	},
	fixed: {
		tableLayout: 'fixed',
	},
} as const;

const tableColumnFrame = {
	render: 'col',
	display: 'table-column',
	flexDirection: 'row',
	alignItems: 'normal',
	flexShrink: 1,
	minWidth: 'auto',
	minHeight: 'auto',
	width: 'var(--rcx-table-col-width, auto)',
} as const;

// end of generated

// Declared where it renders: zero-runtime only erases a `styled()` whose every use is in its own module
const TableWrapper = styled(View, tableWrapperFrame);

const TableFrame = styled(View, {
	...tableFrame,
	variants: {
		layout: tableLayouts,
	},
});

const TableColumn = styled(View, tableColumnFrame);

const Table = (props: TableProps) => {
	const { striped, sticky, fixed = false, columns, children } = props;

	return (
		<TableStickyContext.Provider value={!!sticky}>
			<TableWrapper className='rcx-box rcx-box--full rcx-table__wrapper'>
				<TableFrame
					layout={fixed ? 'fixed' : 'auto'}
					className={prependClassName(
						props.className,
						`rcx-box rcx-box--full rcx-table${fixed ? ' rcx-table--fixed' : ''}${sticky ? ' rcx-table--sticky' : ''}${striped ? ' rcx-table--striped' : ''}`,
					)}
					render={
						<table
							{...ariaAndDataAttributes(props)}
							{...pickWebPressHandlers(props)}
							ref={props.ref}
							id={props.id}
							title={props.title}
							role={props.role}
							tabIndex={props.tabIndex}
						/>
					}
				>
					{columns && (
						<colgroup>
							{columns.map((width, index) => (
								<TableColumn
									key={index}
									className='rcx-box rcx-box--full'
									render={<col {...customProperties({ '--rcx-table-col-width': size(width) })} />}
								/>
							))}
						</colgroup>
					)}
					{children}
				</TableFrame>
			</TableWrapper>
		</TableStickyContext.Provider>
	);
};

export default Table;
