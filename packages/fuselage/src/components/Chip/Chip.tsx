import { styled, Text, View } from '@tamagui/web';

import type { ChipContract } from './Chip.contract';
import { ariaAndDataAttributes } from '../../helpers/ariaAndDataAttributes';
import { pickWebInteractionHandlers } from '../../helpers/pickWebInteractionHandlers';
import { pickWebPressHandlers } from '../../helpers/pickWebPressHandlers';
import { prependClassName } from '../../helpers/prependClassName';
import type { WebButtonProps } from '../../types/WebAttributes';
import { Avatar } from '../Avatar';
import { BoxTransforms } from '../Box/BoxTransforms';
import { Icon } from '../Icon';

export type ChipProps = WebButtonProps<ChipContract>;

// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit

const chipFrame = {
	boxSizing: 'border-box',
	display: 'flex',
	flexDirection: 'row',
	flexShrink: 1,
	alignItems: 'center',
	minWidth: 'auto',
	overflow: 'hidden',
	padding: '$space.x4',
	gap: '$space.x8',
	outlineStyle: 'none',
	borderWidth: 0,
	borderStyle: 'solid',
	borderRadius: '$radius.medium',
	fontVariantNumeric: 'tabular-nums',
} as const;
const chipEnabled = {
	cursor: 'pointer',
	color: '$rcx-font-secondary-info',
	backgroundColor: {
		'default': '$rcx-button-background-secondary-default',
		'focus-visible': '$rcx-button-background-secondary-focus',
		'hover': '$rcx-button-background-secondary-hover',
		'press': '$rcx-button-background-secondary-press',
	},
	boxShadow: {
		'focus-visible': '0 0 0 2px $rcx-stroke-extra-light-highlight',
		'hover': 'none',
		'press': 'none',
	},
} as const;
const chipDisabled = {
	cursor: 'not-allowed',
	color: '$rcx-button-font-on-secondary',
	backgroundColor: '$rcx-button-background-secondary-default',
} as const;
const chipRegular = {
	height: '$size.x28',
	minHeight: '$size.x28',
} as const;
const chipSmall = {
	height: '$size.x20',
	minHeight: '$size.x20',
} as const;
const chipText = {
	boxSizing: 'border-box',
	flexShrink: 1,
	overflow: 'hidden',
	whiteSpace: 'nowrap',
	wordWrap: 'normal',
	textOverflow: 'ellipsis',
	fontFamily: 'inherit',
	fontSize: '0.875rem',
	lineHeight: '1.25rem',
	fontWeight: '400',
	letterSpacing: 0,
	fontVariantNumeric: 'tabular-nums',
	outlineStyle: 'none',
} as const;
const chipTextLooks = {
	enabled: {
		color: '$rcx-font-secondary-info',
	},
	disabled: {
		color: '$rcx-button-font-on-secondary',
	},
} as const;

// end of generated

const ChipFrame = styled(View, {
	render: 'button',
	...chipFrame,
	variants: {
		// the disabled colors win over every state
		look: {
			enabled: { ...chipEnabled },
			disabled: { ...chipDisabled },
		},
		sizing: {
			regular: { ...chipRegular },
			small: { ...chipSmall },
		},
		label: {
			true: { textTransform: 'uppercase' },
			false: {},
		},
	},
});

const ChipText = styled(Text, {
	render: 'span',
	...chipText,
	variants: { look: chipTextLooks },
});

const defaultRenderThumb = ({ url }: { url: string }) => (
	<div className='rcx-box rcx-box--full rcx-avatar'>
		<Avatar size='x20' url={url} />
	</div>
);
const defaultRenderDismissSymbol = () => <Icon name='cross' size='x16' />;

const Chip = (props: ChipProps) => {
	const {
		children,
		className,
		thumbUrl,
		onPress,
		onClick,
		onMouseDown,
		renderThumb = defaultRenderThumb,
		renderDismissSymbol = defaultRenderDismissSymbol,
		small,
		label,
		disabled,
	} = props;
	const dismissable = Boolean(onPress || onClick || onMouseDown);
	const isDisabled = disabled ?? !dismissable;

	return (
		<ChipFrame
			look={isDisabled ? 'disabled' : 'enabled'}
			sizing={small ? 'small' : 'regular'}
			label={Boolean(label)}
			className={prependClassName(className, `rcx-box rcx-chip${small ? ' rcx-chip--small' : ''}${label ? ' rcx-chip--label' : ''}`)}
			render={
				<button
					{...ariaAndDataAttributes(props)}
					{...pickWebInteractionHandlers(props)}
					{...pickWebPressHandlers(props)}
					type='button'
					disabled={isDisabled}
					name={props.name}
					value={props.value}
					ref={props.ref}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{/* The chip is not a Box, so without this the margins of a Margins above it would land on the first Box inside it */}
			<BoxTransforms.Provider value={null}>
				{thumbUrl && renderThumb?.({ url: thumbUrl })}
				{children && (
					<ChipText look={isDisabled ? 'disabled' : 'enabled'} className='rcx-box rcx-chip__text'>
						{children}
					</ChipText>
				)}
				{dismissable && renderDismissSymbol?.()}
			</BoxTransforms.Provider>
		</ChipFrame>
	);
};

export default Chip;
