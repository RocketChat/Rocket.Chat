const defaultRenderThumb = ({ url }: { url: string }) => (
	<Box rcx-avatar>
		<Avatar size='x20' url={url} />
	</Box>
);
const defaultRenderDismissSymbol = () => <Icon name='cross' size='x16' />;

const Chip = ({
	children,
	className,
	thumbUrl,
	onClick,
	onMouseDown,
	renderThumb = defaultRenderThumb,
	renderDismissSymbol = defaultRenderDismissSymbol,
	small,
	label,
	disabled,
	...rest
}: ChipProps) => {
	const onDismiss = onClick || onMouseDown;
	const isDisabled = disabled ?? !onDismiss;

	// The caller's attributes go on the element `render` names: zero-runtime rejects spreads on a frame
	const attributes = { type: 'button' as const, disabled: isDisabled, onClick: onDismiss, ...rest };

	return (
		<ChipFrame
			render={<button {...attributes} />}
			look={isDisabled ? 'disabled' : 'enabled'}
			sizing={small ? 'small' : 'regular'}
			label={Boolean(label)}
			className={prependClassName(className, `rcx-box rcx-chip${small ? ' rcx-chip--small' : ''}${label ? ' rcx-chip--label' : ''}`)}
		>
			<Margins all='x4'>
				{thumbUrl && renderThumb?.({ url: thumbUrl })}
				{children && <span className='rcx-box rcx-chip__text'>{children}</span>}
				{onDismiss && renderDismissSymbol?.()}
			</Margins>
		</ChipFrame>
	);
};

export default withBoxStyling(Chip);
