import { Avatar } from '../Avatar';
import { Icon } from '../Icon';

export type ChipProps = ActionAttributes<HTMLButtonElement> &
	Pick<ButtonHTMLAttributes<HTMLButtonElement>, 'name' | 'value' | 'disabled'> & {
		children?: ReactNode;
		thumbUrl?: string;
		renderThumb?: (props: { url: string }) => ReactNode;
		renderDismissSymbol?: () => ReactNode;
		/** Renders a 20px tall chip. */
		small?: boolean;
		/** Renders the text in uppercase, for chips that categorize rather than select. */
		label?: boolean;
	};

