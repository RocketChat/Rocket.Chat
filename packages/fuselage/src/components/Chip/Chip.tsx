// end of generated

const defaultRenderThumb = ({ url }: { url: string }) => (
	<div className='rcx-box rcx-box--full rcx-avatar'>
		<Avatar size='x20' url={url} />
	</div>
);
const defaultRenderDismissSymbol = () => <Icon name='cross' size='x16' />;

const Chip = (props: ChipProps) => {
	const {
		children,
		className,
		thumbUrl,
		onClick,
		onMouseDown,
		renderThumb = defaultRenderThumb,
		renderDismissSymbol = defaultRenderDismissSymbol,
		small,
		label,
		disabled,
	} = props;
	const dismissable = Boolean(onClick || onMouseDown);
	const isDisabled = disabled ?? !dismissable;
	const attributes = frameProps(props);

	return (
		<ChipFrame
			look={isDisabled ? 'disabled' : 'enabled'}
			sizing={small ? 'small' : 'regular'}
			label={Boolean(label)}
			className={prependClassName(className, `rcx-box rcx-chip${small ? ' rcx-chip--small' : ''}${label ? ' rcx-chip--label' : ''}`)}
			type='button'
			disabled={isDisabled}
			// Tamagui's runtime adds it to a disabled frame, so the compiled element states it too
			aria-disabled={attributes['aria-disabled'] ?? (isDisabled || undefined)}
			name={attributes.name}
			value={attributes.value}
			ref={attributes.ref}
			id={attributes.id}
			title={attributes.title}
			role={attributes.role}
			tabIndex={attributes.tabIndex}
			aria-label={attributes['aria-label']}
			aria-labelledby={attributes['aria-labelledby']}
			aria-describedby={attributes['aria-describedby']}
			aria-controls={attributes['aria-controls']}
			aria-current={attributes['aria-current']}
			aria-expanded={attributes['aria-expanded']}
			aria-haspopup={attributes['aria-haspopup']}
			aria-hidden={attributes['aria-hidden']}
			aria-live={attributes['aria-live']}
			aria-pressed={attributes['aria-pressed']}
			aria-selected={attributes['aria-selected']}
			data-qa={attributes['data-qa']}
			data-qa-id={attributes['data-qa-id']}
			data-qa-type={attributes['data-qa-type']}
			data-testid={attributes['data-testid']}
			onClick={attributes.onClick}
			onContextMenu={attributes.onContextMenu}
			onDragStart={attributes.onDragStart}
			onKeyDown={attributes.onKeyDown}
			onKeyUp={attributes.onKeyUp}
			onMouseDown={attributes.onMouseDown}
			onMouseEnter={attributes.onMouseEnter}
			onMouseLeave={attributes.onMouseLeave}
			onMouseUp={attributes.onMouseUp}
			onPointerDown={attributes.onPointerDown}
			onPointerEnter={attributes.onPointerEnter}
			onPointerLeave={attributes.onPointerLeave}
			onPointerUp={attributes.onPointerUp}
			onTouchCancel={attributes.onTouchCancel}
			onTouchEnd={attributes.onTouchEnd}
			onTouchMove={attributes.onTouchMove}
			onTouchStart={attributes.onTouchStart}
			onFocus={attributes.onFocus}
			onBlur={attributes.onBlur}
		>
			{thumbUrl && renderThumb?.({ url: thumbUrl })}
			{children && <span className='rcx-box rcx-chip__text'>{children}</span>}
			{dismissable && renderDismissSymbol?.()}
		</ChipFrame>
	);
};

export default Chip;
