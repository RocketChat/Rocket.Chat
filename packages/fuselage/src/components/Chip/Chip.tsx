// Declared where they render: zero-runtime only erases a `styled()` whose every use is in its own module
const ChipFrame = styled(View, {
	render: 'button',
	...chipFrame,
	variants: {
		// the disabled colors win over every state
		look: {
			enabled: { ...chipEnabled },
			disabled: { ...chipDisabled },
		},
		sizing: {
			regular: { ...chipRegular },
			small: { ...chipSmall },
		},
		label: {
			true: { textTransform: 'uppercase' },
			false: {},
		},
	},
});

const ChipText = styled(Text, {
	render: 'span',
	...chipText,
});

const ChipThumb = styled(View, { ...chipThumb });

const defaultRenderThumb = ({ url }: { url: string }) => (
	<ChipThumb className='rcx-box rcx-box--full rcx-avatar'>
		<Avatar size='x20' url={url} />
	</ChipThumb>
);
const defaultRenderDismissSymbol = () => <Icon name='cross' size='x16' />;

const Chip = (props: ChipProps) => {
	const {
		children,
		className,
		thumbUrl,
		onClick,
		onMouseDown,
		renderThumb = defaultRenderThumb,
		renderDismissSymbol = defaultRenderDismissSymbol,
		small,
		label,
		disabled,
	} = props;
	const dismissable = Boolean(onClick || onMouseDown);
	const isDisabled = disabled ?? !dismissable;

	return (
		<ChipFrame
			look={isDisabled ? 'disabled' : 'enabled'}
			sizing={small ? 'small' : 'regular'}
			label={Boolean(label)}
			className={prependClassName(className, `rcx-box rcx-chip${small ? ' rcx-chip--small' : ''}${label ? ' rcx-chip--label' : ''}`)}
			render={
				<button
					{...ariaAndDataAttributes(props)}
					{...pickWebPressHandlers(props)}
					type='button'
					disabled={isDisabled}
					name={props.name}
					value={props.value}
					ref={props.ref}
					id={props.id}
					title={props.title}
					role={props.role}
					tabIndex={props.tabIndex}
				/>
			}
		>
			{thumbUrl && renderThumb?.({ url: thumbUrl })}
			{children && <ChipText className='rcx-box rcx-chip__text'>{children}</ChipText>}
			{dismissable && renderDismissSymbol?.()}
		</ChipFrame>
	);
};

export default Chip;
