const WRAPPER_LIMIT_SIZE = 420;

const defaultIcons = {
	info: 'info-circled',
	success: 'checkmark-circled',
	warning: 'warning',
	danger: 'ban',
} as const;

/**
 * The `Callout` is used to get the user's attention explaining something important in the content of the current page.
 */
const Callout = (props: CalloutProps) => {
	const { type, title, children, icon, className, actions } = props;
	const { ref, borderBoxSize } = useResizeObserver<WebSectionElement>();
	const mergedRef = useMergedRefs(ref, props.ref);
	const isLarge = Boolean(borderBoxSize.inlineSize && borderBoxSize.inlineSize >= WRAPPER_LIMIT_SIZE);

	return (
		<CalloutFrame
			tone={type ?? 'default'}
			className={prependClassName(className, `rcx-box rcx-box--full rcx-callout${type ? ` rcx-callout--${type}` : ''}`)}
			{...pickFramePressHandlers(props)}
			render={
				<section {...ariaAndDataAttributes(props)} {...pickWebPressHandlers(props)} ref={mergedRef} id={props.id} role={props.role} />
			}
		>
			<Icon
				className='rcx-callout__icon'
				name={icon || (type && defaultIcons[type]) || 'info-circled'}
				size='x20'
				color={type && `status-font-on-${type}`}
			/>
			<CalloutBody
				layout={isLarge ? 'inline' : 'stacked'}
				className={`rcx-box rcx-box--full rcx-callout__wrapper${isLarge ? ' rcx-callout__wrapper--large' : ''}`}
			>
				<CalloutText className='rcx-box rcx-box--full rcx-callout__wrapper-content'>
					{title && <CalloutTitle className='rcx-box rcx-box--full rcx-callout__title'>{title}</CalloutTitle>}
					{children && (
						<CalloutContent belowTitle={Boolean(title)} className='rcx-box rcx-box--full rcx-callout__content'>
							{children}
						</CalloutContent>
					)}
				</CalloutText>
				{actions && (
					<CalloutActions belowText={!isLarge} className='rcx-box rcx-box--full rcx-callout__actions'>
						{actions}
					</CalloutActions>
				)}
			</CalloutBody>
		</CalloutFrame>
	);
};

export default Callout;
