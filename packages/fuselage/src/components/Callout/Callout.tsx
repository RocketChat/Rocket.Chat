/**
 * The `Callout` is used to get the user's attention explaining something important in the content of the current page.
 */
const Callout = (props: CalloutProps) => {
	const { type, title, children, icon, className, actions } = props;
	const { ref, borderBoxSize } = useResizeObserver<HTMLElement>();
	const isLarge = Boolean(borderBoxSize.inlineSize && borderBoxSize.inlineSize >= WRAPPER_LIMIT_SIZE);

	const defaultIcon =
		(type === 'info' && 'info-circled') ||
		(type === 'success' && 'checkmark-circled') ||
		(type === 'warning' && 'warning') ||
		(type === 'danger' && 'ban') ||
		'info-circled';

	return (
		<CalloutFrame
			render={<section {...ariaAndDataAttributes(props)} ref={ref} id={props.id} role={props.role} />}
			type={type}
			className={cx('rcx-box rcx-box--full', 'rcx-callout', type && `rcx-callout--${type}`, className)}
		>
			<Icon className='rcx-callout__icon' name={icon || defaultIcon} size='x20' />
			<CalloutWrapper
				render={<div />}
				large={isLarge}
				className={cx('rcx-box rcx-box--full', isLarge ? 'rcx-callout__wrapper--large rcx-callout__wrapper' : 'rcx-callout__wrapper')}
			>
				<CalloutBody render={<div />} className={cx('rcx-box rcx-box--full', 'rcx-callout__wrapper-content')}>
					{title && (
						<CalloutTitle render={<div />} className={cx('rcx-box rcx-box--full', 'rcx-callout__title')}>
							{title}
						</CalloutTitle>
					)}
					{children && (
						<CalloutContent render={<div />} afterTitle={Boolean(title)} className={cx('rcx-box rcx-box--full', 'rcx-callout__content')}>
							{children}
						</CalloutContent>
					)}
				</CalloutBody>
				{actions && (
					<CalloutActions render={<div />} large={isLarge} className={cx('rcx-box rcx-box--full', 'rcx-callout__actions')}>
						{actions}
					</CalloutActions>
				)}
			</CalloutWrapper>
		</CalloutFrame>
	);
};

export default Callout;
