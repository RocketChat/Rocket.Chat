const WRAPPER_LIMIT_SIZE = 420;

const defaultIcons = {
	info: 'info-circled',
	success: 'checkmark-circled',
	warning: 'warning',
	danger: 'ban',
} as const;

/**
 * The `Callout` is used to get the user's attention explaining something important in the content of the current page.
 */
const Callout = (props: CalloutProps) => {
	const { type, title, children, icon, className, actions, centered } = props;
	const { ref, borderBoxSize } = useResizeObserver<SectionElement>();
	const mergedRef = useMergedRefs(ref, props.ref);
	const isLarge = Boolean(borderBoxSize.inlineSize && borderBoxSize.inlineSize >= WRAPPER_LIMIT_SIZE);

	return (
		<CalloutFrame
			tone={type ?? 'default'}
			centered={Boolean(centered)}
			className={prependClassName(className, `rcx-box rcx-box--full rcx-callout${type ? ` rcx-callout--${type}` : ''}`)}
			render={<section {...ariaAndDataAttributes(props)} ref={mergedRef} id={props.id} role={props.role} />}
		>
			<Icon
				className={`rcx-callout__icon${type ? ` rcx-callout__icon--${type}` : ''}`}
				name={icon || (type && defaultIcons[type]) || 'info-circled'}
				size='x20'
			/>
			<CalloutBody
				layout={isLarge ? 'inline' : 'stacked'}
				className={`rcx-box rcx-box--full ${isLarge ? 'rcx-callout__wrapper--large ' : ''}rcx-callout__wrapper`}
			>
				<CalloutText className='rcx-box rcx-box--full rcx-callout__wrapper-content'>
					{title && <CalloutTitle className='rcx-box rcx-box--full rcx-callout__title'>{title}</CalloutTitle>}
					{children && <CalloutContent className='rcx-box rcx-box--full rcx-callout__content'>{children}</CalloutContent>}
				</CalloutText>
				{actions && <CalloutActions className='rcx-box rcx-box--full rcx-callout__actions'>{actions}</CalloutActions>}
			</CalloutBody>
		</CalloutFrame>
	);
};

export default Callout;
