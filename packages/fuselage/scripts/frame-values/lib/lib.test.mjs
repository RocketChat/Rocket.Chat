test('markers name the section when there are several', () => {
	assert.deepEqual(
		markers(false, undefined).map((line) => line.split(' by ')[0]),
		['// generated', '// end of generated'],
	);
	assert.equal(markers(true, 'ripple')[0].startsWith('/* generated ripple '), true);
	assert.equal(markers(true, 'ripple')[1], '/* end of generated ripple */');
});

test('literal quotes keys, nests and skips undefined', () => {
	assert.equal(literal({ 'a-b': 1, 'c': { d: 'x', e: undefined } }), '{\n\t"a-b": 1,\n\t"c": {\n\t\t"d": "x",\n\t},\n}');
});

test('offScale refuses a length the spacing scale has, and accepts one it has not', () => {
	assert.throws(() => offScale(4), /use spacing\('x4'\)/);
	assert.throws(() => offScale(-8), /use spacing\('-x8'\)/);
	assert.equal(offScale(-1), '-1px');
	assert.equal(offScale(3), '3px');
});

test('a text frame restates only the View defaults it does not state', () => {
	const defaults = textFrameDefaults({ display: 'inline-flex', minWidth: 'auto' });

	assert.equal(Object.hasOwn(defaults, 'display'), false);
	assert.equal(Object.hasOwn(defaults, 'minWidth'), false);
	assert.equal(defaults.flexDirection, 'column');
	assert.equal(defaults.render, 'div');
});

test('a raw px or rem length in a generator module is a problem, a token call is not', () => {
	assert.equal(moduleProblems('m.mts', "const a = { padding: spacing('x8'), gap: offScale(3) };").length, 0);
	assert.equal(moduleProblems('m.mts', "const a = { paddingInline: '12px' };").length, 1);
	assert.equal(moduleProblems('m.mts', 'const a = { fontSize: 14 };').length, 1);
	assert.equal(moduleProblems('m.mts', "const a = { margin: `calc(${size('x8')} - 2rem)` };").length, 1);
});

test('spacing() on a step the scale has not is a problem', () => {
	assert.equal(moduleProblems('m.mts', "spacing('x4')").length, 0);
	assert.equal(moduleProblems('m.mts', "spacing('x3')").length, 1);
});

test('hand-written CSS outside the generated section may not set a raw spacing length', () => {
	const css = `.a {
	padding: 8px;
}
/* generated by x, do not edit */
.b {
	padding: 4px;
}
/* end of generated */
.c {
	width: 10px;
}`;

	const problems = stylesheetProblems('a.styles.css', css, new Set());

	assert.equal(problems.length, 1);
	assert.match(problems[0], /a\.styles\.css:2: raw length in `padding: 8px`/);
});

test('a custom property that feeds a spacing property counts as one', () => {
	const properties = spacingProperties(["{ padding: 'var(--rcx-thing-gap, 4px)' }"]);

	assert.equal(properties.has('--rcx-thing-gap'), true);
	assert.equal(stylesheetProblems('a.css', '.a {\n\t--rcx-thing-gap: 6px;\n}', properties).length, 1);
	assert.equal(stylesheetProblems('a.css', '.a {\n\t--rcx-other: 6px;\n}', properties).length, 0);
});

test('a transform that starts with none and goes on is a problem', () => {
	assert.equal(transformProblems('f.tsx', '{ transform: { "default": "none", "press": "translateY(1px)" } }').length, 0);
	assert.equal(transformProblems('f.tsx', '{ transform: "translate(1px) translateY(1px)" }').length, 0);
	assert.equal(transformProblems('f.tsx', '{ transform: { "press": "none translateY(1px)" } }').length, 1);
	assert.equal(transformProblems('f.tsx', '{ transform: "none translateY(1px)" }').length, 1);
});

