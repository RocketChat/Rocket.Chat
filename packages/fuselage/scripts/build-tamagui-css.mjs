// Writes the stylesheet Tamagui would otherwise inject at runtime (base `.is_View`/`.is_Text` rules and the token
// custom properties) to `src/styles/tamagui-base.css`, so `fuselage.css` carries it and no provider has to inject it.
// Usage: node scripts/build-tamagui-css.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';

import { build } from 'esbuild';

const root = resolve(import.meta.dirname, '..');
const target = resolve(root, 'src/styles/tamagui-base.css');

const result = await build({
	entryPoints: [resolve(root, 'src/tamagui.config.ts')],
	bundle: true,
	write: false,
	platform: 'node',
	format: 'cjs',
	logLevel: 'silent',
	// The same settings the published bundle pins in `vite.config.mts`
	define: {
		'process.env.NODE_ENV': '"production"',
		'process.env.TAMAGUI_CSS_LAYER': '"fuselage"',
	},
});

const module = { exports: {} };
new Function('require', 'module', 'exports', result.outputFiles[0].text)(createRequire(import.meta.url), module, module.exports);
// Fuselage frames are all `View` or `Text`, so the rules for Tamagui's DOM primitives (`.is_DOM`) never match but still
// cost every style recalc
const baseCSS = module.exports.tamaguiConfig
	.getCSS()
	.replace(/:where\([^)]*\.is_DOM[^)]*\)\{[^}]*\}/g, '')
	.replace(', .t_unmounted .is_DOM', '');
const css = `/* Generated by scripts/build-tamagui-css.mjs from src/tamagui.config.ts; do not edit */\n${baseCSS}\n`;

if (process.argv.includes('--check')) {
	if (readFileSync(target, 'utf8') !== css) {
		console.error('src/styles/tamagui-base.css is stale: run node scripts/build-tamagui-css.mjs');
		process.exit(1);
	}
} else {
	writeFileSync(target, css);
	console.log(`wrote ${target} (${css.length} chars)`);
}
