import assert from 'node:assert/strict';
import { cpSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { test } from 'node:test';
import { pathToFileURL } from 'node:url';

import { generatedSections, undeclaredThemeKeys, unknownConditions, unresolvedTokens } from './zero-stylesheet.mjs';

test('the check runs where no package is installed, as in the production install a build runs under', async () => {
	const root = mkdtempSync(join(tmpdir(), 'zero-stylesheet-'));
	try {
		for (const file of ['scripts/verify/zero-stylesheet.mjs', 'src/tamagui.tokens.ts', 'src/tamagui.media.ts']) {
			cpSync(join(import.meta.dirname, '../..', file), join(root, file));
		}
		const { zeroStylesheetErrors } = await import(pathToFileURL(join(root, 'scripts/verify/zero-stylesheet.mjs')).href);

		assert.match((await zeroStylesheetErrors('.a{color:$typo}'))[0], /\$typo$/);
	} finally {
		rmSync(root, { recursive: true });
	}
});

test('a stylesheet whose tokens all resolved has none', () => {
	assert.deepEqual(
		unresolvedTokens(':root .t_light{--rcx-font-default:var(--t3)}._col-rcx-font-default{color:var(--rcx-font-default)}'),
		[],
	);
});

test('a token or theme key the config does not have is left as written', () => {
	const css =
		'._col-doesNotExist{color:$doesNotExist}._bg-rcx-typo{background-color:$rcx-typo}._p-space{padding:$space.x5}._zi-drag{z-index:$zIndex.drag}';

	assert.deepEqual(unresolvedTokens(css), ['$doesNotExist', '$rcx-typo', '$space.x5', '$zIndex.drag']);
});

test('each one is reported once', () => {
	assert.deepEqual(unresolvedTokens('.a{color:$typo}.b:hover{color:$typo}'), ['$typo']);
});

test('an ends-with attribute selector is not a token', () => {
	assert.deepEqual(unresolvedTokens('[class$="-icon"]{display:none}a[href$=".pdf"]{color:red}'), []);
});
test('a theme key declared under its own name in every theme is not reported', () => {
	const css =
		':root .t_light, :root .t_dark .t_light{--rcx-a:var(--t0);--rcx-b:var(--t1);}:root .t_dark,:root .t_light .t_dark{--rcx-a:var(--t2);--rcx-b:var(--t3)}';

	assert.deepEqual(undeclaredThemeKeys(css, { light: { 'rcx-a': '', 'rcx-b': '' }, dark: { 'rcx-a': '', 'rcx-b': '' } }), []);
});

test('a theme key declared under a shortened name, or in another theme only, is reported', () => {
	const css = ':root .t_light{--rcx-a:var(--t0);--rcx-long-de97204770:var(--t1)}:root .t_dark{--rcx-long-default:var(--t1)}';
	const keys = { 'rcx-a': '', 'rcx-long-default': '' };

	assert.deepEqual(undeclaredThemeKeys(css, { light: keys, dark: keys }), ['light: rcx-long-default', 'dark: rcx-a']);
});

test('a variable a declaration reads is not one it declares', () => {
	assert.deepEqual(undeclaredThemeKeys(':root .t_light{--rcx-b:var(--rcx-a)}', { light: { 'rcx-a': '' } }), ['light: rcx-a']);
});

const media = { pointerCoarse: {}, narrow: '' };
const section = (values) => `const frame = ${values} as const;`;

test('a state, a group state, a media key and a media key measured on a named group are conditions', () => {
	const values = `{
		display: 'flex',
		paddingBlock: { default: 4, pointerCoarse: 8 },
		paddingInline: { 'default': 24, '@narrow/rcx-item-group': 16 },
		opacity: { 'group-hover/item': 1, 'group-focus-within': 1, 'focus-visible': 1, 'press': 1 },
	}`;

	assert.deepEqual(unknownConditions(section(values), media), []);
});

test('a condition the config does not have is reported once, where the stylesheet would only lack its value', () => {
	const values = `{
		display: 'flex',
		paddingBlock: { default: 4, pointerCoars: 8 },
		gap: { pointerCoars: 8 },
		paddingInline: { 'default': 24, '@wide/rcx-item-group': 16, 'group-hovered/item': 8 },
	}`;

	assert.deepEqual(unknownConditions(section(values), media), ['pointerCoars', '@wide/rcx-item-group', 'group-hovered/item']);
});

test('a value of a variant is checked as one of the frame is, and the names of the variant are not conditions', () => {
	const values = `{
		lg: { paddingInline: { 'default': 24, '@narow/rcx-item-group': 16 } },
		md: { paddingInline: 12, content: 'a: {b}, c' },
		hover: { backgroundColor: { hover: '$rcx-surface-hover', hoverNon: 'transparent' } },
	}`;

	assert.deepEqual(unknownConditions(section(values), media), ['@narow/rcx-item-group', 'hoverNon']);
});

test('only the generated sections of the frame modules are read', () => {
	const root = mkdtempSync(join(tmpdir(), 'zero-stylesheet-'));
	try {
		mkdirSync(join(root, 'components/Probe'), { recursive: true });
		writeFileSync(
			join(root, 'components/Probe/Probe.tsx'),
			[
				'const outside = { gap: { never: 1 } };',
				'// generated by scripts/generate-frame-values.mts from @rocket.chat/fuselage-tokens, do not edit',
				'const frame = { display: "flex", gap: { default: 4, pointerCoars: 8 } } as const;',
				'// end of generated',
			].join('\n'),
		);
		writeFileSync(join(root, 'components/Probe/Probe.ts'), 'const frame = { display: "flex", gap: { other: 8 } };');

		assert.deepEqual(unknownConditions(generatedSections(root), media), ['pointerCoars']);
	} finally {
		rmSync(root, { recursive: true });
	}
});

test('every frame value in the package names a condition the config has', async () => {
	const { media: configured } = await import('../../src/tamagui.media.ts');

	assert.deepEqual(unknownConditions(generatedSections(join(import.meta.dirname, '../../src')), configured), []);
});
