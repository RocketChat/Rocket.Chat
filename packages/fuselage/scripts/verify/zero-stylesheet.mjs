// Usage: node scripts/verify/zero-stylesheet.mjs <tamagui-zero.css>
// The zero-runtime compiler reports no bail for a value a frame cannot get: a token or theme key the config does not
// have is written as it was (`color:$typo`), and a theme key declared under another name than the one a frame reads has
// no value under a theme class. A condition the config does not have, such as a misspelled media key, leaves no trace in
// the stylesheet: the value under it is dropped. A zero build calls `zeroStylesheetErrors` on its stylesheet and fails
// on any of the three.
import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

/** The `$name` references left in a stylesheet, each once. `[class$="x"]` is a selector, not a reference. */
export const unresolvedTokens = (css) => [...new Set(css.match(/\$[A-Za-z][\w.-]*/g) ?? [])];

/**
 * The theme keys a stylesheet does not declare as `--<key>`, the name a compiled frame reads, in the rule of the
 * theme's `t_*` class. `themes` is the config's; each result is `<theme>: <key>`.
 */
export const undeclaredThemeKeys = (css, themes) => {
	const rules = [...css.matchAll(/([^{}]+)\{([^{}]*)\}/g)];

	return Object.entries(themes).flatMap(([theme, keys]) => {
		const declared = new Set(
			rules
				.filter(([, selectors]) => selectors.split(',').some((selector) => selector.trim().endsWith(`.t_${theme}`)))
				.flatMap(([, , block]) => [...block.matchAll(/(--[\w-]+)\s*:/g)].map(([, name]) => name)),
		);

		return Object.keys(keys)
			.filter((key) => !declared.has(`--${key}`))
			.map((key) => `${theme}: ${key}`);
	});
};

const STATES = ['hover', 'press', 'focus', 'focus-visible', 'focus-within', 'disabled'];

const isCondition = (part, media) => {
	if (part === 'default' || STATES.includes(part) || Object.hasOwn(media, part)) {
		return true;
	}
	const group = /^group-([a-z-]+?)(?:\/[\w-]+)?$/.exec(part);
	if (group) {
		return STATES.includes(group[1]);
	}
	const container = /^@(\w+)(?:\/[\w-]+)?$/.exec(part);
	return Boolean(container && Object.hasOwn(media, container[1]));
};

const TOKEN = /'(?:[^'\\]|\\.)*'|"(?:[^"\\]|\\.)*"|`(?:[^`\\]|\\.)*`|[{}:,]|[^\s{}:,'"`]+/g;

// The object literals of a generated section as trees: an entry is a key and, for a nested object, its node.
const objectTrees = (text) => {
	const roots = [];
	const stack = [];
	let key;
	let previous;

	for (const [token] of text.matchAll(TOKEN)) {
		if (token === '{') {
			const node = { entries: [] };
			if (stack.length) {
				stack.at(-1).entries.push([key, node]);
			} else {
				roots.push(node);
			}
			stack.push(node);
			key = undefined;
		} else if (token === '}') {
			stack.pop();
			key = undefined;
		} else if (token === ':' && stack.length && key === undefined) {
			key = previous.replace(/^['"]|['"]$/g, '');
		} else if (token === ',') {
			key = undefined;
		} else if (stack.length && key !== undefined && previous === ':') {
			stack.at(-1).entries.push([key, null]);
		}
		previous = token;
	}

	return roots;
};

/**
 * The conditions a generated section names that the Tamagui config does not have, each once. A value that depends on a
 * condition is an object inside a style, or an object with a plain value under a condition; every key of one has to be
 * `default`, a state, a state of a group, a media key or a media key measured on a named group.
 */
export const unknownConditions = (text, media) => {
	const unknown = new Set();

	const visit = (node, insideStyle) => {
		const isStyle = node.entries.some(([, child]) => child === null);
		if (insideStyle || node.entries.some(([name, child]) => child === null && isCondition(name, media))) {
			for (const [name] of node.entries) {
				if (!name.split(':').every((part) => isCondition(part, media))) {
					unknown.add(name);
				}
			}
			return;
		}
		for (const [, child] of node.entries) {
			if (child) {
				visit(child, isStyle);
			}
		}
	};

	objectTrees(text).forEach((root) => visit(root, false));
	return [...unknown];
};

const GENERATED = /\/\/ generated by scripts\/generate-frame-values\.mts[^\n]*\n([\s\S]*?)\/\/ end of generated/g;

/** The generated sections of every frame module under a directory, joined. */
export const generatedSections = (directory) =>
	readdirSync(directory, { recursive: true, encoding: 'utf8' })
		.filter((file) => file.endsWith('.tsx'))
		.flatMap((file) => [...readFileSync(join(directory, file), 'utf8').matchAll(GENERATED)].map(([, section]) => section))
		.join('\n');

/** Why a zero stylesheet cannot ship with the Tamagui config as it is, one message per kind of problem. */
export const zeroStylesheetErrors = async (css) => {
	// Node strips the types itself: a production install, which a build runs under, has no TypeScript loader.
	const { themes } = await import('../../src/tamagui.tokens.ts');
	const { media } = await import('../../src/tamagui.media.ts');
	const unresolved = unresolvedTokens(css);
	const undeclared = undeclaredThemeKeys(css, themes);
	const conditions = unknownConditions(generatedSections(join(import.meta.dirname, '../../src')), media);

	return [
		unresolved.length && `Tokens the Tamagui config does not have: ${unresolved.join(', ')}`,
		undeclared.length && `Theme keys a theme class does not declare under the name a frame reads: ${undeclared.join(', ')}`,
		conditions.length && `Conditions of a frame value the Tamagui config does not have: ${conditions.join(', ')}`,
	].filter(Boolean);
};

if (import.meta.filename === process.argv[1]) {
	const errors = await zeroStylesheetErrors(readFileSync(process.argv[2], 'utf8'));
	if (errors.length) {
		console.error(errors.join('\n'));
		process.exit(1);
	}
	console.log('Every token resolved, every theme key is declared and every condition of a frame value exists.');
}
