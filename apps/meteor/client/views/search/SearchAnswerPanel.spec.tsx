import { mockAppRoot } from '@rocket.chat/mock-providers';
import { render, screen } from '@testing-library/react';
import userEvent from '@testing-library/user-event';

import SearchAnswerPanel, { type SearchAnswerPanelProps } from './SearchAnswerPanel';

import '@testing-library/jest-dom';

const defaultProps: SearchAnswerPanelProps = {
	isLoading: false,
	disabled: false,
	emptyReason: 'No sources are available.',
	onRetry: jest.fn(),
};

const renderPanel = (props: Partial<SearchAnswerPanelProps> = {}, permissions: string[] = []) => {
	const root = mockAppRoot().withTranslations('en', 'core', {
		Search_AI_answer: 'AI overview',
		Search_AI_answer_ready: 'An AI overview will appear here.',
		Search_AI_answer_provider: 'Generated with {{provider}} · {{model}}',
		Search_AI_answer_error: 'Check the LLM provider configuration.',
		Search_AI_answer_error_provider_request_failed: 'The LLM provider did not return an answer.',
		Search_AI_answer_error_unavailable: 'The answer could not be generated.',
		Search_AI_overview_info: 'Generated by AI from the messages below',
		Read_more: 'Read more',
		Read_less: 'Read less',
		Try_again: 'Try again',
		Loading: 'Loading',
	});
	permissions.forEach((permission) => root.withPermission(permission));

	return render(<SearchAnswerPanel {...defaultProps} {...props} />, { wrapper: root.build() });
};

const mockContentHeight = (scrollHeight: number, clientHeight: number) => {
	jest.spyOn(HTMLElement.prototype, 'scrollHeight', 'get').mockReturnValue(scrollHeight);
	jest.spyOn(HTMLElement.prototype, 'clientHeight', 'get').mockReturnValue(clientHeight);
};

beforeEach(() => {
	global.ResizeObserver = jest.fn().mockImplementation((callback: ResizeObserverCallback) => ({
		observe: jest.fn(() => callback([], {} as ResizeObserver)),
		unobserve: jest.fn(),
		disconnect: jest.fn(),
	}));
});

afterEach(() => {
	jest.restoreAllMocks();
});

describe('SearchAnswerPanel', () => {
	it('does not offer to generate or regenerate an answer', () => {
		renderPanel({ answer: 'Deployment completed.' });

		expect(screen.queryByRole('button', { name: /generate/i })).not.toBeInTheDocument();
	});

	it('renders the disabled reason when an answer cannot be generated', () => {
		renderPanel({ disabled: true, emptyReason: 'No related messages were found.' });

		expect(screen.getByText('No related messages were found.')).toBeInTheDocument();
	});

	it('renders a loading state', () => {
		renderPanel({ isLoading: true });

		expect(screen.getByLabelText('Loading')).toHaveAttribute('aria-busy', 'true');
	});

	it('renders markdown and describes the provider on the info icon', () => {
		renderPanel({
			answer: '**Deployment** completed successfully.',
			provider: { name: 'OpenAI compatible', model: 'example-model' },
		});

		expect(screen.getByText('Deployment').tagName).toBe('STRONG');
		expect(screen.getByTitle('Generated with OpenAI compatible · example-model')).toBeInTheDocument();
	});

	it('falls back to a generic description on the info icon without a provider', () => {
		renderPanel();

		expect(screen.getByTitle('Generated by AI from the messages below')).toBeInTheDocument();
	});

	it('renders a generic generation error with a way to try again', async () => {
		const user = userEvent.setup();
		const onRetry = jest.fn();
		renderPanel({ error: { errorType: 'error-ai-provider-request-failed' }, onRetry });

		expect(screen.getByText('The answer could not be generated.')).toBeInTheDocument();
		expect(screen.queryByText('An AI overview will appear here.')).not.toBeInTheDocument();

		await user.click(screen.getByRole('button', { name: 'Try again' }));
		expect(onRetry).toHaveBeenCalledTimes(1);
	});

	it('hides Read more when the answer fits in the preview', () => {
		mockContentHeight(40, 40);
		renderPanel({ answer: 'Short answer.' });

		expect(screen.queryByRole('button', { name: 'Read more' })).not.toBeInTheDocument();
	});

	it('expands and collapses an answer longer than the preview', async () => {
		const user = userEvent.setup();
		mockContentHeight(200, 40);
		renderPanel({ answer: 'A long answer.' });

		const readMore = screen.getByRole('button', { name: 'Read more' });
		expect(readMore).toHaveAttribute('aria-expanded', 'false');

		await user.click(readMore);
		const readLess = screen.getByRole('button', { name: 'Read less' });
		expect(readLess).toHaveAttribute('aria-expanded', 'true');

		await user.click(readLess);
		expect(screen.getByRole('button', { name: 'Read more' })).toHaveAttribute('aria-expanded', 'false');
	});

	it('tells admins why the provider failed', () => {
		renderPanel({ error: { errorType: 'error-ai-provider-request-failed' } }, ['view-privileged-setting']);

		expect(screen.getByText('The LLM provider did not return an answer.')).toBeInTheDocument();
	});

	it('points admins at the provider configuration for unrecognized errors', () => {
		renderPanel({ error: new Error('request failed') }, ['view-privileged-setting']);

		expect(screen.getByText('Check the LLM provider configuration.')).toBeInTheDocument();
	});
});
